"""Structural guards for email behavioral metadata: MessageKind, header facets,
and disposition-notification request. Issue #137.
"""

from __future__ import annotations

from pathlib import Path

from rdflib import OWL, RDF, RDFS, XSD, Graph, Literal, URIRef
from rdflib.query import ResultRow

from gmeow_tools.graph import load_merged_graph

GMEOW = "https://blackcatinformatics.ca/gmeow/"


def _graph() -> Graph:
    """Load the merged ontology graph without imports."""
    return load_merged_graph(include_imports=False)


def _fixture_path() -> str:
    """Return the path to the email coverage fixture."""
    return str(Path(__file__).parent / "fixtures" / "coverage" / "email.ttl")


def test_message_kind_class_exists() -> None:
    graph = _graph()
    node = URIRef(GMEOW + "MessageKind")
    assert (node, RDF.type, OWL.Class) in graph
    assert (
        node,
        RDFS.subClassOf,
        URIRef("http://purl.org/nemo/gufo#QualityValue"),
    ) in graph


def test_message_kind_individuals_exist() -> None:
    graph = _graph()
    for kind in (
        "messageKindDeliveryStatusNotification",
        "messageKindBounce",
        "messageKindFeedbackReport",
        "messageKindReadReceipt",
        "messageKindAutoGenerated",
    ):
        node = URIRef(GMEOW + kind)
        assert (node, RDF.type, URIRef(GMEOW + "MessageKind")) in graph, (
            f"{kind} missing"
        )


def test_has_message_kind_property() -> None:
    graph = _graph()
    node = URIRef(GMEOW + "hasMessageKind")
    assert (node, RDF.type, OWL.ObjectProperty) in graph
    assert (node, RDFS.domain, URIRef(GMEOW + "Message")) in graph
    assert (node, RDFS.range, URIRef(GMEOW + "MessageKind")) in graph
    # Must NOT be functional — categories can overlap (Principle 9)
    assert (node, RDF.type, OWL.FunctionalProperty) not in graph


