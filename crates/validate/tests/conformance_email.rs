//! Conformance twins migrated from the email cluster:
//! `tests/test_email_behavioral.py`, `tests/test_email_participant.py`, and
//! `tests/test_email_versions.py`.
//!
//! Covers behavioral MessageKind overlap + header facets, the
//! `MessageParticipant` relator (occurrence-scoped display names) + EmailAddress
//! decomposition, and the cross-cutting `VersionMembership` roles / patch-diff /
//! collision-fingerprint facets — plus the non-RDF regression guard that the
//! generated LinkML projection compiles the non-functional `resent-*` datatype
//! properties to `multivalued: true` slots.
//!
//! The RDF twins load `tests/fixtures/coverage/email.ttl` (the merged-graph
//! sweeps the Python originals ran reduce to fixture-scoped triple/SELECT checks
//! here). The LinkML twin reads `generated/schemas/gmeow.linkml.yaml` and
//! navigates the top-level `slots` map — the projection surface, not SPARQL.

mod conformance_support;
use conformance_support::*;
use purrdf::TermValue;

const GMEOW: &str = "https://blackcatinformatics.ca/gmeow/";
const EX_MAIL: &str = "https://example.org/mail/";
const XSD_BOOLEAN: &str = "http://www.w3.org/2001/XMLSchema#boolean";

fn gm(local: &str) -> String {
    format!("{GMEOW}{local}")
}

fn ex_mail(local: &str) -> String {
    format!("{EX_MAIL}{local}")
}

/// The email coverage fixture, parsed into a fixture-only store. The originals
/// parsed it into the merged ontology graph, but every asserted triple/solution
/// lives in the fixture itself, so a fixture-scoped store is faithful and lighter.
fn email_store() -> GraphStore {
    GraphStore::parse_ttl_file(&repo_root().join("tests/fixtures/coverage/email.ttl"))
}

