//! `gmn-dialect-paths <tree-root>` — list every GMN-dialect artifact of a materialized
//! tree, one repo-relative path per line, in canonical order.
//!
//! The ONE reason this binary exists is that `make maint-medium-model-facing-diff`
//! compares two trees produced by two different commits, and it must classify both with
//! the SAME predicate. Re-spelling
//! [`gmeow_pipeline::gmn_dialect::is_gmn_dialect_path`] as a shell `find` expression in
//! the Makefile would be a second source of truth for what "model-facing" means — the
//! exact drift the derived path set exists to prevent — and it would drift silently,
//! because a `find` that matched nothing looks the same as a tree with nothing in it.
//!
//! It READS a tree and classifies its paths. It never builds anything, so pointing it at
//! the merge-base worktree is not "overlaying this branch's sources onto the merge base":
//! the base tree is regenerated entirely by the base's own toolchain, and this only
//! decides which of the files it produced are in the comparison.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let Some(root) = args.next() else {
        eprintln!(
            "usage: gmn-dialect-paths <tree-root>\n\n\
             Prints every repo-relative path under <tree-root>/generated/ that the declared\n\
             GMN-dialect predicate selects, one per line, sorted. Exits non-zero when the\n\
             tree carries no such path — an empty list is a materialization failure, never\n\
             a smaller comparison."
        );
        return ExitCode::from(2);
    };
    let root = PathBuf::from(root);
    // GENERATED-READ-OK: this is an AUDIT lane, not a produce stage. It is the classifier
    // `make maint-medium-model-facing-diff` points at two ALREADY-MATERIALIZED checkouts
    // (this branch's and the merge base's, each regenerated by its own toolchain) to decide
    // which of their files are model-facing. Nothing it reads folds into `gmeow.gts` — it
    // prints paths and exits — so there is no stale-disk-fold to make.
    let generated = root.join("generated");
    if !generated.is_dir() {
        eprintln!(
            "{}: no generated/ tree. Run `make regen` in that checkout first — comparing an \
             unmaterialized tree would report every artifact as 'unchanged' by comparing \
             nothing.",
            generated.display()
        );
        return ExitCode::from(2);
    }

    let mut files: Vec<PathBuf> = Vec::new();
    collect(&generated, &mut files);
    let mut selected: Vec<String> = files
        .iter()
        .filter_map(|path| {
            let rel = path
                .strip_prefix(&root)
                .ok()?
                .to_string_lossy()
                .replace('\\', "/");
            gmeow_pipeline::gmn_dialect::is_gmn_dialect_path(&rel).then_some(rel)
        })
        .collect();
    selected.sort();
    selected.dedup();

    if selected.is_empty() {
        eprintln!(
            "{}: the declared GMN-dialect predicate selected ZERO paths. That is a hard \
             failure, not an empty diff: a comparison over an empty set passes trivially.",
            root.display()
        );
        return ExitCode::from(1);
    }
    for path in &selected {
        println!("{path}");
    }
    ExitCode::SUCCESS
}

/// Every regular file under `dir`, recursively, skipping symlinks in both positions.
fn collect(dir: &Path, out: &mut Vec<PathBuf>) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    let mut paths: Vec<PathBuf> = entries
        .filter_map(|entry| entry.ok().map(|entry| entry.path()))
        .filter(|path| !path.is_symlink())
        .collect();
    paths.sort();
    for path in paths {
        if path.is_dir() {
            collect(&path, out);
        } else {
            out.push(path);
        }
    }
}
