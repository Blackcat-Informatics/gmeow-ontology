"""Compile the GMEOW mapping DSL into the four standard alignment artifacts.

``gmeow-dev regenerate mappings`` renders, from the single authoring source in
``mapping-dsl/``:

* ``mappings/*.sssom.tsv`` — SSSOM 1:1 term-equivalence rows;
* ``projections/*.edoal.ttl`` — EDOAL complex-alignment cells (with ``edoal:measure``);
* ``projections/functions.fno.ttl`` — the FnO transform catalog, its parameter
  ``fno:type`` DERIVED from each predicate's ontology ``rdfs:range`` (so the
  type-mismatch bug class is structurally impossible);
* ``queries/projections/*.rq`` — the executable SPARQL CONSTRUCT branches.

Before writing anything, the compiler renders the artifacts to a temporary tree
and runs the three :mod:`gmeow_tools.projection_lint` cross-layer invariants on
them; a violation aborts the compile (it can never reach disk). ``--check``
renders to a temp tree and diffs it against the committed files (RDF by graph
isomorphism, TSV/SPARQL by bytes), reporting any drift without writing.
"""

