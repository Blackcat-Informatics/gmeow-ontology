//! Native EDOAL emission — GMEOW's `generated/projections/<profile>.edoal.ttl`
//! emitter, sourced entirely from Rust (#861).
//!
//! This mirrors the SSSOM ([`crate::mapping_emit`]) and FnO ([`crate::fno_emit`])
//! emitters: the Python `mapping_compile.emit_edoal` orchestrator is pulled into the
//! slice framework. Every input is discovered natively from the repo root — the
//! projection cells from the shared `dsl/mappings/**/*.ttl` tree + the slice
//! [`ArtifactRole::Mapping`] artifacts, the language-tag retag map from
//! `ontology/gmeow.ttl` + the slice [`ArtifactRole::Module`] artifacts.
//!
//! The committed `*.edoal.ttl` bytes are produced by the project's canonical Turtle
//! serializer ([`gmeow_rdf::turtle_normalize::canonical_turtle`]); this module builds
//! the EDOAL triples as N-Triples (with deterministic blank-node labels so the
//! once-referenced anonymous nodes inline as `[ … ]` in interning/first-seen order),
//! retags `@x-gmeow-english` → `@en` at build time, and renders through that
//! serializer with the full prefix registry (only the used prefixes appear). The
//! result is byte-identical to the historical Python emitter (the parity gate).

