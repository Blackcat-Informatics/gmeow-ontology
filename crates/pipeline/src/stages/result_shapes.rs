/// Committed logical path of the generated result-shape projection.
pub const RESULT_SHAPES_PATH: &str = "generated/shapes/result-shapes.ttl";

use gmeow_ns::GMEOW_NS;

const HEADER: &str = "# GENERATED by `gmeow-dev sync --mode update --outputs generated` (result-shapes) from logic:ResultShape\n# declarations on competency questions — DO NOT EDIT (P4/P17: logic: is canonical,\n# SHACL is the projection; the Rust authority is gmeow-logic-compile::result_shape).\n@prefix gmeow: <https://blackcatinformatics.ca/gmeow/> .\n@prefix sh:    <http://www.w3.org/ns/shacl#> .\n@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .\n@prefix skos:  <http://www.w3.org/2004/02/skos/core#> .\n";

/// The `rdfs:isDefinedBy` target every minted `GenResultRowShape_*` individual
/// carries — the deterministic per-committed-path graph-identity IRI
/// [`crate::stages::superset::rdf_fanout_graph_iri`] derives for any RDF file under
/// `generated/`. NOTE: `RESULT_SHAPES_PATH` currently rides in the `REP_SHAPES`
/// OPAQUE archive member (`carrier.rs::build_archive_blobs`), not an authored
/// `rdf-fanout` row in `slices/core/pipeline/module.ttl` — this IRI is the
/// document's stable identity label, not (yet) an independently RDF-fold-verified
/// named graph inside `gmeow.gts`.
fn result_shapes_graph_iri() -> String {
    crate::stages::superset::rdf_fanout_graph_iri(RESULT_SHAPES_PATH)
        .expect("RESULT_SHAPES_PATH is a committed .ttl path under generated/")
}

/// The term kind a column requires, in the closed result-shape vocabulary.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Iri,
    Literal,
    BlankNode,
}

/// One projected column of a shape: variable, kind, whether it is required, and
/// an optional pinned datatype IRI (only meaningful for `Kind::Literal` columns).
#[derive(Debug, Clone)]
struct Column {
    var: String,
    kind: Kind,
    required: bool,
    /// `logic:columnDatatype` IRI, if declared on this column.  Only emitted as
    /// a SHACL constraint when the column is a literal kind.
    datatype: Option<String>,
}

/// Recursively collect every `slices/**/tests/competency.ttl` (sorted).
pub(crate) fn competency_files(root: &Path) -> Result<Vec<PathBuf>, gmeow_errors::Diag> {
    let mut out = Vec::new();
    let slices = root.join("slices");
    collect_competency(&slices, &mut out)?;
    out.sort();
    Ok(out)
}

fn collect_competency(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), gmeow_errors::Diag> {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => {
            return Err(gmeow_errors::Diag::of_kind(crate::error::Io {
                message: (e).to_string(),
            }));
        }
    };
    for entry in entries {
        let entry = entry.map_err(|e| {
            gmeow_errors::Diag::of_kind(crate::error::Io {
                message: e.to_string(),
            })
        })?;
        let path = entry.path();
        if path.is_dir() {
            collect_competency(&path, out)?;
        } else if path.file_name().is_some_and(|n| n == "competency.ttl") {
            out.push(path);
        }
    }
    Ok(())
}

/// The skolemization authority under which anonymous competency `ExpectedRow`s (and any other
/// blank node in a competency spec) are minted to stable genid IRIs before SHACL validation.
/// The skolemized dataset is validation-only and NEVER egresses, so this authority names no
/// shipped surface — it only has to be a well-formed base for the RFC 8615 `/.well-known/genid/`
/// space PurRDF mints under.
const COMPETENCY_SKOLEM_AUTHORITY: &str = "https://blackcatinformatics.ca";

/// Load every competency spec into one native dataset (each parsed through the
/// canonical native codec and unioned so per-file blanks stay disjoint).
///
/// The dataset is **skolemized** before it is returned: PurRDF's SHACL-SPARQL pre-binding
/// (SHACL spec §5.2.1) cannot correlate a BLANK-NODE focus node that appears only inside the
/// `FILTER NOT EXISTS` of a result-column presence check, so an `ExpectedRow` authored
/// anonymously (`[ … ]`) would spuriously fail its own shape. Replacing every blank node with a
/// stable genid IRI (RDF 1.2 first-class blank-node recourse) makes each `ExpectedRow` a focus
/// node the pre-binding can carry. This is structure-preserving (only blank-node labels change)
/// and validation-only; `render_result_shapes` reads only NAMED shape/column nodes, so its
/// byte-deterministic output is unaffected.
fn load_competency_store(root: &Path) -> Result<Arc<RdfDataset>, gmeow_errors::Diag> {
    let dataset = native_query::dataset_from_files(&competency_files(root)?)?;
    let skolemized =
        purrdf::skolemize(dataset.as_ref(), COMPETENCY_SKOLEM_AUTHORITY).map_err(|e| {
            gmeow_errors::Diag::of_kind(crate::error::Parse {
                message: format!("result-shapes: skolemizing the competency store failed: {e:?}"),
            })
        })?;
    Ok(Arc::new(skolemized))
}

/// The lexical string of `cells[i]` (a literal's lexical form or an IRI's text).
fn lit(cells: &[Option<TermValue>], i: Option<usize>) -> Option<String> {
    match i.and_then(|i| cells.get(i)).and_then(Option::as_ref) {
        Some(TermValue::Literal { lexical_form, .. }) => Some(lexical_form.clone()),
        Some(TermValue::Iri(n)) => Some(n.clone()),
        _ => None,
    }
}

/// The IRI of `cells[i]`, or `None` if unbound / not an IRI.
fn iri(cells: &[Option<TermValue>], i: Option<usize>) -> Option<String> {
    match i.and_then(|i| cells.get(i)).and_then(Option::as_ref) {
        Some(TermValue::Iri(n)) => Some(n.clone()),
        _ => None,
    }
}

fn local_kind(kind_iri: &str) -> Result<Kind, gmeow_errors::Diag> {
    match kind_iri.rsplit(['/', '#']).next().unwrap_or(kind_iri) {
        "TermKindIri" => Ok(Kind::Iri),
        "TermKindLiteral" => Ok(Kind::Literal),
        "TermKindBlankNode" => Ok(Kind::BlankNode),
        other => Err(gmeow_errors::Diag::of_kind(
            crate::error::InvalidDeclaration {
                message: format!("result-shapes: unknown logic:columnTermKind <…/{other}>"),
            },
        )),
    }
}

/// Extract `shape IRI -> sorted columns` from the competency dataset.
fn shapes(store: &Arc<RdfDataset>) -> Result<BTreeMap<String, Vec<Column>>, gmeow_errors::Diag> {
    let query = "\
        PREFIX gmeow: <https://blackcatinformatics.ca/gmeow/>\n\
        PREFIX logic: <https://blackcatinformatics.ca/logic/>\n\
        SELECT ?shape ?var ?kind ?binding ?datatype WHERE {\n\
          ?cq gmeow:cqResultShape ?shape .\n\
          ?shape logic:declaresColumn ?col .\n\
          ?col logic:columnVariable ?var ;\n\
               logic:columnTermKind ?kind ;\n\
               logic:columnBinding ?binding .\n\
          OPTIONAL { ?col logic:columnDatatype ?datatype }\n\
        }";
    let solutions = native_query::select(store, query)?;
    let c_shape = solutions.col("shape");
    let c_var = solutions.col("var");
    let c_kind = solutions.col("kind");
    let c_binding = solutions.col("binding");
    let c_datatype = solutions.col("datatype");

    let mut by_shape: BTreeMap<String, BTreeMap<String, Column>> = BTreeMap::new();
    for cells in &solutions.rows {
        let shape = iri(cells, c_shape).ok_or_else(|| {
            gmeow_errors::Diag::of_kind(crate::error::Parse {
                message: "result-shapes: ?shape did not bind an IRI".to_owned(),
            })
        })?;
        let var = lit(cells, c_var).ok_or_else(|| {
            gmeow_errors::Diag::of_kind(crate::error::Parse {
                message: "result-shapes: a column has no logic:columnVariable".to_owned(),
            })
        })?;
        let kind = local_kind(&iri(cells, c_kind).ok_or_else(|| {
            gmeow_errors::Diag::of_kind(crate::error::Parse {
                message: "result-shapes: ?kind did not bind an IRI".to_owned(),
            })
        })?)?;
        let required = iri(cells, c_binding)
            .map(|b| b.rsplit(['/', '#']).next().unwrap_or(&b) == "BindingRequired")
            .unwrap_or(false);
        let datatype = iri(cells, c_datatype);
        by_shape.entry(shape).or_default().insert(
            var.clone(),
            Column {
                var,
                kind,
                required,
                datatype,
            },
        );
    }
    Ok(by_shape
        .into_iter()
        .map(|(s, cols)| (s, cols.into_values().collect()))
        .collect())
}

/// A deterministic, collision-free local name for the generated NodeShape of a
/// source shape IRI (sanitise the IRI tail after the gmeow namespace).
fn nodeshape_local(shape_iri: &str) -> String {
    let tail = shape_iri.strip_prefix(GMEOW_NS).unwrap_or(shape_iri);
    let sanitized: String = tail
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    format!("GenResultRowShape_{sanitized}")
}

fn kind_word(kind: Kind) -> &'static str {
    match kind {
        Kind::Iri => "an IRI",
        Kind::Literal => "a literal",
        Kind::BlankNode => "a blank node",
    }
}

/// The reified cell value-property for a kind (`None` for a blank node — the cell
/// model has no value property for it, so only presence is checkable).
fn value_prop(kind: Kind) -> Option<&'static str> {
    match kind {
        Kind::Iri => Some("cellValueIri"),
        Kind::Literal => Some("cellValueLiteral"),
        Kind::BlankNode => None,
    }
}

/// Render the result-shape projection document.
pub fn render_result_shapes(root: &Path) -> Result<String, gmeow_errors::Diag> {
    let store = load_competency_store(root)?;
    let mut blocks: Vec<String> = vec![HEADER.to_string()];

    let graph_iri = result_shapes_graph_iri();
    for (shape_iri, columns) in shapes(&store)? {
        let local = nodeshape_local(&shape_iri);
        let subject_iri = format!("{GMEOW_NS}{local}");
        let label = format!("result-row shape for <{shape_iri}> (generated)");
        let definition = format!("Result-row shape for <{shape_iri}> (generated).");
        let mut lines: Vec<String> =
            vec![format!("gmeow:{local}"), "    a sh:NodeShape ;".to_string()];
        lines.extend(abox_annotation_turtle_lines(
            &subject_iri,
            &label,
            &definition,
            &graph_iri,
            BOX_ABOX,
            "    ",
        ));
        lines.extend([
            "    sh:target [".to_string(),
            "        a sh:SPARQLTarget ;".to_string(),
            format!(
                "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT ?this WHERE {{ ?cq gmeow:cqResultShape <{shape_iri}> . ?cq gmeow:cqExpectRow ?this }}\"\"\" ;"
            ),
            "    ] ;".to_string(),
        ]);

        for col in &columns {
            let v = &col.var;
            let want = kind_word(col.kind);
            // Presence + right-kind for required columns.
            if col.required {
                let presence = match value_prop(col.kind) {
                    Some(prop) => format!(
                        "FILTER NOT EXISTS {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' ; gmeow:{prop} ?val }}"
                    ),
                    None => format!(
                        "FILTER NOT EXISTS {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' }}"
                    ),
                };
                lines.push("    sh:sparql [".to_string());
                lines.push("        sh:severity sh:Violation ;".to_string());
                lines.push(format!(
                    "        sh:message \"result column ?{v} must be present and bind {want}\" ;"
                ));
                lines.push(format!(
                    "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT $this WHERE {{ {presence} }}\"\"\" ;"
                ));
                lines.push("    ] ;".to_string());
            }
            // Wrong-kind: a cell for this var binding the OTHER value property.
            if let Some(wrong) = wrong_value_prop(col.kind) {
                lines.push("    sh:sparql [".to_string());
                lines.push("        sh:severity sh:Violation ;".to_string());
                lines.push(format!(
                    "        sh:message \"result column ?{v} must bind {want}\" ;"
                ));
                lines.push(format!(
                    "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT $this WHERE {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' ; gmeow:{wrong} ?val }}\"\"\" ;"
                ));
                lines.push("    ] ;".to_string());
            }
            // Pinned datatype: for literal columns with a logic:columnDatatype IRI.
            if col.kind == Kind::Literal
                && let Some(dt) = &col.datatype
            {
                lines.push("    sh:sparql [".to_string());
                lines.push("        sh:severity sh:Violation ;".to_string());
                lines.push(format!(
                        "        sh:message \"result column ?{v} must bind a literal of datatype <{dt}>\" ;"
                    ));
                lines.push(format!(
                        "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT $this WHERE {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' ; gmeow:cellValueLiteral ?val . FILTER ( datatype(?val) != <{dt}> ) }}\"\"\" ;"
                    ));
                lines.push("    ] ;".to_string());
            }
        }

        // Close the node shape: replace the trailing " ;" of the last line with " .".
        let last = lines.len() - 1;
        if let Some(stripped) = lines[last].strip_suffix(" ;") {
            lines[last] = format!("{stripped} .");
        }
        blocks.push(lines.join("\n") + "\n");
    }
    Ok(blocks.join("\n"))
}

/// The value property a binding of the WRONG kind would use (`None` for a blank
/// node, whose kind the value-keyed cell model cannot distinguish).
fn wrong_value_prop(kind: Kind) -> Option<&'static str> {
    match kind {
        Kind::Iri => Some("cellValueLiteral"),
        Kind::Literal => Some("cellValueIri"),
        Kind::BlankNode => None,
    }
}

// ── Declarative-contract subsumption (content-level, NOT emitted) ─────────────
//
// These map a result column's contract onto the canonical ValidationShapeIr model to
// PROVE (in-test) that the declarative model subsumes the procedural sh:sparql column
// constraints. They are never emitted and never feed the byte-deterministic render, so
// they are test-scoped.

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `result-shapes` export-leaf stage.
pub struct ResultShapesStage;

impl Stage for ResultShapesStage {
    fn id(&self) -> &str {
        "stage-export-result-shapes"
    }
    fn consumes(&self) -> &[String] {
        &[]
    }
    fn impl_version(&self) -> &str {
        "result_shapes.v1"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<PathBuf>, gmeow_errors::Diag> {
        // The leaf reads every competency spec's logic:ResultShape declarations;
        // declare them as cache inputs so a shape edit busts the cache.
        competency_files(root)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, gmeow_errors::Diag> {
        let ttl = render_result_shapes(input.root)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(RESULT_SHAPES_PATH.to_string(), ttl.into_bytes());
        Ok(StageOutput::new(StageProduct::from_artifacts(
            self.id(),
            artifacts,
        )))
    }
}

