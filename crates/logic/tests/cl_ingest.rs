//! End-to-end proof (#725, Task 4): import a sample **external** Common Logic
//! (CLIF) knowledge base and reason over it — `parse_clif_str` → `LogicProgram`
//! IR → native/Nemo materialization.
//!
//! The fixtures live under `conformance/logic/cl-ingest/`:
//!
//! - `sample-kb.logic.ttl` — the canonical `logic:` authoring source: a minimal
//!   genealogy theory (two Horn rules — an `ancestor` base case and its
//!   transitive step — over a `parent` EDB predicate).
//! - `sample-kb.clif` — the CLIF export of that program, produced by
//!   [`gmeow_logic_compile::clif::writer::project_clif`]. `parse_clif_str` only
//!   ever reconstructs the IR from the `;; @@gmeow-rdf-meta@@` carrier channel
//!   of a gmeow-dialect CLIF file (the idiomatic FOL sentences before the
//!   sentinel are a validated-only human view), so this fixture MUST be
//!   generated by `project_clif`, never hand-authored. `GMEOW_CL_INGEST_BLESS=1`
//!   regenerates it from the `.logic.ttl` source; the default (unset) run
//!   re-projects the source and asserts the committed CLIF is byte-identical,
//!   so a stale export can never mask an ingest regression.
//! - `sample-kb.edb.nq` — the EDB: `parent(alice, bob)` and `parent(bob, carol)`
//!   in the `.../genealogy/world-main` graph.
//!
//! The load-bearing assertion is the transitively derived `ancestor(alice,
//! carol)` edge — it cannot be produced by an EDB echo; only rule application
//! (the transitive-step Horn rule, applied twice) derives it.

use gmeow_logic_compile::clif::parse_clif_str;
use gmeow_logic_compile::clif::writer::project_clif;
use gmeow_logic_compile::frontend::{parse_logic_str, Severity};
use gmeow_logic_compile::projections::compile_program;

const GENEALOGY_NS: &str = "https://example.org/cl-ingest/genealogy/";

fn fixture_path(name: &str) -> String {
    concat!(
        env!("CARGO_MANIFEST_DIR"),
        "/../../conformance/logic/cl-ingest/"
    )
    .to_owned()
        + name
}

fn read_fixture(name: &str) -> String {
    let path = fixture_path(name);
    std::fs::read_to_string(&path).unwrap_or_else(|e| panic!("read {path}: {e}"))
}

/// The committed `sample-kb.clif` is a projection of `sample-kb.logic.ttl`
/// (never hand-authored). Bless (`GMEOW_CL_INGEST_BLESS=1`) re-projects the
/// source and rewrites the fixture; the default run re-projects and asserts
/// byte-identity, so the committed CLIF can never silently drift from its
/// `logic:` source of truth.
#[test]
fn sample_kb_clif_fixture_matches_projection() {
    let ttl = read_fixture("sample-kb.logic.ttl");
    let (program0, diags0) = parse_logic_str(&ttl, None).expect("parse sample-kb.logic.ttl");
    assert!(
        diags0.iter().all(|d| d.severity != Severity::Error),
        "sample-kb.logic.ttl parse raised Error diagnostics: {diags0:?}"
    );

    let projected = project_clif(&program0).expect("project_clif(sample-kb.logic.ttl)");
    let clif_path = fixture_path("sample-kb.clif");

    if std::env::var("GMEOW_CL_INGEST_BLESS").as_deref() == Ok("1") {
        std::fs::write(&clif_path, &projected.content)
            .unwrap_or_else(|e| panic!("write {clif_path}: {e}"));
        return;
    }

    let committed = std::fs::read_to_string(&clif_path).unwrap_or_else(|e| {
        panic!("read {clif_path}: {e} — run with GMEOW_CL_INGEST_BLESS=1 to generate the fixture")
    });
    assert_eq!(
        committed, projected.content,
        "committed sample-kb.clif is stale — re-bless with GMEOW_CL_INGEST_BLESS=1"
    );
}

/// The end-to-end ingest + reason proof: `parse_clif_str` on the committed
/// external CLIF KB → `compile_program` → `materialize_routed` derives the
/// `ancestor` transitive closure over the `parent` EDB.
#[test]
fn sample_kb_clif_ingest_and_reason_derives_ancestor_closure() {
    // ── 1. Ingest: parse the committed external CLIF KB back into IR. ──────────
    let clif = read_fixture("sample-kb.clif");
    let source_iri = format!("{GENEALOGY_NS}kb");
    let (program, diags) =
        parse_clif_str(&clif, Some(source_iri)).expect("parse_clif_str(sample-kb.clif)");
    assert!(
        diags.iter().all(|d| d.severity != Severity::Error),
        "CLIF ingest raised Error diagnostics on a project_clif-produced fixture: {diags:?}"
    );

    // ── 2. Compile the ingested program down to the Nemo/native rule text. ─────
    let arts = compile_program(&program).expect("compile_program(ingested CLIF program)");

    // ── 3. Reason: materialize the rules over the committed EDB. ────────────────
    let edb = read_fixture("sample-kb.edb.nq");

    let profiles: [Option<&str>; 2] = [None, Some("StratifiedNAFProfile")];
    let mut derived_last: Vec<(String, String, String)> = Vec::new();
    let mut found = false;
    let ancestor_pred = format!("{GENEALOGY_NS}ancestor");
    let want_alice = format!("<{GENEALOGY_NS}alice>");
    let want_bob = format!("<{GENEALOGY_NS}bob>");
    let want_carol = format!("<{GENEALOGY_NS}carol>");

    for profile in profiles {
        let m = gmeow_logic::materialize::materialize_routed(
            &arts.nemo_rules,
            &edb,
            None,
            None,
            None,
            profile,
        )
        .unwrap_or_else(|e| panic!("materialize_routed(profile={profile:?}) failed: {e}"));

        let derived: Vec<(String, String, String)> = m
            .quads
            .iter()
            .map(|q| {
                (
                    gmeow_logic::provenance::term_display(&q.subject),
                    q.predicate.clone(),
                    gmeow_logic::provenance::term_display(&q.object),
                )
            })
            .collect();

        let has_closure = derived
            .iter()
            .any(|(s, p, o)| p == &ancestor_pred && s == &want_alice && o == &want_carol);

        derived_last = derived;
        if has_closure {
            found = true;
            break;
        }
    }

    assert!(
        found,
        "ancestor(alice, carol) was NOT derived under any tried profile — the transitive-step \
         Horn rule must fire twice over the ingested CLIF program's rules; derived quads: \
         {derived_last:?}"
    );

    // The two base facts must also be present (asserted-EDB directly, and the
    // base Horn rule's direct application over `parent`).
    for (want_s, want_o) in [(&want_alice, &want_bob), (&want_bob, &want_carol)] {
        assert!(
            derived_last
                .iter()
                .any(|(s, p, o)| p == &ancestor_pred && s == want_s && o == want_o),
            "expected base ancestor({want_s}, {want_o}) to be derived; derived quads: \
             {derived_last:?}"
        );
    }
}
