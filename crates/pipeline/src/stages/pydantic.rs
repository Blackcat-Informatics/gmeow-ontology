fn err(message: impl Into<String>) -> gmeow_errors::Diag {
    gmeow_errors::Diag::of_kind(crate::error::StageFailed {
        stage: "stage-export-pydantic".into(),
        message: message.into(),
    })
}

// ── Wheel version (owl:versionInfo → __about__.py) ──────────────────────────

/// The bare ontology IRI (no trailing slash) — the subject carrying
/// `owl:versionInfo` in `ontology/gmeow.ttl`'s header. Mirrors the same subject
/// `crate::stages::term_manifest`/`crate::stages::carrier`/`crate::stages::metadata`
/// each independently read `owl:versionInfo` off.
const ONTOLOGY_IRI: &str = "https://blackcatinformatics.ca/gmeow";
const OWL_VERSION_INFO: &str = "http://www.w3.org/2002/07/owl#versionInfo";

/// Load the authored ontology header (`ontology/gmeow.ttl`) and return its
/// `owl:versionInfo` literal verbatim — the SINGLE source of the `gmeow-ontology`
/// wheel version, stamped into the generated `gmeow_models/__about__.py`
/// (`pyproject.toml`'s `[tool.hatch.version]` reads `__version__` from there). A
/// hard requirement: never defaulted, and hard-fails when the value is missing or
/// is not a PEP 440 PUBLIC version identifier (never a local version — PyPI
/// rejects a `+local` segment, so this policy forbids one outright).
fn ontology_version_info(root: &Path) -> Result<String, gmeow_errors::Diag> {
    let path = root.join("ontology").join("gmeow.ttl");
    let bytes = std::fs::read(&path)
        .map_err(|e| err(format!("read ontology header {}: {e}", path.display())))?;
    let dataset = purrdf::parse_dataset(&bytes, "text/turtle", None)
        .map_err(|e| err(format!("parse ontology header {}: {e}", path.display())))?;
    for quad in dataset.owned_quads() {
        if quad.graph_name.is_some() {
            continue; // the ontology header lives in the default graph only.
        }
        let purrdf::model::RdfTerm::Iri(subject) = &quad.subject else {
            continue;
        };
        if subject != ONTOLOGY_IRI || quad.predicate != OWL_VERSION_INFO {
            continue;
        }
        let purrdf::model::RdfTerm::Literal(literal) = &quad.object else {
            continue;
        };
        let version = literal.lexical_form.clone();
        if !is_pep440_public_version(&version) {
            return Err(err(format!(
                "ontology {ONTOLOGY_IRI} owl:versionInfo {version:?} is not a PEP 440 public \
                 version identifier — refusing to stamp a malformed wheel version"
            )));
        }
        return Ok(version);
    }
    Err(err(format!(
        "authored ontology {ONTOLOGY_IRI} has no owl:versionInfo — cannot derive the wheel version"
    )))
}

/// Whether `raw` is a PEP 440–compliant PUBLIC version identifier — i.e. it has
/// NO local-version segment (`+...`), which this emitter forbids outright (PyPI
/// rejects a local version, so a wheel version can never legitimately carry one).
/// Hand-rolled (no external regex dependency): mirrors the canonical PEP 440
/// `VERSION_PATTERN` public-version grammar,
///
/// ```text
/// [v] [N!] N(.N)* [{a|b|c|rc|alpha|beta|pre|preview}[N]] [{.post|-|post|rev|r}[N]] [{.dev}[N]]
/// ```
///
/// case-insensitively, with the documented `-`/`_`/`.` separator flexibility
/// between segments. Any trailing byte after the matched grammar (in particular a
/// `+local` segment) fails the match.
fn is_pep440_public_version(raw: &str) -> bool {
    if raw.is_empty() || !raw.is_ascii() {
        return false;
    }
    let lower = raw.to_ascii_lowercase();
    let b = lower.as_bytes();
    let n = b.len();
    let mut i = 0usize;

    fn digits(b: &[u8], i: &mut usize) -> bool {
        let start = *i;
        while *i < b.len() && b[*i].is_ascii_digit() {
            *i += 1;
        }
        *i > start
    }
    fn sep(b: &[u8], i: &mut usize) {
        if *i < b.len() && matches!(b[*i], b'-' | b'_' | b'.') {
            *i += 1;
        }
    }
    fn tag(b: &[u8], i: &mut usize, tags: &[&str]) -> bool {
        for t in tags {
            if b[*i..].starts_with(t.as_bytes()) {
                *i += t.len();
                return true;
            }
        }
        false
    }

    // Optional leading "v" (PEP 440 permits it, e.g. `v1.0`).
    if i < n && b[i] == b'v' {
        i += 1;
    }
    // Optional epoch: digits "!".
    let save = i;
    if digits(b, &mut i) && i < n && b[i] == b'!' {
        i += 1;
    } else {
        i = save;
    }
    // Release segment: digits ("." digits)*  — at least one group, required.
    if !digits(b, &mut i) {
        return false;
    }
    loop {
        let save = i;
        if i < n && b[i] == b'.' {
            i += 1;
            if digits(b, &mut i) {
                continue;
            }
        }
        i = save;
        break;
    }
    // Optional pre-release: [-_.]? (preview|alpha|beta|pre|rc|a|b|c) [-_.]? N?
    // (tags ordered longest-first so a short alias never shadows a longer one).
    {
        let save = i;
        let mut j = i;
        sep(b, &mut j);
        const PRE_TAGS: &[&str] = &["preview", "alpha", "beta", "pre", "rc", "a", "b", "c"];
        if tag(b, &mut j, PRE_TAGS) {
            sep(b, &mut j);
            digits(b, &mut j);
            i = j;
        } else {
            i = save;
        }
    }
    // Optional post-release: ("-" N) | ([-_.]? (post|rev|r) [-_.]? N?).
    {
        let save = i;
        if i < n && b[i] == b'-' {
            let mut j = i + 1;
            if digits(b, &mut j) {
                i = j;
            }
        } else {
            let mut j = i;
            sep(b, &mut j);
            const POST_TAGS: &[&str] = &["post", "rev", "r"];
            if tag(b, &mut j, POST_TAGS) {
                sep(b, &mut j);
                digits(b, &mut j);
                i = j;
            } else {
                i = save;
            }
        }
    }
    // Optional dev-release: [-_.]? "dev" [-_.]? N?
    {
        let save = i;
        let mut j = i;
        sep(b, &mut j);
        if b[j..].starts_with(b"dev") {
            j += 3;
            sep(b, &mut j);
            digits(b, &mut j);
            i = j;
        } else {
            i = save;
        }
    }
    // No local-version segment permitted: the whole string must be consumed.
    i == n
}

/// Render `gmeow_models/__about__.py` — the SINGLE source of the wheel version,
/// the ontology's `owl:versionInfo` verbatim. `pyproject.toml`'s
/// `[tool.hatch.version] path = "gmeow_models/__about__.py"` reads `__version__`
/// straight from here, so hatchling and the package agree by construction. This
/// is gmeow orchestration layered ONTO purrdf's emitted package, not one of its
/// artifacts.
///
/// `version` is PEP 440-validated by [`ontology_version_info`] before it ever
/// reaches here, so it contains only ASCII alphanumerics and `.`/`-`/`_`/`!` —
/// no character `{version:?}` would need to escape beyond a plain quote wrap.
///
/// # Bump policy
///
/// Bump `owl:versionInfo` in `ontology/gmeow.ttl` and `make sync` — never
/// hand-edit this file or set `version` in `pyproject.toml` directly.
fn render_about(version: &str) -> Vec<u8> {
    let mut out = String::new();
    out.push_str("\"\"\"The gmeow-ontology wheel version — a single-source projection.\n\n");
    out.push_str("This is the ontology's owl:versionInfo (ontology/gmeow.ttl), verbatim.\n");
    out.push_str("pyproject.toml's [tool.hatch.version] reads __version__ from here. To\n");
    out.push_str("release a new wheel version, bump owl:versionInfo in ontology/gmeow.ttl\n");
    out.push_str("and run `make sync` — never hand-edit this file or set `version`\n");
    out.push_str("in pyproject.toml directly.\n\"\"\"\n\n");
    out.push_str("from __future__ import annotations\n\n");
    out.push_str(&format!("__version__ = {version:?}\n"));
    out.into_bytes()
}

// ── Public entry point ───────────────────────────────────────────────────────

/// The gmeow-owned `PydanticConfig` — package identity + docstrings `purrdf`
/// never fabricates.
fn pydantic_config() -> Result<PydanticConfig, gmeow_errors::Diag> {
    PydanticConfig::new(PACKAGE_NAME, PACKAGE_DOCSTRING, MODELS_DOCSTRING)
        .map_err(|e| err(format!("build PydanticConfig: {e}")))
}

/// Aggregate `emit_pydantic`'s [`purrdf::LossLedger`] into a single `tracing`
/// event per `(code, note)` pair — mirrors
/// [`crate::stages::json_schema::report_losses`] / [`crate::stages::schemas`]'s
/// `report_losses` so no runtime-projection loss is ever silently dropped.
fn report_losses(losses: &purrdf::LossLedger) {
    let mut grouped: BTreeMap<(&str, &str), Vec<&str>> = BTreeMap::new();
    for loss in losses.entries() {
        let subject = loss
            .location
            .as_deref()
            .and_then(|location| location.subject.as_deref())
            .unwrap_or("<unlocated>");
        grouped
            .entry((loss.code.as_ref(), loss.note.as_ref()))
            .or_default()
            .push(subject);
    }
    for ((construct, reason), mut shapes) in grouped {
        shapes.sort_unstable();
        shapes.dedup();
        let examples = shapes
            .iter()
            .take(5)
            .copied()
            .collect::<Vec<_>>()
            .join(", ");
        let suffix = if shapes.len() > 5 {
            format!(" (+{} more)", shapes.len() - 5)
        } else {
            String::new()
        };
        tracing::info!(
            target: "pydantic_loss",
            construct = construct,
            shapes = shapes.len(),
            reason = reason,
            examples = %format!("{examples}{suffix}"),
            "lossy drop projecting compiled JSON Schema to the Pydantic v2 runtime surface",
        );
    }
}

/// Compile + enrich the fresh shape union through the ONE shared builder, emit
/// the Pydantic package via `purrdf::shapes::pydantic::emit_pydantic`, report
/// its loss ledger, and stamp the gmeow-orchestrated `__about__.py` wheel
/// version alongside purrdf's artifacts.
///
/// Deterministic: `emit_pydantic` sorts every collection, and the version stamp
/// is a pure function of the authored `owl:versionInfo` — no timestamps.
fn render_pydantic_package(
    root: &Path,
    shapes: &purrdf::shapes::shapes::Shapes,
) -> Result<BTreeMap<String, Vec<u8>>, gmeow_errors::Diag> {
    let compiled = crate::stages::schema_compile::enriched_compiled_schema(root, shapes)?;
    let config = pydantic_config()?;
    let package =
        emit_pydantic(&compiled, &config).map_err(|e| err(format!("emit_pydantic: {e}")))?;
    report_losses(&package.losses);

    let version = ontology_version_info(root)?;
    let mut artifacts = package.artifacts;
    artifacts.insert(format!("{PKG}/{ABOUT_MODULE}.py"), render_about(&version));
    Ok(artifacts)
}

/// Render the Pydantic package from the COMMITTED (on-disk) shape union — the
/// standalone `make sync SYNC_OUTPUTS=docs` entry, which runs post-pipeline against
/// the fanout-refreshed committed files. The in-DAG [`PydanticStage`] must NOT use
/// this: it routes through [`crate::stages::shape_union_fresh::load_shapes_fresh`]
/// so the union's generated members are THIS run's product bytes (the
/// stale-disk-fold class).
pub fn render_models_python_package(
    root: &Path,
) -> Result<BTreeMap<String, Vec<u8>>, gmeow_errors::Diag> {
    let (_store, shapes) = purrdf::shapes::shape_union::load_shapes(root)
        .map_err(|m| err(format!("load shape union: {m}")))?;
    render_pydantic_package(root, &shapes)
}

// ── Pipeline stage ───────────────────────────────────────────────────────────

/// The `stage-export-pydantic` export-leaf stage: a fresh-union leaf (like
/// `stage-export-json-schema` / `stage-export-schemas`) that renders the
/// Pydantic model package from the shape union via `purrdf::shapes::pydantic`,
/// with the union's `generated/shapes/*.ttl` members sourced from THIS run's
/// consumed producer products (never the stale committed files — the
/// stale-disk-fold class). Its artifacts are written to disk under
/// [`PACKAGE_DISK_PREFIX`] (the wheel source) and folded into the
/// `models-python` blob by the carrier.
pub struct PydanticStage {
    consumes: Vec<String>,
}

impl PydanticStage {
    /// Construct the stage. It reads the AUTHORED shape/ontology sources from disk
    /// and consumes the four generated-shape producers so the compiled union folds
    /// THIS run's fresh `generated/shapes/*.ttl` bytes.
    pub fn new() -> Self {
        Self {
            consumes: crate::stages::shape_union_fresh::producer_consumes(),
        }
    }
}

impl Default for PydanticStage {
    fn default() -> Self {
        Self::new()
    }
}

impl Stage for PydanticStage {
    fn id(&self) -> &str {
        "stage-export-pydantic"
    }
    fn consumes(&self) -> &[String] {
        &self.consumes
    }
    fn impl_version(&self) -> &str {
        // v2-fresh-shape-union: the union's generated/shapes/*.ttl members are
        // product-sourced from the consumed producer stages instead of read off
        // disk. -purrdf: cut over from the hand-rolled slice-routed renderer to
        // purrdf::shapes::pydantic::emit_pydantic (a flat single-module package) —
        // bumped to invalidate every previously-cached slice-routed byte.
        "pydantic.v2-fresh-shape-union-purrdf"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<std::path::PathBuf>, gmeow_errors::Diag> {
        // The AUTHORED half of the shape union (`shapes/*.ttl` minus lints +
        // `slices/*/*/shapes.ttl`) is the disk source set the emitter reads — declared
        // as cache inputs so an authored-shape edit busts the cache. The GENERATED
        // members are NOT declared: they are product-sourced off the consumed producer
        // stages, whose product digests already key the cache (a `generated/` path here
        // would itself be the stale-disk-fold bug class). The value-vocabulary
        // enrichment ALSO reads the ontology ABox (`slices/**/module.ttl`), so those
        // sources bust the cache too — a new vocabulary member must reflow the schema.
        // The ontology header (`ontology/gmeow.ttl`) sources the `__about__.py`
        // version stamp, so it busts the cache too.
        let mut files = crate::stages::shape_union_fresh::authored_shape_files(root)?;
        files.extend(crate::stages::value_vocab::ontology_module_files(root));
        files.push(root.join("ontology").join("gmeow.ttl"));
        files.sort();
        files.dedup();
        Ok(files)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, gmeow_errors::Diag> {
        let fresh = crate::stages::shape_union_fresh::fresh_generated_shape_members(
            self.id(),
            input.upstream,
        )?;
        let (_store, shapes) =
            crate::stages::shape_union_fresh::load_shapes_fresh(input.root, &fresh)?;
        let rendered = render_pydantic_package(input.root, &shapes)?;
        // Key every member at its on-disk package path (the wheel source tree); the
        // carrier strips the prefix back to the package-relative blob member key.
        let artifacts: BTreeMap<String, Vec<u8>> = rendered
            .into_iter()
            .map(|(k, v)| (format!("{PACKAGE_DISK_PREFIX}{k}"), v))
            .collect();
        Ok(StageOutput::new(StageProduct::from_artifacts(
            self.id(),
            artifacts,
        )))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .canonicalize()
            .unwrap()
    }

    /// The fresh `generated/shapes/*.ttl` byte map a hermetic test builds from the
    /// COMMITTED files — the same members [`fresh_generated_shape_members`] pulls
    /// off the producer products in production
    /// ([`crate::stages::shape_union_fresh::fresh_generated_shape_members`]), so
    /// the test exercises the stage's real fresh-union path without a pipeline run.
    /// Mirrors `crate::stages::json_schema::tests::committed_fresh_map`.
    fn committed_fresh_map(root: &Path) -> BTreeMap<String, Vec<u8>> {
        [
            crate::stages::compile_logic::VALIDATION_SHAPES_TTL_PATH,
            crate::stages::compile_logic::PROCEDURAL_CONSTRAINTS_PATH,
            crate::stages::constraint_shapes::CONSTRAINT_SHAPES_PATH,
            crate::stages::frame_shapes::FRAME_SHAPES_PATH,
            crate::stages::result_shapes::RESULT_SHAPES_PATH,
        ]
        .into_iter()
        .map(|rel| {
            (
                rel.to_string(),
                std::fs::read(root.join(rel)).unwrap_or_else(|e| panic!("read {rel}: {e}")),
            )
        })
        .collect()
    }

    fn run_once(root: &Path) -> BTreeMap<String, Vec<u8>> {
        let fresh = committed_fresh_map(root);
        let (_store, shapes) = crate::stages::shape_union_fresh::load_shapes_fresh(root, &fresh)
            .expect("load fresh shape union");
        render_pydantic_package(root, &shapes).expect("render pydantic package")
    }

    #[test]
    fn pydantic_stage_emits_all_artifacts_deterministically() {
        let stage = PydanticStage::new();
        assert_eq!(stage.id(), "stage-export-pydantic");
        let root = repo_root();
        let first = run_once(&root);

        for member in [
            "gmeow_models/models.py",
            "gmeow_models/_base.py",
            "gmeow_models/__init__.py",
            "gmeow_models/py.typed",
            "gmeow_models/__about__.py",
        ] {
            assert!(first.contains_key(member), "missing {member}");
        }

        let models_py =
            String::from_utf8(first["gmeow_models/models.py"].clone()).expect("models.py utf8");
        assert!(models_py.contains("class "), "models.py has no class");
        assert!(
            models_py.contains("PurrdfBaseModel"),
            "models.py does not use the purrdf base class"
        );

        let about_py =
            String::from_utf8(first["gmeow_models/__about__.py"].clone()).expect("about.py utf8");
        let version = ontology_version_info(&root).expect("ontology version");
        assert!(
            about_py.contains(&version),
            "__about__.py does not carry the ontology version {version:?}:\n{about_py}"
        );

        // Byte-deterministic across two runs.
        let second = run_once(&root);
        assert_eq!(
            first, second,
            "pydantic package output is non-deterministic"
        );
    }
}
