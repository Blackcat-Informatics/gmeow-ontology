/// Select only producer-owned fields for the independently authored fragment.
fn profile(fragment: &str, extra: &str) -> String {
    let mut input = SIMPLE.replace(
        r#""fragment":"backward""#,
        &format!(r#""fragment":"{fragment}""#),
    );
    if fragment != "backward" {
        input = input.replacen(r#""answer_count":2"#, r#""derived_count":2"#, 1);
    }
    if !extra.is_empty() {
        input = input.replacen(
            r#""cost_vector":[]"#,
            &format!(r#""cost_vector":[],{extra}"#),
            1,
        );
    }
    if matches!(fragment, "incremental" | "incremental-grounding") {
        input = input.replace(r#""native_vs_golden":true"#,
            r#""native_vs_golden":true,"incremental_insert_vs_scratch":true,"incremental_retract_vs_scratch":false"#);
    }
    input
}

/// Feed authored bytes to the actual two projection functions without invoking their stage.
fn rendered(input: &str) -> Result<(String, String), gmeow_errors::Diag> {
    let directory = tempdir().unwrap();
    std::fs::create_dir(directory.path().join("bench")).unwrap();
    std::fs::write(directory.path().join(COST_BASELINE_PATH), input).unwrap();
    let ledger = render_cost_ledger(directory.path())?; // gmeow-test-input: synthetic-only
    let soak = render_soak(directory.path())?; // gmeow-test-input: synthetic-only
    Ok((
        String::from_utf8(ledger[COST_LEDGER_PATH].clone()).unwrap(),
        String::from_utf8(soak[SOAK_RECORD_PATH].clone()).unwrap(),
    ))
}

/// Obtain native JSON pointers from structural decoding, before report-level admission.
fn native_error(input: &str) -> DecodeError {
    match json::record::from_slice::<CostArtifact>(input.as_bytes()) {
        Ok(_) => panic!("invalid artifact admitted: {input}"),
        Err(error) => error,
    }
}

