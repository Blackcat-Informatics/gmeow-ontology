pub const RDF12_YAMLLD_PATH: &str = "pipeline/statements/gmeow.rdf12.yamlld";

const OWL_BANNER: &str = "# GENERATED by `gmeow-dev sync --mode update --outputs generated` (statements) from dsl/statements/ — DO NOT EDIT.\n# OWL 2 axiom-annotation downcast of GMEOW's canonical RDF 1.2 statement metadata.\n";
const RDF12_BANNER: &str = "# RDF 1.2 / RDF* — GMEOW's canonical statement-level model, the lead serialization.\n# Generated natively by `gmeow-dev sync --mode update --outputs generated` (statements) from dsl/statements/.\n# DO NOT EDIT — author in dsl/statements/.\n";

/// An IRI in term position — the oxigraph-free replacement for
/// `oxigraph::model::NamedNode`. `Display` renders the N-Triples `<iri>` form (the
/// same form `NamedNode`'s `Display` produced, which `emit_owl` depends on).
#[derive(Clone, PartialEq, Eq)]
struct Iri(String);

impl Iri {
    fn as_str(&self) -> &str {
        &self.0
    }
}

impl std::fmt::Display for Iri {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "<{}>", self.0)
    }
}

/// An RDF object term — the oxigraph-free replacement for `oxigraph::model::Term` in
/// object position. `Display` renders the N-Triples form (`<iri>`, `"lex"`,
/// `"lex"@lang`, `"lex"^^<dt>`), byte-identical to the oxigraph `Term` `Display`
/// `emit_owl` and the reifier mint relied on.
#[derive(Clone, PartialEq, Eq)]
enum ObjTerm {
    Iri(String),
    Literal {
        lexical: String,
        datatype: String,
        language: Option<String>,
    },
}

impl std::fmt::Display for ObjTerm {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            ObjTerm::Iri(iri) => write!(f, "<{iri}>"),
            ObjTerm::Literal {
                lexical,
                datatype,
                language,
            } => {
                let escaped = escape_literal(lexical);
                match language {
                    Some(lang) => write!(f, "\"{escaped}\"@{lang}"),
                    None if datatype == "http://www.w3.org/2001/XMLSchema#string" => {
                        // oxigraph `Term` Display omits the `^^xsd:string` datatype
                        // for a plain string literal — match that exactly.
                        write!(f, "\"{escaped}\"")
                    }
                    None => write!(f, "\"{escaped}\"^^<{datatype}>"),
                }
            }
        }
    }
}

/// Escape a literal lexical form for the N-Triples quoted-string Display.
fn escape_literal(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            other => out.push(other),
        }
    }
    out
}

/// A quoted base triple `<<( s p o )>>` of a reified statement.
#[derive(Clone)]
struct QuotedTriple {
    subject: Iri,
    predicate: Iri,
    object: ObjTerm,
}

/// One reified statement: quoted triple + reifier + sorted annotations.
struct StatementCell {
    reifier: Iri,
    triple: QuotedTriple,
    /// `(annProperty, annValue)` pairs, sorted by `(prop, value-n3)`.
    annotations: Vec<(Iri, ObjTerm)>,
}

/// Compile the statement DSL under `root` into `(owl_ttl, rdf12_ttl)`, both
/// banner-prefixed. The OWL form is the axiom-annotation downcast; the RDF 1.2
/// form is materialized from it by the native codec.
pub fn compile_statements(root: &Path) -> Result<(String, String), gmeow_errors::Diag> {
    let store = parse_statement_dsl(root)?;
    let mut cells = extract_cells(&store)?;
    // Deterministic: by reifier IRI.
    cells.sort_by(|a, b| a.reifier.as_str().cmp(b.reifier.as_str()));

    let owl_ntriples = emit_owl(&cells);
    let rdf12 = purrdf::statements::project_owl_to_rdf12(&owl_ntriples).map_err(|e| {
        gmeow_errors::Diag::of_kind(crate::error::StageFailed {
            stage: "stage-statements".to_string(),
            message: format!("OWL → RDF 1.2 projection failed: {e}"),
        })
    })?;

    let owl_out = format!("{OWL_BANNER}{}\n", owl_ntriples.trim_end());
    let rdf12_out = format!("{RDF12_BANNER}{}\n", rdf12.trim_end());
    Ok((owl_out, rdf12_out))
}

/// Compile statement artifacts and fold their diagnostics into the native report.
///
/// This is the Rust-owned implementation behind the Python feedback surface:
/// Python supplies the already-loaded ontology graph as N-Triples, but parsing,
/// statement compilation, invariant checking, RDF 1.2 normalization, lossless
/// comparison, and compile-error reporting all happen here.
pub fn compile_diagnostics_report(root: &Path, ontology_nt: &str) -> gmeow_errors::Report {
    let mut report = gmeow_errors::Report::new("statement-compile");
    let (owl_ttl, rdf12_ttl) = match compile_statements(root) {
        Ok(artifacts) => artifacts,
        Err(err) => {
            add_dsl_error(&mut report, err.to_string());
            return report;
        }
    };

    match invariant_findings(&owl_ttl, ontology_nt) {
        Ok(findings) => {
            for finding in findings {
                report.add_finding(finding);
            }
        }
        Err(err) => {
            add_dsl_error(&mut report, err.to_string());
            return report;
        }
    }

    let normalized_owl = match purrdf::statements::normalize_rdf12_to_owl(&rdf12_ttl) {
        Ok(normalized) => normalized,
        Err(err) => {
            add_dsl_error(&mut report, format!("RDF 1.2 normalization failed: {err}"));
            return report;
        }
    };

    match lossless_findings(&owl_ttl, &normalized_owl) {
        Ok(findings) => {
            for finding in findings {
                report.add_finding(finding);
            }
        }
        Err(err) => add_dsl_error(&mut report, err.to_string()),
    }
    report
}

fn add_dsl_error(report: &mut gmeow_errors::Report, message: String) {
    report.add_finding(
        gmeow_errors::Finding::new(
            gmeow_errors::Severity::Error,
            "statement-compile.dsl-error",
            message,
        )
        .with_tool("statement-compile"),
    );
}

fn invariant_findings(
    statement_owl_ttl: &str,
    ontology_nt: &str,
) -> Result<Vec<gmeow_errors::Finding>, gmeow_errors::Diag> {
    // Union the emitted OWL (Turtle) with the ontology (N-Triples) in one default-graph
    // native dataset — the exact union the Store version built by inserting both into one
    // store — then run the native invariant twin over it.
    let owl = turtle_bytes_to_dataset(statement_owl_ttl.as_bytes(), "statement OWL")?;
    let ontology = crate::stages::source_load::rdf_bytes_to_dataset(
        ontology_nt.as_bytes(),
        "application/n-triples",
        "ontology N-Triples",
    )?;
    let ds = RdfDataset::union(&[owl.as_ref(), ontology.as_ref()]);
    Ok(gmeow_validate::statement::check_statement_invariants_dataset(&ds))
}

fn lossless_findings(
    authored_owl_ttl: &str,
    normalized_owl_ttl: &str,
) -> Result<Vec<gmeow_errors::Finding>, gmeow_errors::Diag> {
    let authored = turtle_bytes_to_dataset(authored_owl_ttl.as_bytes(), "authored OWL")?;
    let normalized = turtle_bytes_to_dataset(normalized_owl_ttl.as_bytes(), "normalized OWL")?;
    Ok(gmeow_validate::statement::check_statement_lossless_dataset(
        &authored,
        &normalized,
    ))
}

/// The sorted `dsl/statements/*.ttl` source files (the leaf's raw inputs — folded
/// into the cache key via `input_files` so a DSL edit busts the cache).
pub fn statement_dsl_files(root: &Path) -> Result<Vec<std::path::PathBuf>, gmeow_errors::Diag> {
    let dir = root.join("dsl").join("statements");
    if !dir.is_dir() {
        return Ok(Vec::new());
    }
    let mut files: Vec<std::path::PathBuf> = Vec::new();
    // Fail-fast on a read_dir entry error: a transient FS error must surface, not
    // silently drop a DSL file (no-optionality).
    for entry in std::fs::read_dir(&dir)? {
        let path = entry?.path();
        if path.extension().is_some_and(|x| x == "ttl") {
            files.push(path);
        }
    }
    files.sort();
    Ok(files)
}

/// Parse every `dsl/statements/*.ttl` into one frozen native dataset.
///
/// Each file is parsed standalone and the per-file datasets are merged via
/// [`RdfDataset::union`], which standardizes blank scopes apart per input — the native
/// twin of the old per-source blank-prefix scoping (annotation cells use anonymous
/// blanks that restart at `_:gts_0` each parse, so distinct DSL files must not merge
/// them).
fn parse_statement_dsl(root: &Path) -> Result<Arc<RdfDataset>, gmeow_errors::Diag> {
    let mut parsed: Vec<Arc<RdfDataset>> = Vec::new();
    for path in statement_dsl_files(root)? {
        let bytes = std::fs::read(&path)?;
        let dataset = turtle_bytes_to_dataset(&bytes, &path.display().to_string())?;
        parsed.push(dataset);
    }
    let refs: Vec<&RdfDataset> = parsed.iter().map(|d| d.as_ref()).collect();
    Ok(Arc::new(RdfDataset::union(&refs)))
}

/// Extract every `gmeow:StatementMetadata` cell from the dataset.
fn extract_cells(ds: &RdfDataset) -> Result<Vec<StatementCell>, gmeow_errors::Diag> {
    let mut cells = Vec::new();
    let (Some(type_id), Some(class_id)) = (
        ds.term_id_by_value(&TermValue::iri(RDF_TYPE)),
        ds.term_id_by_value(&TermValue::iri(format!("{GMEOW}StatementMetadata"))),
    ) else {
        return Ok(cells);
    };
    for q in ds.quads_for_pattern(None, Some(type_id), Some(class_id), GraphMatch::Default) {
        let TermRef::Iri(cell) = ds.resolve(q.s) else {
            return Err(gmeow_errors::Diag::of_kind(crate::error::Parse {
                message: "statement metadata cell must be a named IRI".to_string(),
            }));
        };
        let cell = Iri(cell.to_owned());
        cells.extend(parse_cell(ds, &cell)?);
    }
    Ok(cells)
}

/// Parse one `gmeow:StatementMetadata` cell into one StatementCell per reifier.
///
/// RDF 1.2 permits several reifiers per statement: one proposition (the quoted
/// base triple) may be put forward by several claim tokens. Each authored
/// `gmeow:reifier` becomes its own `owl:Axiom` node reifying the shared triple
/// and carrying the cell's annotations; a cell with no authored reifier mints a
/// single deterministic one. The base triple and annotations are parsed once and
/// cloned per reifier.
fn parse_cell(ds: &RdfDataset, cell: &Iri) -> Result<Vec<StatementCell>, gmeow_errors::Diag> {
    let cell_id = ds
        .term_id_by_value(&TermValue::iri(cell.as_str()))
        .ok_or_else(|| cell_err(cell, "metadata cell IRI vanished from dataset"))?;
    let subject = single_named(ds, cell_id, cell, &format!("{GMEOW}qSubject"))?
        .ok_or_else(|| cell_err(cell, "missing an IRI qSubject"))?;
    let predicate = single_named(ds, cell_id, cell, &format!("{GMEOW}qPredicate"))?
        .ok_or_else(|| cell_err(cell, "missing an IRI qPredicate"))?;
    let obj_iri = single_object(ds, cell_id, cell, &format!("{GMEOW}qObject"))?;
    let obj_lit = single_object(ds, cell_id, cell, &format!("{GMEOW}qObjectLiteral"))?;
    let object = match (obj_iri, obj_lit) {
        (Some(o), None) | (None, Some(o)) => o,
        _ => {
            return Err(cell_err(
                cell,
                "needs exactly one of qObject / qObjectLiteral",
            ));
        }
    };
    let triple = QuotedTriple {
        subject,
        predicate,
        object,
    };
    let mut reifiers = all_named(ds, cell_id, cell, &format!("{GMEOW}reifier"))?;
    if reifiers.is_empty() {
        reifiers.push(mint_reifier(&triple)?);
    }
    // Deterministic across reifiers within a cell.
    reifiers.sort_by(|a, b| a.as_str().cmp(b.as_str()));
    reifiers.dedup();
    let mut annotations = parse_annotations(ds, cell_id, cell)?;
    annotations.sort_by(|a, b| (a.0.as_str(), term_n3(&a.1)).cmp(&(b.0.as_str(), term_n3(&b.1))));
    Ok(reifiers
        .into_iter()
        .map(|reifier| StatementCell {
            reifier,
            triple: triple.clone(),
            annotations: annotations.clone(),
        })
        .collect())
}

fn parse_annotations(
    ds: &RdfDataset,
    cell_id: purrdf::TermId,
    cell: &Iri,
) -> Result<Vec<(Iri, ObjTerm)>, gmeow_errors::Diag> {
    let Some(ann_pred_id) = ds.term_id_by_value(&TermValue::iri(format!("{GMEOW}annotation")))
    else {
        return Ok(Vec::new());
    };
    let mut out = Vec::new();
    // Materialize the annotation-node ids first so the borrow of `ds` from the pattern
    // iterator ends before the per-node sub-queries (which also borrow `ds`).
    let ann_node_ids: Vec<purrdf::TermId> = ds
        .quads_for_pattern(Some(cell_id), Some(ann_pred_id), None, GraphMatch::Default)
        .map(|q| q.o)
        .collect();
    for ann_id in ann_node_ids {
        // The annotation node is an IRI or a blank node (the `[ ... ]` cell).
        match ds.resolve(ann_id) {
            TermRef::Iri(_) | TermRef::Blank { .. } => {}
            _ => return Err(cell_err(cell, "annotation must be a node")),
        }
        let prop = single_named(ds, ann_id, cell, &format!("{GMEOW}annProperty"))?
            .ok_or_else(|| cell_err(cell, "annotation missing an IRI annProperty"))?;
        let value = single_object(ds, ann_id, cell, &format!("{GMEOW}annValue"))?
            .ok_or_else(|| cell_err(cell, "annotation missing annValue"))?;
        out.push((prop, value));
    }
    Ok(out)
}

/// Emit the OWL axiom-annotation form as N-Triples (a Turtle subset), sorted.
fn emit_owl(cells: &[StatementCell]) -> String {
    let mut lines: Vec<String> = Vec::new();
    for cell in cells {
        let s = cell.triple.subject.to_string();
        let p = cell.triple.predicate.to_string();
        let o = cell.triple.object.to_string();
        let ax = cell.reifier.to_string();
        lines.push(format!("{s} {p} {o} ."));
        lines.push(format!("{ax} <{RDF_TYPE}> <{OWL}Axiom> ."));
        lines.push(format!("{ax} <{OWL}annotatedSource> {s} ."));
        lines.push(format!("{ax} <{OWL}annotatedProperty> {p} ."));
        lines.push(format!("{ax} <{OWL}annotatedTarget> {o} ."));
        for (prop, value) in &cell.annotations {
            lines.push(format!("{ax} {} {} .", prop, value));
        }
    }
    lines.sort();
    lines.dedup();
    lines.join("\n")
}

/// Mint a deterministic reifier IRI: `sha1(n3(s) " " n3(p) " " n3(o))`. Mirrors
/// the Python `mint_reifier` so an unauthored reifier is stable across compiles. The
/// `Display` of [`Iri`]/[`ObjTerm`] reproduces the oxigraph `Term` N-Triples form the
/// old `mint_reifier` hashed, keeping minted IRIs byte-identical across the cutover.
fn mint_reifier(triple: &QuotedTriple) -> Result<Iri, gmeow_errors::Diag> {
    let s = triple.subject.to_string();
    let p = triple.predicate.to_string();
    let o = term_n3(&triple.object);
    let canonical = format!("{s} {p} {o}");
    let digest = hex_lower(&Sha1::digest(canonical.as_bytes()));
    Ok(Iri(format!("{GMEOW}reifier/{digest}")))
}

