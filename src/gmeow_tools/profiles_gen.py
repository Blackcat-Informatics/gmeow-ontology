"""The ``profiles`` generator: IRI-addressable ontology profiles (#330).

The IRI doctrine's composition leg: term IRIs are flat-forever (identity),
``isDefinedBy`` names the owning slice (ownership), and PROFILE IRIs are
generated ``owl:imports`` closures (composition). The root IRI is the CORE
profile (its imports list is gated by tests against the manifests);
``<…/gmeow/full>`` is the everything-aggregation emitted here; named
profiles (``<…/gmeow/profiles/<name>>``) materialize whenever a manifest
declares ``gmeow:sliceProfile`` membership. A slice that exists without
appearing in its profiles is impossible by construction.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from gmeow_tools.config import (
    FULL_PROFILE_IRI,
    NAMED_PROFILE_NS,
    ONTOLOGY_IRI,
    PROFILES_DIR,
    PROJECT_ROOT,
    SLICES_DIR,
)
from gmeow_tools.generator import Generator, register
from gmeow_tools.slices import Slice, discover_slices

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path


def group_named_profiles(slices: dict[str, Slice]) -> dict[str, list[str]]:
    """Profile name → member slice IRIs, from manifest declarations."""
    out: dict[str, list[str]] = {}
    for slice_ in slices.values():
        if slice_.profile:
            out.setdefault(slice_.profile, []).append(slice_.iri)
    return {name: sorted(iris) for name, iris in sorted(out.items())}


def _profile_document(iri: str, label: str, comment: str, imports: list[str]) -> str:
    """Render one profile ontology document (Turtle)."""
    lines = [
        "# GENERATED by gmeow profiles — DO NOT EDIT (#330).",
        "# Composition lives in profile IRIs; membership derives from the",
        "# slice manifests. https://github.com/Blackcat-Informatics/gmeow-ontology",
        "",
        "@prefix owl:  <http://www.w3.org/2002/07/owl#> .",
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
        "",
        f"<{iri}>",
        "    a owl:Ontology ;",
        f'    rdfs:label "{label}"@en ;',
        f'    skos:definition "{comment}"@en ;',
        f"    rdfs:isDefinedBy <{iri}> ;",
        "    owl:imports",
    ]
    lines.extend(f"        <{imp}> ," for imp in imports[:-1])
    lines.append(f"        <{imports[-1]}> .")
    return "\n".join(lines) + "\n"


def render_profiles() -> dict[str, str]:
    """Render every profile document: relative filename → Turtle text."""
    slices = discover_slices()
    extensions = sorted(s.iri for s in slices.values() if not s.is_core)

    out: dict[str, str] = {
        "full.ttl": _profile_document(
            FULL_PROFILE_IRI,
            "GMEOW — full profile",
            "The everything-aggregation: the core profile (the root IRI's "
            "generated tierCore closure) plus every extension slice. The "
            "kitchen-sink consumer's single import target, and the input "
            "to the global reasoning gate.",
            [ONTOLOGY_IRI, *extensions],
        )
    }
    for name, members in group_named_profiles(slices).items():
        out[f"{name}.ttl"] = _profile_document(
            NAMED_PROFILE_NS + name,
            f"GMEOW — {name} profile",
            f"The {name} profile: a declared slice set aggregated as its own "
            "dereferenceable, citable, reasonable ontology. Membership is "
            "declared per-slice with gmeow:sliceProfile.",
            [ONTOLOGY_IRI, *members],
        )
    return out


@register
class ProfilesGenerator(Generator):
    """Emit the profile ontology documents from the slice manifests."""

    name: str = "profiles"

    @property
    def inputs(self) -> Sequence[Path]:
        """Membership derives from the manifests alone."""
        return sorted(SLICES_DIR.glob("*/*/manifest.ttl"))

    @property
    def outputs(self) -> Sequence[Path]:
        """One document per profile (full + named)."""
        return [PROFILES_DIR / name for name in render_profiles()]

    def render(self, staging: Path) -> None:
        """Render every profile document into the staging tree."""
        target_dir = staging / PROFILES_DIR.relative_to(PROJECT_ROOT)
        target_dir.mkdir(parents=True, exist_ok=True)
        for name, text in render_profiles().items():
            (target_dir / name).write_text(text, encoding="utf-8")
