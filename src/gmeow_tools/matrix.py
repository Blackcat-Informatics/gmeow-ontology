"""The module-status matrix — the audit ledger of the slice architecture.

A registered generator (#287) emitting ``generated/module-status.md``: one row
per slice with tier, dependency count, term counts, and documentation status
(full guide vs stub). The matrix keeps the #325 documentation-uplift gap and
the per-slice audit state *visible and tracked* instead of anecdotal.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from rdflib import RDF, Graph, URIRef
from rdflib.namespace import OWL
from rdflib.term import Node

from gmeow_tools.config import (
    GENERATED_DIR,
    LOGIC_NAMESPACE,
    NAMESPACE,
    PROJECT_ROOT,
    SLICES_DIR,
)
from gmeow_tools.generator import Generator, register
from gmeow_tools.slices import Slice, discover_slices

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path

MATRIX_FILE = GENERATED_DIR / "module-status.md"

_HEADER = (
    """<!-- GENERATED by gmeow matrix — DO NOT EDIT. -->

# Module status matrix

One row per slice (#287): tier and dependencies from the manifest, term counts
from the module, documentation status from the guide. STUB guides are the #325
Tier-2 uplift backlog.

"""
    "| slice | tier | group | deps | classes | props | individuals | examples "
    "| advice | guide |\n"
    "|---|---|---|---:|---:|---:|---:|---:|---:|---|\n"
)

_USE_WHEN = URIRef(NAMESPACE + "useWhen")
_HOW_TO_USE = URIRef(NAMESPACE + "howToUse")


def _term_counts(module: Path) -> tuple[int, int, int, int, int]:
    g = Graph()
    g.parse(module, format="turtle")

    def terms(kind: Node) -> set[Node]:
        # The logic slice authors its vocabulary in the canonical ``logic:``
        # namespace (Principle 17), not the ``gmeow:`` one, so its module-status
        # row must count both surfaces.
        subjects = (s for s in g.subjects(RDF.type, kind))
        return {
            s
            for s in subjects
            if str(s).startswith(NAMESPACE) or str(s).startswith(LOGIC_NAMESPACE)
        }

    classes = terms(OWL.Class)
    property_terms = (
        terms(OWL.ObjectProperty)
        | terms(OWL.DatatypeProperty)
        | terms(OWL.AnnotationProperty)
    )
    public_terms = classes | property_terms
    advisory_complete = sum(
        1
        for term in public_terms
        if (term, _USE_WHEN, None) in g and (term, _HOW_TO_USE, None) in g
    )
    props = (
        len(terms(OWL.ObjectProperty))
        + len(terms(OWL.DatatypeProperty))
        + len(terms(OWL.AnnotationProperty))
    )
    return (
        len(classes),
        props,
        len(terms(OWL.NamedIndividual)),
        advisory_complete,
        len(public_terms),
    )


def _guide_status(s: Slice) -> str:
    doc = s.path / "docs.md"
    if not doc.exists():
        return "MISSING"
    if "This is a STUB guide" in doc.read_text(encoding="utf-8"):
        return "stub"
    return "full"


def render_matrix() -> str:
    """Render the matrix table body plus the summary footer."""
    slices = discover_slices()
    rows: list[str] = []
    stubs = 0
    advisory_done = 0
    advisory_total = 0
    for s in slices.values():
        classes, props, inds, slice_advisory_done, slice_advisory_total = _term_counts(
            s.module_path
        )
        guide = _guide_status(s)
        stubs += guide == "stub"
        examples = len(list((s.path / "examples").glob("*.ttl")))
        if s.tier == "core":
            advisory_done += slice_advisory_done
            advisory_total += slice_advisory_total
            advisory = f"{slice_advisory_done}/{slice_advisory_total}"
        else:
            advisory = "-"
        rows.append(
            f"| {s.name} | {s.tier} | {s.group} | {len(s.depends_on)} "
            f"| {classes} | {props} | {inds} | {examples} | {advisory} | {guide} |"
        )
    footer = (
        f"\n**{len(slices)} slices** · documentation: "
        f"{len(slices) - stubs} full guides, {stubs} stubs remaining (#325); "
        f"advisory coverage: {advisory_done}/{advisory_total} core "
        f"class/property terms (#471).\n"
    )
    return "\n".join(rows) + "\n" + footer


@register
class MatrixGenerator(Generator):
    """Emit the module-status matrix from manifests + modules + guides."""

    name: str = "matrix"

    @property
    def inputs(self) -> Sequence[Path]:
        """Manifests, modules, guides, and examples drive the matrix."""
        return [
            *sorted(SLICES_DIR.glob("*/*/manifest.ttl")),
            *sorted(SLICES_DIR.glob("*/*/module.ttl")),
            *sorted(SLICES_DIR.glob("*/*/docs.md")),
            *sorted(SLICES_DIR.glob("*/*/examples/*.ttl")),
        ]

    @property
    def outputs(self) -> Sequence[Path]:
        """The single committed matrix file."""
        return [MATRIX_FILE]

    def render(self, staging: Path) -> None:
        """Write the matrix into the staging tree."""
        out = staging / MATRIX_FILE.relative_to(PROJECT_ROOT)
        out.parent.mkdir(parents=True, exist_ok=True)
        # No source-hash banner: the matrix is a pure function of its visible
        # columns, so it churns (and conflicts) only when those columns actually
        # change — not on every unrelated edit to any input file.
        out.write_text(_HEADER + render_matrix(), encoding="utf-8")
