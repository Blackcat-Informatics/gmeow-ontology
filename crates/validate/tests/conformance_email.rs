/// Twin of `test_fixture_version_memberships_use_roles_not_subclasses`: canonical
/// vs. variant status is carried by the cross-cutting `VersionMembership` relator
/// (roles, not email-specific subclasses). The `OPTIONAL { … versionScale … }`
/// cell is bound (`scaleMinor`) for the variant membership and UNBOUND for the
/// canonical one.
///
/// This is the explicit unbound-OPTIONAL-cell assertion: we run `.select`
/// directly (rather than a row-set builder) and assert the canonical membership's
/// `?scale` cell is `None`, so an accidentally-bound cell would fail here.
#[test]
fn version_memberships_use_roles_not_subclasses() {
    let g = email_store();
    let (vars, rows) = g.select(
        &[("set".to_owned(), iri(&ex_mail("msgVersionSet")))],
        "PREFIX gmeow: <https://blackcatinformatics.ca/gmeow/> \
         SELECT ?membership ?msg ?role ?scale WHERE { \
             ?membership a gmeow:VersionMembership ; \
                         gmeow:versionSet ?set ; \
                         gmeow:versionMember ?msg ; \
                         gmeow:versionRole ?role . \
             OPTIONAL { ?membership gmeow:versionScale ?scale . } }",
    );
    assert_eq!(vars, vec!["membership", "msg", "role", "scale"]);

    // Locate the single row for a given ?msg (col 1); return (role, scale) cells.
    let row_for = |msg: &str| -> (Option<TermValue>, Option<TermValue>) {
        let matching: Vec<&Vec<Option<TermValue>>> = rows
            .iter()
            .filter(|r| r.get(1) == Some(&Some(iri(msg))))
            .collect();
        assert_eq!(
            matching.len(),
            1,
            "expected exactly one membership row for {msg}"
        );
        let r = matching[0];
        (r[2].clone(), r[3].clone())
    };

    let (canonical_role, canonical_scale) = row_for(&ex_mail("msgCanonical"));
    assert_eq!(canonical_role, Some(iri(&gm("roleCanonical"))));
    // The canonical membership has NO versionScale — the OPTIONAL cell is UNBOUND.
    assert_eq!(
        canonical_scale, None,
        "canonical membership must leave the OPTIONAL ?scale cell unbound"
    );

    let (variant_role, variant_scale) = row_for(&ex_mail("msgVariant"));
    assert_eq!(variant_role, Some(iri(&gm("roleVariant"))));
    assert_eq!(variant_scale, Some(iri(&gm("scaleMinor"))));
}

/// Twin of `test_fixture_patch_diff_links_and_digest`: the variant links to an
/// `EmailPatchDiff` artifact derived from the canonical body, carrying its media
/// type and a blake3 content digest.
#[test]
fn patch_diff_links_and_digest() {
    let g = email_store();
    let variant = ex_mail("msgVariant");
    let patch = ex_mail("variantPatch");
    assert!(g.has(Some(&variant), Some(&gm("hasPatchDiff")), Some(&patch)));
    assert!(g.has(Some(&patch), Some(RDF_TYPE), Some(&gm("EmailPatchDiff"))));
    assert!(g.has_literal(&patch, &gm("mediaType"), "text/x-gmeow-patch", XSD_STRING));
    assert!(g.has(
        Some(&patch),
        Some(&gm("wasDerivedFrom")),
        Some(&ex_mail("msgCanonicalBody")),
    ));
    assert!(g.has_literal(
        &patch,
        &gm("contentDigest"),
        "blake3:patch-bytes",
        XSD_STRING,
    ));
}

/// Twin of `test_fixture_collision_flags_and_fingerprints`: both canonical and
/// variant carry the Message-ID collision flag and their respective blake3
/// fingerprints; the variant additionally records its body-only analysis scope
/// and the input body line.
#[test]
fn collision_flags_and_fingerprints() {
    let g = email_store();
    let canonical = ex_mail("msgCanonical");
    let variant = ex_mail("msgVariant");
    assert!(g.has_literal(&canonical, &gm("messageIdCollision"), "true", XSD_BOOLEAN));
    assert!(g.has_literal(&variant, &gm("messageIdCollision"), "true", XSD_BOOLEAN));
    assert!(g.has_literal(
        &canonical,
        &gm("canonicalFingerprint"),
        "blake3:canonical-body-hash",
        XSD_STRING,
    ));
    assert!(g.has_literal(
        &variant,
        &gm("bodyLineFingerprint"),
        "blake3:variant-body-line-hash",
        XSD_STRING,
    ));
    assert!(g.has_literal(&variant, &gm("analysisScope"), "body-only", XSD_STRING));
    assert!(g.has_literal(
        &variant,
        &gm("analysisInputBodyLine"),
        "Please review the attached Q2 report.",
        XSD_STRING,
    ));
}
