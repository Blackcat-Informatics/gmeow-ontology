//! Compile-time string comparison for the assertions this leaf and its dependents
//! make about constants that must name the same value.

/// Byte equality of two strings in const context: the compile-time proof that two
/// constants which must name the same value have not drifted apart.
#[must_use]
pub const fn const_str_eq(a: &str, b: &str) -> bool {
    let (a, b) = (a.as_bytes(), b.as_bytes());
    if a.len() != b.len() {
        return false;
    }
    let mut i = 0;
    while i < a.len() {
        if a[i] != b[i] {
            return false;
        }
        i += 1;
    }
    true
}
