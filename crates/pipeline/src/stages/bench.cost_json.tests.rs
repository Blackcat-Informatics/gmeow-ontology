#[test]
fn json_bench_cost_sort_order_is_independent_of_record_and_ledger_input_order() {
    let case = r#"{"corpus":"Z","case":"Z","fragment":"backward","native":{"consumed_steps":1,"answer_count":2,"alloc_bytes":3,"alloc_count":4,"peak_live_bytes":5,"cost_vector":[]},"agreement":{"native_vs_golden":true}}"#;
    let prefix = SIMPLE.find(r#""cases":["#).unwrap() + r#""cases":["#.len();
    let end = SIMPLE.find(r#"],"rule_parallelism":"#).unwrap();
    let first = &SIMPLE[prefix..end];
    let tally = r#"{"cases":1,"agree":1,"corpus_only":0,"dl_gap":0,"finding_count":1,"finding_graph_blake3":"D"}"#;
    let input = SIMPLE
        .replace(
            &format!(r#""cases":[{first}]"#),
            &format!(r#""cases":[{case},{first}]"#),
        )
        .replace(
            &format!(r#""ledgers":{{"C":{tally}}}"#),
            &format!(r#""ledgers":{{"Z":{tally},"C":{tally}}}"#),
        )
        .replacen(r#""case_count":1"#, r#""case_count":2"#, 1);
    let reversed = input
        .replace(
            &format!(r#""cases":[{case},{first}]"#),
            &format!(r#""cases":[{first},{case}]"#),
        )
        .replace(
            &format!(r#""ledgers":{{"Z":{tally},"C":{tally}}}"#),
            &format!(r#""ledgers":{{"C":{tally},"Z":{tally}}}"#),
        );
    let (ledger, soak) = rendered(&input).unwrap();
    assert_eq!((ledger.clone(), soak), rendered(&reversed).unwrap());
    assert!(
        ledger.find("| C | A | backward").unwrap() < ledger.find("| Z | Z | backward").unwrap()
    );
    assert!(
        ledger.find("| C | 1 | 1 | 0 | 0 | 1 | D |").unwrap()
            < ledger.find("| Z | 1 | 1 | 0 | 0 | 1 | D |").unwrap()
    );
    let extra_comparisons = SIMPLE.replace(r#""cases":1,"agree":1"#, r#""cases":3,"agree":3"#);
    assert!(rendered(&extra_comparisons).is_ok());
}

