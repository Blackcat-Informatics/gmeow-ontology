"""``gmeow create-docs`` — browsable docs tree from a GTS snapshot (#439).

A lossy, deterministic Markdown projection of the ontology plus the bundled
slice guides, and the full ontology-docs site (the ``ontology-docs`` blob the
snapshot stage embeds, #897) carried by the offline snapshot.
"""

from __future__ import annotations

import io
import tarfile
from pathlib import Path
from typing import TYPE_CHECKING

from gmeow_tools.config import FULL_PROFILE_IRI, NAMESPACE, ONTOLOGY_IRI, PREFIXES
from gmeow_tools.export import Term, collect_terms, curie, fold_meta, marked
from gmeow_tools.gts_views import FoldView, load_fold

if TYPE_CHECKING:
    from gmeow_tools.language_tags import LangSelector

_RDFS_IS_DEFINED_BY = "http://www.w3.org/2000/01/rdf-schema#isDefinedBy"

_BANNER = (
    "> Generated by ``gmeow create-docs``. The OWL source is canonical; this tree "
    "is a lossy projection for human browsing.\n\n"
)


def resolve_doc_language(
    selector: LangSelector | None = None, tag_map: dict[str, str] | None = None
) -> str:
    """Return the internal documentation language tag for *selector*.

    The first requested public BCP-47 tag that maps to an internal tag is used;
    otherwise the English fallback is returned.
    """
    if selector is not None and tag_map is not None:
        public_to_internal = {v: k for k, v in tag_map.items()}
        for public in selector.requested:
            if public in public_to_internal:
                return public_to_internal[public]
    return "x-gmeow-english"


def _safe_filename(curie_str: str) -> str:
    return f"{curie_str.replace(':', '-')}.md"


def _expand_curie(curie_str: str) -> str:
    """Expand a CURIE to a full IRI using the configured prefix map."""
    if ":" not in curie_str:
        return curie_str
    prefix, local = curie_str.split(":", 1)
    ns = PREFIXES.get(prefix)
    if ns is None:
        return curie_str
    return ns + local


def _link(curie_str: str) -> str:
    """Markdown link for a CURIE when the prefix is known, else plain text."""
    if ":" not in curie_str:
        return curie_str
    prefix = curie_str.split(":", 1)[0]
    if prefix not in PREFIXES:
        return f"`{curie_str}`"
    return f"[`{curie_str}`]({_expand_curie(curie_str)})"


def _defined_by(view: FoldView, tid: int) -> str:
    """CURIE of the owning slice/module, or empty string."""
    owner_tid = view.value(tid, _RDFS_IS_DEFINED_BY)
    if owner_tid is None:
        return ""
    return curie(view.lex(owner_tid))


def _append_usage_advice(lines: list[str], term: Term) -> None:
    """Append advisory metadata to a generated per-term Markdown page."""
    fields = [
        ("Scope", term.scope_notes),
        ("Example", term.examples),
        ("Use when", term.use_when),
        ("Avoid when", term.avoid_when),
        ("How to use", term.how_to_use),
    ]
    consumer_fields = [
        ("Use for consumers", term.use_for_consumer),
        ("Avoid for consumers", term.avoid_for_consumer),
    ]
    if not any(values for _, values in fields + consumer_fields):
        return
    lines.append("## Usage Advice")
    lines.append("")
    for label, values in fields:
        if values:
            lines.append(f"- **{label}:** " + " ".join(values))
    for label, values in consumer_fields:
        if values:
            lines.append(
                f"- **{label}:** " + ", ".join(_link(value) for value in values)
            )
    lines.append("")


def _write_index(
    out_dir: Path,
    view: FoldView,
    terms: list[Term],
    *,
    has_ontology_docs: bool = True,
) -> None:
    title, version = fold_meta(view)
    n_classes = sum(1 for t in terms if t.category == "class")
    n_properties = sum(1 for t in terms if t.category == "property")
    n_individuals = sum(1 for t in terms if t.category == "individual")

    lines = [
        f"# {title}",
        "",
        f"**Version:** `{version}`  ",
        f"**Namespace:** <{NAMESPACE}>  ",
        f"**Terms:** {n_classes} classes, {n_properties} properties, "
        f"{n_individuals} individuals",
        "",
        "## Profiles",
        "",
        f"- **Core profile:** <{ONTOLOGY_IRI}> — the root ontology IRI.",
        f"- **Full profile:** <{FULL_PROFILE_IRI}> — core plus extensions.",
        "",
        "## Layout",
        "",
        "- [`terms/`](terms/) — one Markdown file per GMEOW term.",
        "- [`slices/`](slices/) — per-slice guide documentation.",
    ]
    if has_ontology_docs:
        lines.append(
            "- [`ontology-docs/`](ontology-docs/) — the full ontology-docs site (#440)."
        )
    lines.extend(
        [
            "- [`alignments.md`](alignments.md) — alignment summary.",
            "- [`statements.md`](statements.md) — RDF 1.2 statement layer summary.",
            "",
        ]
    )
    (out_dir / "index.md").write_text("\n".join(lines), encoding="utf-8")


def _write_term_file(out_dir: Path, term: Term, view: FoldView) -> None:
    path = (
        out_dir / "terms" / _CATEGORY_DIRS[term.category] / _safe_filename(term.curie)
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    lines: list[str] = [
        "# " + marked(term.label or term.curie, term.label_fallback),
        "",
        _BANNER,
    ]

    if term.definition:
        lines.append(marked(term.definition, term.definition_fallback))
        lines.append("")

    term_tid = view.tid_of_iri(term.iri)
    if term_tid is not None:
        owner = _defined_by(view, term_tid)
        if owner:
            lines.append(f"*Defined by:* {_link(owner)}")
            lines.append("")

    _append_usage_advice(lines, term)

    if term.category == "class":
        if term.parents:
            lines.append("*Subclass of:* " + ", ".join(_link(p) for p in term.parents))
            lines.append("")
    elif term.category == "property":
        meta = [f"*{term.prop_kind} property*"]
        if term.domain or term.range:
            meta.append(f"`{term.domain or '?'}` → `{term.range or '?'}`")
        if term.functional:
            meta.append("functional")
        lines.append(" · ".join(meta))
        lines.append("")
        if term.sub_property_of:
            lines.append(
                "*Sub-property of:* "
                + ", ".join(_link(p) for p in term.sub_property_of)
            )
            lines.append("")
    else:  # individual
        if term.types:
            lines.append("*Type:* " + ", ".join(_link(t) for t in term.types))
            lines.append("")

    if term.alignments:
        lines.append("*Alignments:*")
        for align in term.alignments:
            if "=" in align:
                rel, obj = align.split("=", 1)
                lines.append(f"- `{rel}` {_link(obj)}")
            else:
                lines.append(f"- `{align}`")
        lines.append("")

    lines.append(f"*IRI:* <{term.iri}>")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


_CATEGORY_DIRS: dict[str, str] = {
    "class": "classes",
    "property": "properties",
    "individual": "individuals",
}


def _write_terms(out_dir: Path, view: FoldView, terms: list[Term]) -> None:
    for term in terms:
        _write_term_file(out_dir, term, view)


def _write_slice_guides(out_dir: Path, view: FoldView) -> None:
    for digest, meta in view.graph.blob_meta.items():
        rep = meta.get("rep")
        if not isinstance(rep, str) or not rep.startswith("docs:"):
            continue
        rel = rep[len("docs:") :]
        if "/" not in rel:
            continue
        group, name = rel.split("/", 1)
        path = out_dir / "slices" / group / name / "docs.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(view.graph.blobs[digest])


def _unpack_doc_archive(
    out_dir: Path, view: FoldView, rep: str, target_name: str, lang: str
) -> bool:
    extracted = False
    for digest, meta in view.graph.blob_meta.items():
        if meta.get("rep") != rep:
            continue
        raw = view.graph.blobs.get(digest)
        if raw is None:
            continue
        prefix = f"{lang}/"
        with tarfile.open(fileobj=io.BytesIO(raw), mode="r") as tar:
            for member in tar.getmembers():
                if not member.isfile() or not member.name.startswith(prefix):
                    continue
                rel = member.name[len(prefix) :]
                target = out_dir / target_name / rel
                target.parent.mkdir(parents=True, exist_ok=True)
                fileobj = tar.extractfile(member)
                if fileobj is not None:
                    target.write_bytes(fileobj.read())
                    extracted = True
        return extracted
    return extracted


def _write_alignments(out_dir: Path, terms: list[Term]) -> None:
    counts: dict[str, int] = {}
    examples: dict[str, list[str]] = {}
    for term in terms:
        for align in term.alignments:
            if "=" not in align:
                continue
            rel, obj = align.split("=", 1)
            counts[rel] = counts.get(rel, 0) + 1
            examples.setdefault(rel, []).append(f"`{term.curie}` → {_link(obj)}")

    lines = [
        "# Alignment summary",
        "",
        _BANNER,
        "| Relation | Count | Examples |",
        "|---|---|---|",
    ]
    for rel in sorted(counts):
        sample = ", ".join(examples[rel][:3])
        lines.append(f"| `{rel}` | {counts[rel]} | {sample} |")
    lines.append("")
    (out_dir / "alignments.md").write_text("\n".join(lines), encoding="utf-8")


def _write_statements(out_dir: Path, view: FoldView) -> None:
    reifiers = view.reifiers()
    annotations = view.annotations()
    pred_counts: dict[str, int] = {}
    for _, p, _ in annotations:
        pred = view.curie(view.lex(p))
        pred_counts[pred] = pred_counts.get(pred, 0) + 1

    lines = [
        "# RDF 1.2 statement layer summary",
        "",
        _BANNER,
        f"- **Reified statements:** {len(reifiers)}",
        f"- **Annotations:** {len(annotations)}",
        "",
        "## Annotation predicates",
        "",
    ]
    for pred, count in sorted(pred_counts.items(), key=lambda kv: (-kv[1], kv[0])):
        lines.append(f"- `{pred}`: {count}")
    lines.append("")
    (out_dir / "statements.md").write_text("\n".join(lines), encoding="utf-8")


def create_docs(
    gts_path: Path,
    out_dir: Path,
    *,
    force: bool = False,
    selector: LangSelector | None = None,
) -> None:
    """Write a deterministic browsable docs tree from a GTS snapshot."""
    if out_dir.exists() and any(out_dir.iterdir()) and not force:
        raise FileExistsError(
            f"output directory is not empty: {out_dir}; use force=True to overwrite"
        )
    out_dir.mkdir(parents=True, exist_ok=True)

    view = load_fold(gts_path)
    if selector is None:
        from gmeow_tools.language_tags import resolve_lang_input

        selector = resolve_lang_input(None, view.tag_map())
    doc_lang = resolve_doc_language(selector, view.tag_map())
    terms = collect_terms(view, selector=selector)

    has_ontology_docs = _unpack_doc_archive(
        out_dir, view, "ontology-docs", "ontology-docs", doc_lang
    )
    _write_index(out_dir, view, terms, has_ontology_docs=has_ontology_docs)
    _write_terms(out_dir, view, terms)
    _write_slice_guides(out_dir, view)
    _write_alignments(out_dir, terms)
    _write_statements(out_dir, view)
