/// The native object term at `(subject_id, predicate, ?)`, materialized as an owned
/// [`ObjTerm`] if it is an IRI or literal. Blank/triple-term objects map to `None`
/// here (no statement field accepts them; the callers below either require an IRI or
/// a literal/IRI value).
fn resolve_obj(ds: &RdfDataset, id: purrdf::TermId) -> Option<ObjTerm> {
    match ds.resolve(id) {
        TermRef::Iri(iri) => Some(ObjTerm::Iri(iri.to_owned())),
        TermRef::Literal {
            lexical,
            datatype,
            language,
            ..
        } => {
            let dt = match ds.resolve(datatype) {
                TermRef::Iri(iri) => iri.to_owned(),
                other => format!("{other:?}"),
            };
            Some(ObjTerm::Literal {
                lexical: lexical.to_owned(),
                datatype: dt,
                language: language.map(str::to_owned),
            })
        }
        TermRef::Blank { .. } | TermRef::Triple { .. } => None,
    }
}

/// The single object of `(subject_id, predicate, ?)` (IRI or literal), or `None` if
/// absent. More than one value is a hard error (no silent pick).
fn single_object(
    ds: &RdfDataset,
    subject_id: purrdf::TermId,
    subject: &Iri,
    predicate: &str,
) -> Result<Option<ObjTerm>, gmeow_errors::Diag> {
    let Some(p_id) = ds.term_id_by_value(&TermValue::iri(predicate)) else {
        return Ok(None);
    };
    let obj_ids: Vec<purrdf::TermId> = ds
        .quads_for_pattern(Some(subject_id), Some(p_id), None, GraphMatch::Default)
        .map(|q| q.o)
        .collect();
    if obj_ids.len() > 1 {
        return Err(gmeow_errors::Diag::of_kind(crate::error::Parse {
            message: format!(
                "{subject} has {} values for {predicate} — expected one",
                obj_ids.len()
            ),
        }));
    }
    match obj_ids.into_iter().next() {
        Some(id) => resolve_obj(ds, id).map(Some).ok_or_else(|| {
            // A blank-node / triple-term value where an IRI or literal was expected.
            cell_err(
                subject,
                &format!("{predicate} value must be an IRI or literal"),
            )
        }),
        None => Ok(None),
    }
}

/// The single IRI value of `(subject_id, predicate, ?)`, or `None` if absent. A
/// non-IRI value is a hard error.
fn single_named(
    ds: &RdfDataset,
    subject_id: purrdf::TermId,
    subject: &Iri,
    predicate: &str,
) -> Result<Option<Iri>, gmeow_errors::Diag> {
    match single_object(ds, subject_id, subject, predicate)? {
        Some(ObjTerm::Iri(iri)) => Ok(Some(Iri(iri))),
        Some(_) => Err(gmeow_errors::Diag::of_kind(crate::error::Parse {
            message: format!("{subject} {predicate} must be an IRI"),
        })),
        None => Ok(None),
    }
}

/// Every IRI value of `predicate` on `subject` (for multi-valued properties such
/// as `gmeow:reifier`, where RDF 1.2 allows several reifiers per statement). A
/// non-IRI value is a hard error (no silent skip).
fn all_named(
    ds: &RdfDataset,
    subject_id: purrdf::TermId,
    subject: &Iri,
    predicate: &str,
) -> Result<Vec<Iri>, gmeow_errors::Diag> {
    let Some(p_id) = ds.term_id_by_value(&TermValue::iri(predicate)) else {
        return Ok(Vec::new());
    };
    let obj_ids: Vec<purrdf::TermId> = ds
        .quads_for_pattern(Some(subject_id), Some(p_id), None, GraphMatch::Default)
        .map(|q| q.o)
        .collect();
    let mut out: Vec<Iri> = Vec::new();
    for id in obj_ids {
        match ds.resolve(id) {
            TermRef::Iri(iri) => out.push(Iri(iri.to_owned())),
            _ => {
                return Err(gmeow_errors::Diag::of_kind(crate::error::Parse {
                    message: format!("{subject} {predicate} must be an IRI"),
                }));
            }
        }
    }
    Ok(out)
}

/// An N3-style serialization of a term for content hashing (IRIs as `<iri>`,
/// literals as `"lex"`, `"lex"@lang`, or `"lex"^^<dt>`) — the [`ObjTerm`] `Display`
/// reproduces the oxigraph `Term` N-Triples form byte-for-byte.
fn term_n3(term: &ObjTerm) -> String {
    term.to_string()
}

fn cell_err(cell: &Iri, msg: &str) -> gmeow_errors::Diag {
    gmeow_errors::Diag::of_kind(crate::error::Parse {
        message: format!("statement {cell} {msg}"),
    })
}

fn hex_lower(bytes: &[u8]) -> String {
    let mut s = String::with_capacity(bytes.len() * 2);
    for b in bytes {
        s.push_str(&format!("{b:02x}"));
    }
    s
}

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `statements` pipeline stage.
pub struct StatementsStage;

impl Stage for StatementsStage {
    fn id(&self) -> &str {
        "stage-statements"
    }
    fn consumes(&self) -> &[String] {
        // Declared empty: the compiler reads dsl/statements/ from the root. The
        // dogfooded DAG wires it after source-load; the consumes-agreement check
        // is reconciled when source-load publishes the loaded dataset (P3 wiring).
        &[]
    }
    fn impl_version(&self) -> &str {
        // v2: the statement layer's JSON-LD-star / YAML-LD-star projections join the
        // product on the INTERNAL `pipeline/statements/` lane, so `stage-archive-blobs`
        // folds them into the bundle's `yaml-ld-archive` frame without a second render.
        "statements.v2"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<std::path::PathBuf>, gmeow_errors::Diag> {
        // Raw source read: the RDF-1.2 statement cells come from `dsl/statements/`,
        // which no upstream product reflects. Declare them so a DSL edit busts the
        // cache. `consumes() == []` (the leaf reads sources, not upstream products).
        statement_dsl_files(root)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, gmeow_errors::Diag> {
        let (owl, rdf12) = compile_statements(input.root)?;
        // Carry the RDF 1.2 statement layer as the bundle's frozen dataset (the
        // contribution `gts_compose` unions over the base graph). Parsing the rdf12
        // Turtle folds the statement layer — `rdf:reifies` triple-term objects become
        // reifier bindings and the reifiers' other triples become annotations — so
        // the side-tables ride in the dataset, not flattened into base quads. The
        // OWL_PATH / RDF12_PATH byte lanes are kept for the pre-C3 byte readers.
        let dataset =
            purrdf::parse_dataset(rdf12.as_bytes(), "text/turtle", None).map_err(|e| {
                gmeow_errors::Diag::of_kind(crate::error::Parse {
                    message: format!("RDF 1.2 statement-layer parse: {e}"),
                })
            })?;
        // The claim corpus's JSON-LD-family surface, rendered ONCE here (the
        // transform-once razor) from the SAME frozen statement dataset the Turtle lead
        // parsed into — never re-derived downstream, and never from the committed file,
        // which is not flushed until the post-run reconcile returns. `stage-archive-blobs`
        // tars these two into the bundle's `yaml-ld-archive` frame, the frame
        // that rides unprimed: a JSON-LD-family consumer reads the reified
        // statement layer directly, in the syntax whose distinguishing repeated substrings
        // (the reifier IRIs, the `gmeow:qSubject`/`qPredicate`/`qObject` coat, the
        // standpoint qualifiers) are exactly what that dictionary is trained on.
        let jsonld = crate::stages::yaml_ld::serialize_graph(dataset.as_ref())?;
        let yamlld = crate::stages::yaml_ld::serialize_graph_yaml(dataset.as_ref(), None)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(OWL_PATH.to_string(), owl.into_bytes());
        artifacts.insert(RDF12_PATH.to_string(), rdf12.into_bytes());
        artifacts.insert(RDF12_JSONLD_PATH.to_string(), jsonld.into_bytes());
        artifacts.insert(RDF12_YAMLLD_PATH.to_string(), yamlld.into_bytes());
        Ok(StageOutput::new(StageProduct::from_artifacts_over(
            self.id(),
            dataset,
            artifacts,
        )))
    }
}
