/// Twin of `test_resent_properties_are_multivalued_in_linkml_schema`.
///
/// NON-RDF: this exercises the generated LinkML projection surface, not SPARQL.
/// The non-functional `resentDate` / `resentMessageId` datatype properties must
/// compile to `multivalued: true` slots. We read
/// `generated/schemas/gmeow.linkml.yaml` into a `serde_yaml::Value` and navigate
/// the top-level `slots` map (`slots.<name>.multivalued`), mirroring the Python
/// `schema.get("slots", {})...get("multivalued") is True` assertions exactly.
#[test]
fn resent_properties_are_multivalued_in_linkml_schema() {
    let path = repo_root().join("generated/schemas/gmeow.linkml.yaml");
    let text = std::fs::read_to_string(&path)
        .unwrap_or_else(|e| panic!("failed to read {}: {e}", path.display()));
    let schema: serde_yaml::Value =
        serde_yaml::from_str(&text).expect("gmeow.linkml.yaml must parse as YAML");
    let slots = schema
        .get("slots")
        .expect("LinkML schema must carry a top-level `slots` map");
    for slot in ["resentDate", "resentMessageId"] {
        let multivalued = slots
            .get(slot)
            .unwrap_or_else(|| panic!("slot {slot:?} must exist in the LinkML `slots` map"))
            .get("multivalued")
            .and_then(serde_yaml::Value::as_bool);
        assert_eq!(
            multivalued,
            Some(true),
            "non-functional slot {slot:?} must be `multivalued: true`"
        );
    }
}

/// Twin of `test_fixture_binds_occurrence_correctly`: the same address
/// (`addrAlice`) appears in msg1 as `messageRoleFrom` with display name
/// "Alice Smith" and in msg2 as `messageRoleTo` with "Dr. Alice Smith" — the
/// display name is scoped to the participant occurrence, not the address. The
/// Python-side positional filtering of `ResultRow`s becomes native row-membership
/// assertions over the 5-var SELECT.
#[test]
fn binds_occurrence_correctly() {
    let g = email_store();
    let (vars, rows) = g.select(
        &[],
        "SELECT ?mp ?msg ?addr ?role ?display WHERE { \
         ?mp a <https://blackcatinformatics.ca/gmeow/MessageParticipant> ; \
             <https://blackcatinformatics.ca/gmeow/participantMessage> ?msg ; \
             <https://blackcatinformatics.ca/gmeow/participantAddress> ?addr ; \
             <https://blackcatinformatics.ca/gmeow/participantRole> ?role ; \
             <https://blackcatinformatics.ca/gmeow/displayName> ?display . }",
    );
    assert!(
        rows.len() >= 4,
        "expected at least 4 participants, got {}",
        rows.len()
    );
    assert_eq!(vars, vec!["mp", "msg", "addr", "role", "display"]);

    // Collect the display names for a given (message, address, role) occurrence.
    let displays_for = |msg: &str, addr: &str, role: &str| -> Vec<TermValue> {
        rows.iter()
            .filter(|r| {
                r.get(1) == Some(&Some(iri(msg)))
                    && r.get(2) == Some(&Some(iri(addr)))
                    && r.get(3) == Some(&Some(iri(role)))
            })
            .filter_map(|r| r.get(4).cloned().flatten())
            .collect()
    };

    let msg1_alice = displays_for(
        &ex_mail("msg1"),
        &ex_mail("addrAlice"),
        &gm("messageRoleFrom"),
    );
    assert_eq!(msg1_alice, vec![lit("Alice Smith")]);

    let msg2_alice = displays_for(
        &ex_mail("msg2"),
        &ex_mail("addrAlice"),
        &gm("messageRoleTo"),
    );
    assert_eq!(msg2_alice, vec![lit("Dr. Alice Smith")]);
}

