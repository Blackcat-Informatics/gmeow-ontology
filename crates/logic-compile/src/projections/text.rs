//! Byte-identical text projection back-ends: Datalog and N3.
//!
//! These are compared **byte-for-byte** against the conformance goldens, so every
//! separator, quote style, and sort order is golden-pinned.  The Python duplicate
//! has been retired; this is the source of truth.

use super::super::ir::{LogicModality, LogicProgram, LogicRule};
use super::{
    GMEOW_NS, LOGIC_NS, OWL_NS, ProjectionResult, RDF_NS, RDF_TYPE, RDFS_NS,
    aggregation_drop_notes, contract_drop_notes, is_modal_or_scoped, python_repr, target_meta,
};

/// Extract a safe Datalog predicate name from an IRI (`_local`-style).
fn datalog_local(iri: &str) -> String {
    for ns in [LOGIC_NS, GMEOW_NS, RDF_NS, OWL_NS, RDFS_NS] {
        if let Some(raw) = iri.strip_prefix(ns) {
            return raw.replace(['-', '.', '#'], "_");
        }
    }
    // Fall back to the last path segment, then the last `#` segment.
    let after_slash = iri.rsplit('/').next().unwrap_or(iri);
    after_slash
        .rsplit('#')
        .next()
        .unwrap_or(after_slash)
        .to_owned()
}

/// Datalog term token for a subject/object (`_dl_term`-style).
fn dl_term(value: &str, is_literal: bool) -> String {
    if value.starts_with('?') {
        value.to_owned()
    } else if is_literal {
        python_repr(value)
    } else {
        format!("\"{value}\"")
    }
}

/// The context string for a ground axiom fact (modality value or `"default"`).
fn ctx_str(axiom: &super::super::ir::LogicAxiom) -> String {
    if is_modal_or_scoped(axiom) && axiom.scope.modality != LogicModality::None {
        axiom.scope.modality.as_str().to_owned()
    } else {
        "default".to_owned()
    }
}

/// A fresh world variable not colliding with the rule's logical variables
/// (`base` is `"?C"` for Datalog).
fn fresh_world_var(rule: &LogicRule, base: &str) -> String {
    let mut rule_vars: std::collections::HashSet<&str> = std::collections::HashSet::new();
    if rule.head.subject.starts_with('?') {
        rule_vars.insert(&rule.head.subject);
    }
    if rule.head.obj.starts_with('?') {
        rule_vars.insert(&rule.head.obj);
    }
    for ba in &rule.body {
        if ba.subject.starts_with('?') {
            rule_vars.insert(&ba.subject);
        }
        if ba.obj.starts_with('?') {
            rule_vars.insert(&ba.obj);
        }
    }
    let mut world = base.to_owned();
    let mut suffix = 0;
    while rule_vars.contains(world.as_str()) {
        suffix += 1;
        world = format!("{base}{suffix}");
    }
    world
}

