/// Twin of `test_fixture_dsn_has_overlapping_kinds`: msgDsn is a bounce, a DSN,
/// AND auto-generated. The rdflib `initBindings={"msg": msgDsn}` becomes a native
/// `.bind`, and the Python "exactly 3 distinct kinds" (a `set` of size 3) is the
/// order-insensitive `select_row_set` of the 3 expected kind rows.
#[test]
fn dsn_has_overlapping_kinds() {
    QueryCase::new("email/dsn-kinds", &[Feature::InitBindings])
        .over_ontology_plus("tests/fixtures/coverage/email.ttl")
        .query(
            "SELECT ?kind WHERE { \
             ?msg <https://blackcatinformatics.ca/gmeow/hasMessageKind> ?kind . }",
        )
        .bind("msg", iri(&ex_mail("msgDsn")))
        .select_row_set(vec![
            vec![iri(&gm("messageKindDeliveryStatusNotification"))],
            vec![iri(&gm("messageKindBounce"))],
            vec![iri(&gm("messageKindAutoGenerated"))],
        ])
        .run();
}

