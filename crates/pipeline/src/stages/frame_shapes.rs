//! The `frame-shapes` export leaf (#861 P4): Principle 11 SHACL by annotation (#283).
//!
//! A genuine port of `src/gmeow_tools/frame_shapes_gen.py` (no Rust existed):
//! every `gmeow:requiresFrame` declaration in the root ontology + slice modules
//! becomes a generated frame-relativity NodeShape. Byte-deterministic → compared
//! byte-for-byte to the committed `generated/shapes/frame-shapes.ttl`.

use std::collections::BTreeMap;
use std::path::Path;

use oxigraph::io::{RdfFormat, RdfParser};
use oxigraph::model::{NamedNode, Term};
use oxigraph::store::Store;

use crate::error::PipelineError;
use crate::node::{Stage, StageInput, StageKind, StageOutput, StageProduct};
use crate::stages::source_load::module_files;

/// Committed logical path of the generated frame-relativity shapes.
pub const FRAME_SHAPES_PATH: &str = "generated/shapes/frame-shapes.ttl";

const NS: &str = "https://blackcatinformatics.ca/gmeow/";
const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";
const OWL_FUNCTIONAL: &str = "http://www.w3.org/2002/07/owl#FunctionalProperty";

const HEADER: &str = "# GENERATED by `gmeow regenerate` (frame-shapes) from gmeow:requiresFrame\n# declarations in the slice modules — DO NOT EDIT (#283, CONSTITUTION P11).\n@prefix gmeow: <https://blackcatinformatics.ca/gmeow/> .\n@prefix sh:    <http://www.w3.org/ns/shacl#> .\n@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .\n";

/// Load the root ontology + every slice module into one store (NO imports —
/// matching `load_merged_graph(include_imports=False)`).
fn load_authored_no_imports(root: &Path) -> Result<Store, PipelineError> {
    let store =
        Store::new().map_err(|e| PipelineError::Parse(format!("store creation failed: {e}")))?;
    let mut files = vec![root.join("ontology").join("gmeow.ttl")];
    files.extend(module_files(root)?);
    for path in files {
        if !path.is_file() {
            continue;
        }
        let bytes = std::fs::read(&path)?;
        for quad in RdfParser::from_format(RdfFormat::Turtle)
            .lenient()
            .for_reader(bytes.as_slice())
        {
            let quad = quad.map_err(|e| {
                PipelineError::Parse(format!("syntax error in {}: {e}", path.display()))
            })?;
            store
                .insert(&quad)
                .map_err(|e| PipelineError::Parse(format!("store insert failed: {e}")))?;
        }
    }
    Ok(store)
}

fn nn(iri: &str) -> NamedNode {
    NamedNode::new(iri).unwrap()
}

/// Single object of `(subject, predicate)` as a string, if any.
fn single_value(store: &Store, subject: &NamedNode, predicate: &str) -> Option<String> {
    store
        .quads_for_pattern(
            Some(subject.into()),
            Some(nn(predicate).as_ref()),
            None,
            None,
        )
        .filter_map(|q| q.ok())
        .find_map(|q| match q.object {
            Term::Literal(l) => Some(l.value().to_string()),
            Term::NamedNode(n) => Some(n.as_str().to_string()),
            _ => None,
        })
}

/// `(carrier-local, frame-prop-local, exactly_one, severity)` per declaration, sorted.
fn frame_requirements(store: &Store) -> Result<Vec<(String, String, bool, String)>, PipelineError> {
    let requires = nn(&format!("{NS}requiresFrame"));
    let functional = nn(OWL_FUNCTIONAL);
    let rdf_type = nn(RDF_TYPE);

    // Collect (carrier, frame_prop) IRI pairs, sorted.
    let mut pairs: Vec<(String, String)> = Vec::new();
    for quad in store.quads_for_pattern(None, Some(requires.as_ref()), None, None) {
        let quad = quad.map_err(|e| PipelineError::Parse(e.to_string()))?;
        if let (oxigraph::model::NamedOrBlankNode::NamedNode(c), Term::NamedNode(p)) =
            (&quad.subject, &quad.object)
        {
            pairs.push((c.as_str().to_string(), p.as_str().to_string()));
        }
    }
    pairs.sort();
    pairs.dedup();

    let mut rows = Vec::with_capacity(pairs.len());
    for (carrier, frame_prop) in pairs {
        let carrier_nn = nn(&carrier);
        let exactly_one = match single_value(store, &carrier_nn, &format!("{NS}frameCardinality")) {
            Some(v) => v == "exactly-one",
            None => store
                .quads_for_pattern(
                    Some((&nn(&frame_prop)).into()),
                    Some(rdf_type.as_ref()),
                    Some((&functional).into()),
                    None,
                )
                .next()
                .is_some(),
        };
        let severity = single_value(store, &carrier_nn, &format!("{NS}frameRequirementSeverity"))
            .unwrap_or_else(|| "violation".to_string());
        rows.push((
            carrier.strip_prefix(NS).unwrap_or(&carrier).to_string(),
            frame_prop
                .strip_prefix(NS)
                .unwrap_or(&frame_prop)
                .to_string(),
            exactly_one,
            severity,
        ));
    }
    Ok(rows)
}

/// Render the frame-relativity shapes document.
pub fn render_frame_shapes(root: &Path) -> Result<String, PipelineError> {
    let store = load_authored_no_imports(root)?;
    let mut blocks: Vec<String> = vec![HEADER.to_string()];
    for (carrier, prop, exactly_one, severity) in frame_requirements(&store)? {
        let sh_severity = if severity == "warning" {
            "sh:Warning"
        } else {
            "sh:Violation"
        };
        let count = if exactly_one {
            "exactly one"
        } else {
            "at least one"
        };
        let mut lines: Vec<String> = vec![
            format!("gmeow:{carrier}FrameRequirementShape"),
            "    a sh:NodeShape ;".to_string(),
            format!("    rdfs:label \"{carrier} frame-relativity shape (generated)\"@en ;"),
            format!("    sh:targetClass gmeow:{carrier} ;"),
            "    sh:property [".to_string(),
            format!("        sh:path gmeow:{prop} ;"),
            "        sh:minCount 1 ;".to_string(),
        ];
        if exactly_one {
            lines.push("        sh:maxCount 1 ;".to_string());
        }
        lines.push("        sh:nodeKind sh:IRI ;".to_string());
        lines.push(format!("        sh:severity {sh_severity} ;"));
        lines.push(format!(
            "        sh:message \"A {carrier} must carry {count} reference frame (gmeow:{prop}) — a value asserted without its frame is ill-formed (CONSTITUTION P11).\" ;"
        ));
        lines.push("    ] .".to_string());
        blocks.push(lines.join("\n") + "\n");
    }
    Ok(blocks.join("\n"))
}

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `frame-shapes` export-leaf stage.
pub struct FrameShapesStage;

impl Stage for FrameShapesStage {
    fn id(&self) -> &str {
        "stage-export-frame-shapes"
    }
    fn kind(&self) -> StageKind {
        StageKind::ExportLeaf
    }
    fn consumes(&self) -> &[String] {
        &[]
    }
    fn impl_version(&self) -> &str {
        "frame_shapes.v1"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<std::path::PathBuf>, PipelineError> {
        // The `gmeow:requiresFrame` declarations this leaf reads ARE in the fold's
        // authored default graph, so a consume-`stage-snapshot` rewrite is possible
        // (the MAXIMAL-INFORMATION-FLOW option). We instead declare the SAME authored
        // sources (root ontology + slice modules) as cache inputs: it is exactly as
        // sound (the fold's default graph is built from these same files, and the
        // IRI→IRI frame declarations are language-neutral so translations never touch
        // them) while keeping `consumes() == []` — no DAG re-wire, no byte-parity risk
        // from re-reading through the GTS store. A declaration change busts the cache.
        let mut files = vec![root.join("ontology").join("gmeow.ttl")];
        files.extend(crate::stages::source_load::module_files(root)?);
        Ok(files)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, PipelineError> {
        let ttl = render_frame_shapes(input.root)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(FRAME_SHAPES_PATH.to_string(), ttl.into_bytes());
        Ok(StageOutput {
            product: StageProduct::from_artifacts(self.id(), artifacts),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> std::path::PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .canonicalize()
            .unwrap()
    }

    #[test]
    fn frame_shapes_are_byte_identical_to_committed() {
        let root = repo_root();
        let fresh = render_frame_shapes(&root).expect("render");
        let committed =
            std::fs::read_to_string(root.join(FRAME_SHAPES_PATH)).expect("committed frame-shapes");
        assert_eq!(fresh, committed, "frame-shapes.ttl drifted from committed");
    }
}
