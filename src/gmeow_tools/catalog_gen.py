"""The ``catalog`` generator: catalog-v001.xml from slice discovery (#331).

The OASIS XML catalog (the ROBOT/Protégé IRI→file map) is 100% derivable
from the slice manifests plus a handful of static entries — yet it was
hand-edited ~52 times during the #287 migration. This generator ends the
class: discovered, drift-gated, never hand-edited again. The existing
``test_all_modules_are_in_catalog`` stays as defense in depth.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from gmeow_tools.config import (
    FULL_PROFILE_IRI,
    NAMED_PROFILE_NS,
    ONTOLOGY_IRI,
    PROJECT_ROOT,
    SLICES_DIR,
)
from gmeow_tools.generator import Generator, register
from gmeow_tools.profiles_gen import group_named_profiles
from gmeow_tools.slices import discover_slices

if TYPE_CHECKING:
    from collections.abc import Sequence
    from pathlib import Path

_CATALOG_FILE = PROJECT_ROOT / "catalog-v001.xml"

#: Static (non-slice) entries — the upper-ontology spine. Extend HERE, never
#: by editing the catalog.
_STATIC_ENTRIES: tuple[tuple[str, str], ...] = (
    ("http://purl.org/nemo/gufo#", "imports/gufo.ttl"),
    # the root IRI = the core profile; profile docs are generated (#330)
    (ONTOLOGY_IRI, "ontology/gmeow.ttl"),
    (FULL_PROFILE_IRI, "generated/profiles/full.ttl"),
)


def _render_catalog() -> str:
    """Render the catalog text: static spine + every discovered slice."""
    lines = [
        '<?xml version="1.0" encoding="UTF-8" standalone="no"?>',
        "<!-- GENERATED by gmeow catalog — DO NOT EDIT.",
        "     OASIS XML catalog: maps ontology IRIs to local files so the",
        "     import closure (gUFO spine + GMEOW slices) resolves offline for",
        "     ROBOT, Protégé, and the reasoning pipeline. Paths are relative",
        "     to this file (the repository root). Derived from the slice",
        "     manifests by src/gmeow_tools/catalog_gen.py (#331). -->",
        '<catalog prefer="public" xmlns="urn:oasis:names:tc:entity:xmlns:xml:catalog">',
        "    <!-- Upper-ontology spine (static allowlist) -->",
    ]
    lines.extend(
        f'    <uri name="{name}" uri="{uri}"/>' for name, uri in _STATIC_ENTRIES
    )
    lines.append("")
    lines.append("    <!-- GMEOW slices (discovered from manifests) -->")
    slices = discover_slices()
    for slice_ in sorted(slices.values(), key=lambda s: s.iri):
        rel = slice_.module_path.relative_to(PROJECT_ROOT).as_posix()
        lines.append(f'    <uri name="{slice_.iri}" uri="{rel}"/>')
    named = group_named_profiles(slices)
    if named:
        lines.append("")
        lines.append("    <!-- Named profiles (generated, #330) -->")
        lines.extend(
            f'    <uri name="{NAMED_PROFILE_NS}{name}"'
            f' uri="generated/profiles/{name}.ttl"/>'
            for name in named
        )
    lines.append("</catalog>")
    return "\n".join(lines) + "\n"


@register
class CatalogGenerator(Generator):
    """Emit catalog-v001.xml from the slice manifests."""

    name: str = "catalog"

    @property
    def inputs(self) -> Sequence[Path]:
        """The manifests are the catalog's single source of truth."""
        return sorted(SLICES_DIR.glob("*/*/manifest.ttl"))

    @property
    def outputs(self) -> Sequence[Path]:
        """One committed artifact at the repository root."""
        return [_CATALOG_FILE]

    def render(self, staging: Path) -> None:
        """Render the catalog into the staging tree."""
        target = staging / _CATALOG_FILE.relative_to(PROJECT_ROOT)
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(_render_catalog(), encoding="utf-8")
