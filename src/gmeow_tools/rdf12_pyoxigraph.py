"""RDF 1.2 / RDF* codec helpers (pyoxigraph — in-process cross-check).

Mirrors :mod:`gmeow_tools.rdf12` but uses pyoxigraph instead of Apache Jena.
This is an additive, non-authoritative verification path (CONSTITUTION
Principle 7). Jena remains the canonical artifact writer.
"""

from __future__ import annotations

from io import BytesIO
from pathlib import Path

import pyoxigraph
from rdflib import Graph

from gmeow_tools.config import QUERIES_DIR
from gmeow_tools.graph import bind_prefixes

#: OWL axiom-annotation downcast → RDF 1.2 / RDF* reifying triples.
PROJECT_QUERY = QUERIES_DIR / "codecs" / "rdf12-project.rq"
#: RDF 1.2 / RDF* → OWL axiom-annotation normal form (the round-trip inverse).
NORMALIZE_QUERY = QUERIES_DIR / "codecs" / "rdf12-to-owl.rq"

#: Header prepended to the emitted RDF 1.2 lead artifact.
_RDF12_BANNER = (
    "# RDF 1.2 / RDF* — GMEOW's canonical statement-level model, the lead\n"
    "# serialization. Generated by pyoxigraph cross-check from statement-dsl/\n"
    "# together with (and verified isomorphic to) the OWL 2 axiom-annotation\n"
    "# downcast the reasoner consumes. DO NOT EDIT — author in statement-dsl/.\n"
)


def _serialize_triples(triples: pyoxigraph.QueryTriples) -> str:
    """Serialize a pyoxigraph QueryTriples iterator to Turtle text."""
    output = BytesIO()
    pyoxigraph.serialize(triples, output, format=pyoxigraph.RdfFormat.TURTLE)
    return output.getvalue().decode("utf-8")


def project_owl_to_rdf12(owl_path: Path, output: Path) -> Path:
    """Materialize the RDF 1.2 / RDF* lead artifact from the OWL downcast.

    Args:
        owl_path: The generated OWL axiom-annotation form.
        output: Destination for the RDF 1.2 Turtle serialization.

    Returns:
        The path to the generated RDF 1.2 artifact.
    """
    store = pyoxigraph.Store()
    store.load(path=str(owl_path), format=pyoxigraph.RdfFormat.TURTLE)
    query_text = PROJECT_QUERY.read_text(encoding="utf-8")
    results = store.query(query_text)
    assert isinstance(results, pyoxigraph.QueryTriples)
    ttl = _serialize_triples(results)
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(_RDF12_BANNER + ttl.rstrip("\n") + "\n", encoding="utf-8")
    return output


def normalize_rdf12_to_owl(rdf12_path: Path) -> Graph:
    """Normalize an RDF 1.2 file back to the OWL axiom-annotation normal form.

    Args:
        rdf12_path: The RDF 1.2 Turtle file.

    Returns:
        The OWL normal form as an rdflib graph.
    """
    store = pyoxigraph.Store()
    store.load(path=str(rdf12_path), format=pyoxigraph.RdfFormat.TURTLE)
    query_text = NORMALIZE_QUERY.read_text(encoding="utf-8")
    results = store.query(query_text)
    assert isinstance(results, pyoxigraph.QueryTriples)
    ttl = _serialize_triples(results)
    graph = Graph()
    graph.parse(data=ttl, format="turtle")
    bind_prefixes(graph)
    return graph
