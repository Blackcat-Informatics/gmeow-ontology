/// The authored deployed-site sections, substituted at [`SITE_SECTIONS_MARKER`].
///
/// Deliberately OUTSIDE the npm package directory (`assets/console/`): a file inside it
/// could be pulled into the tarball by a `files` entry or by npm's own always-included set,
/// and this content exists precisely because it must not be published there. Its SPDX
