//! The per-op numeric-builtin oracle-gold conformance lane (issue #1428).
//!
//! Issue #1428's acceptance criterion requires "each op separately anchored to
//! an INDEPENDENT oracle." The native evaluator's exact-ℚ arithmetic
//! (`crates/logic/src/physical/builtin_eval.rs`) previously carried ONLY
//! in-crate `#[test]`s that call its own `eval()` and assert on `eval()`'s own
//! output — a tautology. This test is the independent counterpart: it reads
//! the frozen, hand-derived gold under
//! `coverage/external/1428-numeric-builtin-oracle-gold/cases/*.json` (never
//! generated by running the engine — see each case's `provenance.derivation`)
//! and drives every case through the PUBLIC production query surface
//! (`gmeow_logic::dispatch::dispatch_query`, the exact entry point
//! `crates/logic/src/dispatch.rs`'s own end-to-end tests use), never the
//! crate-private `eval()`.
//!
//! Three "gap" cases independently derive that a program MUST be refused
//! (`math:ZeroDivisor` / `math:Overflow` / `math:DimensionalInhomogeneity`).
//! Each moded-builtin gap is now ledgered with per-kind identity, so the
//! `dispatch_query` refusal NAMES the specific `math:` failure class it
//! anchors — these cases assert the exact ledgered kind is surfaced, the
//! "gap kinds ledgered (never silently wrong)" acceptance criterion exercised
//! against the independent oracle.
//!
//! Offline + deterministic: no Docker, Java, network, or Python.

use std::collections::BTreeMap;
use std::path::PathBuf;

use gmeow_logic::dispatch::dispatch_query;
use gmeow_logic::profile_gate::PROCEDURAL_PROLOG_PROFILE;
use gmeow_logic::query_ir::{Budget, parse_query_program};
use gmeow_logic::seam::WorldFactSnapshot;
use gmeow_logic::store::WorldStore;
use purrdf::TermValue;
use serde_json::Value;

/// The single world every case's facts/program are evaluated against. Content
/// is irrelevant (cases never inspect the world IRI); it only needs to be a
/// stable, single named graph.
const WORLD: &str = "https://example.org/1428/world";

/// The frozen-gold root, `coverage/external/1428-numeric-builtin-oracle-gold/`.
fn gold_root() -> PathBuf {
    gmeow_conformance::paths::repo_root()
        .join("coverage")
        .join("external")
        .join("1428-numeric-builtin-oracle-gold")
}

/// One frozen EDB fact fixture: `(subject_iri, predicate_iri, literal_lex,
/// literal_datatype_iri)`, loaded verbatim as a typed-literal RDF object via
/// `purrdf::TermValue::typed_literal` + `WorldStore::insert_quad_terms` — the
/// same production entry point `crates/logic/src/dispatch.rs`'s own
/// `dimension_composition_flows_through_dispatch` end-to-end test uses to feed
/// a dimension-transport literal into the evaluator.
struct GoldFact {
    s: String,
    p: String,
    lex: String,
    datatype: String,
}

/// One check against a single answer-set binding: which goal variable, how to
/// interpret its bound surface, and the hand-derived expected form.
struct GoldCheck {
    var: String,
    value_kind: String,
    expected: String,
}

/// One frozen oracle-gold case, parsed from its committed JSON.
struct GoldCase {
    file: String,
    op: String,
    mode: String,
    facts: Vec<GoldFact>,
    program: String,
    checks: Vec<GoldCheck>,
    expect_bindings: Option<u64>,
    expected_gap_kind: Option<String>,
}

fn read_gold_case(path: &std::path::Path) -> GoldCase {
    let text =
        std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    let value: Value =
        serde_json::from_str(&text).unwrap_or_else(|e| panic!("parse {}: {e}", path.display()));
    let file = path
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("<unknown>")
        .to_owned();

    let op = value["op"]
        .as_str()
        .unwrap_or_else(|| panic!("{}: missing string `op`", path.display()))
        .to_owned();
    let mode = value["mode"]
        .as_str()
        .unwrap_or_else(|| panic!("{}: missing string `mode`", path.display()))
        .to_owned();
    let program = value["program"]
        .as_str()
        .unwrap_or_else(|| panic!("{}: missing string `program`", path.display()))
        .to_owned();

    let facts = value["facts"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .into_iter()
        .map(|f| GoldFact {
            s: f["s"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: fact missing `s`", path.display()))
                .to_owned(),
            p: f["p"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: fact missing `p`", path.display()))
                .to_owned(),
            lex: f["lex"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: fact missing `lex`", path.display()))
                .to_owned(),
            datatype: f["datatype"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: fact missing `datatype`", path.display()))
                .to_owned(),
        })
        .collect();

    let checks = value["checks"]
        .as_array()
        .cloned()
        .unwrap_or_default()
        .into_iter()
        .map(|c| GoldCheck {
            var: c["var"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: check missing `var`", path.display()))
                .to_owned(),
            value_kind: c["value_kind"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: check missing `value_kind`", path.display()))
                .to_owned(),
            expected: c["expected"]
                .as_str()
                .unwrap_or_else(|| panic!("{}: check missing `expected`", path.display()))
                .to_owned(),
        })
        .collect();

    let expect_bindings = value["expect_bindings"].as_u64();
    let expected_gap_kind = value["expected_gap_kind"].as_str().map(str::to_owned);

    GoldCase {
        file,
        op,
        mode,
        facts,
        program,
        checks,
        expect_bindings,
        expected_gap_kind,
    }
}

/// Render a `checks[].expected` lexical form to the exact bound-surface string
/// the evaluator emits, per `checks[].value_kind`. Mirrors
/// `builtin_eval::emit_surface`'s wire format (documented in that module, and
/// exercised end-to-end by `crates/logic/src/dispatch.rs`'s own
/// `exact_rational_answer_flows_through_dispatch` /
/// `dimension_composition_flows_through_dispatch` tests) WITHOUT calling any
/// crate-private item — this is just the public wire contract.
fn expected_surface(value_kind: &str, expected: &str) -> String {
    match value_kind {
        "integer" => format!("\"{expected}\"^^<http://www.w3.org/2001/XMLSchema#integer>"),
        "rational" => format!("\"{expected}\"^^<urn:gmeow:transport:rational>"),
        "dimension" => format!("\"{expected}\"^^<urn:gmeow:transport:dimension>"),
        "quantity" => format!("\"{expected}\"^^<urn:gmeow:transport:quantity>"),
        // A bare IRI/constant surface (already in its canonical `<iri>` form).
        "const" => expected.to_owned(),
        other => panic!("unknown check value_kind {other:?}"),
    }
}

/// The single offline assertion: for every frozen, independently-derived
/// numeric-builtin case, driving its program through the PUBLIC
/// `dispatch_query` surface reproduces the hand-derived gold. Aggregates every
/// mismatch into one failure so a regression names every offending case.
#[test]
fn native_engine_matches_the_independent_numeric_builtin_oracle_gold() {
    let cases_dir = gold_root().join("cases");
    let mut case_files: Vec<PathBuf> = std::fs::read_dir(&cases_dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", cases_dir.display()))
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.extension().is_some_and(|x| x == "json"))
        .collect();
    case_files.sort();
    assert!(
        !case_files.is_empty(),
        "no frozen numeric-builtin oracle gold found under {} — the committed corpus is \
         missing from the checkout",
        cases_dir.display()
    );

    let mut failures: Vec<String> = Vec::new();

    for case_path in &case_files {
        let case = read_gold_case(case_path);
        let ctx = format!("{} (op={})", case.file, case.op);

        // Build the world: every case's facts loaded as typed-literal EDB
        // quads via the same public store API
        // `dimension_composition_flows_through_dispatch` uses.
        let store = WorldStore::new();
        for fact in &case.facts {
            let object = TermValue::typed_literal(fact.lex.as_str(), fact.datatype.as_str());
            store
                .insert_quad_terms(
                    WORLD,
                    TermValue::iri(fact.s.as_str()),
                    TermValue::iri(fact.p.as_str()),
                    object,
                )
                .unwrap_or_else(|e| panic!("{ctx}: insert_quad_terms: {e}"));
        }
        let foreign = WorldFactSnapshot::from_world(&store, WORLD, PROCEDURAL_PROLOG_PROFILE)
            .unwrap_or_else(|e| panic!("{ctx}: WorldFactSnapshot::from_world: {e}"));

        let program = parse_query_program(&case.program)
            .unwrap_or_else(|e| panic!("{ctx}: parse_query_program: {e}"));

        let result = dispatch_query(
            &foreign,
            WORLD,
            &program,
            PROCEDURAL_PROLOG_PROFILE,
            &Budget::default(),
        );

        match case.mode.as_str() {
            "gap" => {
                let expected_kind = case
                    .expected_gap_kind
                    .as_deref()
                    .unwrap_or_else(|| panic!("{ctx}: mode=gap requires `expected_gap_kind`"));
                match result {
                    Ok(answer) => failures.push(format!(
                        "{ctx}: expected a refusal (derived gap kind {expected_kind}) but the \
                         engine DECIDED an answer: {answer:?}"
                    )),
                    Err(diag) => {
                        // The moded-builtin gap is now ledgered with per-kind identity, so
                        // the refusal NAMES the specific `math:` failure class each gap
                        // anchors. Assert the observable refusal DOES surface the exact
                        // kind — not merely that some Arithmetic gap occurred. This is the
                        // "gap kinds ledgered (never silently wrong)" acceptance criterion
                        // exercised end-to-end from the independent oracle.
                        let expected_class = match expected_kind {
                            "ZeroDivisor" => "ZeroDivisor",
                            "Overflow" => "Overflow",
                            "ZeroDenominator" => "ZeroDenominator",
                            // BuiltinError::DimensionMismatch anchors the inhomogeneity class.
                            "DimensionMismatch" => "DimensionalInhomogeneity",
                            "MalformedDimension" => "MalformedDimension",
                            "MetricForm" => "NonPositiveDefiniteNorm",
                            other => other,
                        };
                        let needle = format!(
                            "https://blackcatinformatics.ca/math/{expected_class}"
                        );
                        if !diag.message().contains(&needle) {
                            failures.push(format!(
                                "{ctx}: expected the refusal to name the ledgered gap class \
                                 {needle} (derived kind {expected_kind}), got {:?}",
                                diag.message()
                            ));
                        }
                    }
                }
            }
            "value" => match result {
                Err(diag) => failures.push(format!(
                    "{ctx}: expected a decided answer but the engine refused: {}",
                    diag.message()
                )),
                Ok(answer) => {
                    if answer.bindings.len() != 1 {
                        failures.push(format!(
                            "{ctx}: expected exactly one answer binding, got {}: {:?}",
                            answer.bindings.len(),
                            answer.bindings
                        ));
                        continue;
                    }
                    let binding: &BTreeMap<String, String> = &answer.bindings[0];
                    for check in &case.checks {
                        let want = expected_surface(&check.value_kind, &check.expected);
                        match binding.get(&check.var) {
                            Some(got) if *got == want => {}
                            Some(got) => failures.push(format!(
                                "{ctx}: var {} = {got:?}, expected {want:?}",
                                check.var
                            )),
                            None => failures.push(format!(
                                "{ctx}: goal variable {} is not bound in the answer: {:?}",
                                check.var, binding
                            )),
                        }
                    }
                }
            },
            "compare" => match result {
                Err(diag) => failures.push(format!(
                    "{ctx}: expected a decided (possibly empty) answer set but the engine \
                     refused: {}",
                    diag.message()
                )),
                Ok(answer) => {
                    let expect_bindings = case.expect_bindings.unwrap_or_else(|| {
                        panic!("{ctx}: mode=compare requires `expect_bindings`")
                    });
                    if answer.bindings.len() as u64 != expect_bindings {
                        failures.push(format!(
                            "{ctx}: expected {expect_bindings} answer binding(s), got {}: {:?}",
                            answer.bindings.len(),
                            answer.bindings
                        ));
                        continue;
                    }
                    if !answer.bindings.is_empty() {
                        let binding: &BTreeMap<String, String> = &answer.bindings[0];
                        for check in &case.checks {
                            let want = expected_surface(&check.value_kind, &check.expected);
                            match binding.get(&check.var) {
                                Some(got) if *got == want => {}
                                Some(got) => failures.push(format!(
                                    "{ctx}: var {} = {got:?}, expected {want:?}",
                                    check.var
                                )),
                                None => failures.push(format!(
                                    "{ctx}: goal variable {} is not bound in the answer: {:?}",
                                    check.var, binding
                                )),
                            }
                        }
                    }
                }
            },
            other => failures.push(format!("{ctx}: unknown mode {other:?}")),
        }
    }

    assert!(
        failures.is_empty(),
        "native engine diverged from the independent numeric-builtin oracle gold for {} \
         case(s):\n  • {}",
        failures.len(),
        failures.join("\n  • ")
    );
}
