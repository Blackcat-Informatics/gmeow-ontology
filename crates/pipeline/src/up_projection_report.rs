//! Render the gate-derived up-projection audit ([`AuditLedger`]) as the committed Markdown
//! report (`docs/up-projection-audit.md`). Presentation only — the IR construction and gate
//! evaluation live in [`crate::up_projection_gates`]; this module never re-derives a count.
//!
//! The headline is the gate-verdict ledger `(proved + claimed) / total`, with the
//! proved-lawful / claimed split disclosed beneath and the gate-excluded / unsupported residue
//! surfaced (never hidden — "count, don't abort" must not conceal a RED).

use crate::up_projection_gates::AuditLedger;

/// Render the gate-derived audit ledger as the committed Markdown report.
pub fn render_audit_markdown(ledger: &AuditLedger) -> String {
    let mut lines: Vec<String> = Vec::new();
    lines.push("# Up-projection invertibility audit\n".to_owned());
    lines.push(
        "Generated by `gmeow up-projection-audit`. Coverage is measured on the vendored \
         real-world snapshots `tests/fixtures/coverage/external/{bii,paudley}.ttl` — fixed real \
         RDF, so the number moves only by extending GMEOW or its cells, never by authoring \
         fixtures.\n"
            .to_owned(),
    );
    lines.push(
        "Every count below is a **correspondence-gate verdict**, not a heuristic bucket count: \
         each liftable target term is realized as a `logic:Correspondence` and run through the \
         five gates. A term is *proved* only when its round-trip gate passes over two \
         independently-sourced real projection rules; a term whose reverse rule does not invert \
         its forward rule is gate-excluded even if its bucket looked clean.\n"
            .to_owned(),
    );

    let t = &ledger.totals;
    let liftable = ledger.liftable();
    let total = ledger.total();
    let pct = (100 * liftable).checked_div(total).unwrap_or(0);
    lines.push(format!(
        "## Headline: {liftable}/{total} target terms liftable ({pct}%)\n"
    ));
    lines.push(format!(
        "- **proved-lawful** (round-trip / mnemomorphism gate PASS): {}\n\
         - **claimed** (alignment-asserted, `ObligationUnknown` — not discharged): {}\n\
         - gate-excluded (a liftable bucket whose correspondence tripped a gate): {}\n\
         - unsupported (no lift rule — `hard-mint` / `down-only` / `GAP`): {}\n",
        t.proved, t.claimed, t.red_excluded, t.unsupported
    ));

    // The whole-audit tier table.
    lines.push("| tier | count | meaning |".to_owned());
    lines.push("|---|---|---|".to_owned());
    lines.push(format!(
        "| proved | {} | round-trip verified over real forward + reverse legs |",
        t.proved
    ));
    lines.push(format!(
        "| claimed | {} | liftable, asserted by the alignment relation, not proved by inversion |",
        t.claimed
    ));
    lines.push(format!(
        "| gate-excluded | {} | reverse rule does not invert the forward rule (or overclaims) |",
        t.red_excluded
    ));
    lines.push(format!(
        "| unsupported | {} | no liftable cell in either layer |",
        t.unsupported
    ));
    lines.push(String::new());

    // Per-vocabulary breakdown (gate-derived).
    lines.push("## Per-vocabulary (gate-derived)\n".to_owned());
    lines.push("| vocab | liftable/total | proved | claimed | excluded | unsupported |".to_owned());
    lines.push("|---|---|---|---|---|---|".to_owned());
    let mut vocabs: Vec<(&String, &crate::up_projection_gates::TierCounts)> =
        ledger.per_vocab.iter().collect();
    vocabs.sort_by(|a, b| b.1.total().cmp(&a.1.total()).then_with(|| a.0.cmp(b.0)));
    for (vocab, counts) in vocabs {
        lines.push(format!(
            "| {} | {}/{} | {} | {} | {} | {} |",
            vocab,
            counts.liftable(),
            counts.total(),
            counts.proved,
            counts.claimed,
            counts.red_excluded,
            counts.unsupported,
        ));
    }
    lines.push(String::new());

    // Coverage gaps.
    lines.push(format!(
        "## Coverage gaps ({} distinct terms)\n",
        ledger.gaps.len()
    ));
    lines.push(
        "Used in the real files with no liftable cell in either layer. Triage: \
         *has-concept-needs-cell* / *pass-through* (authority links) / *genuine GMEOW gap* \
         (model it or declare out-of-coverage).\n"
            .to_owned(),
    );
    if !ledger.gaps.is_empty() {
        lines.push("| term |".to_owned());
        lines.push("|---|".to_owned());
        for term in &ledger.gaps {
            lines.push(format!("| `{term}` |"));
        }
        lines.push(String::new());
    }

    let mut out = lines.join("\n");
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::up_projection_gates::{AuditLedger, TierCounts};
    use std::collections::BTreeMap;

    #[test]
    fn headline_is_proved_plus_claimed_with_the_split_disclosed() {
        let mut per_vocab = BTreeMap::new();
        per_vocab.insert(
            "schema".to_owned(),
            TierCounts {
                proved: 2,
                claimed: 5,
                red_excluded: 1,
                unsupported: 3,
            },
        );
        let ledger = AuditLedger {
            totals: TierCounts {
                proved: 2,
                claimed: 5,
                red_excluded: 1,
                unsupported: 3,
            },
            per_vocab,
            gaps: vec!["schema:foo".to_owned()],
        };
        let md = render_audit_markdown(&ledger);
        // headline numerator = proved + claimed = 7 of 11 total.
        assert!(md.contains("Headline: 7/11 target terms liftable (63%)"));
        assert!(md.contains("proved-lawful"));
        assert!(md.contains("claimed"));
        assert!(md.contains("gate-excluded"));
        assert!(md.contains("Coverage gaps (1 distinct terms)"));
        // No process-flow references (a '#' immediately followed by a digit) leak
        // into the committed doc — Markdown headers use '# ' (hash then space).
        assert!(
            !md.chars()
                .collect::<Vec<_>>()
                .windows(2)
                .any(|w| w[0] == '#' && w[1].is_ascii_digit()),
            "the committed audit doc must carry no issue/PR numbers"
        );
    }
}
