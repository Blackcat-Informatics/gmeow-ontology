//! The `matrix` export leaf (P4): the module-status matrix
//! (`generated/module-status.md`).
//!
//! A genuine port of `src/gmeow_tools/matrix.py` (no Rust existed): one row per
//! slice — tier/group/deps from the manifest, term counts from the module,
//! guide status from `docs.md`, example count from `examples/`. Byte-deterministic.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use purrdf::{DatasetView, GraphMatch, RdfDataset, TermId, TermRef, TermValue, parse_dataset};

use crate::node::{Stage, StageInput, StageOutput, StageProduct};
use crate::stages::source_load::module_files;

/// Committed logical path of the module-status matrix.
pub const MATRIX_PATH: &str = "generated/module-status.md";

const NS: &str = "https://blackcatinformatics.ca/gmeow/";
use gmeow_ns::LOGIC_NS;
const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";

const HEADER: &str = "<!-- GENERATED by gmeow matrix — DO NOT EDIT. -->\n\n# Module status matrix\n\nOne row per slice: tier and dependencies from the manifest, term counts\nfrom the module, documentation status from the guide. STUB guides are the Tier-2 uplift backlog.\n\n| slice | tier | group | deps | classes | props | individuals | examples | advice | guide |\n|---|---|---|---:|---:|---:|---:|---:|---:|---|\n";

struct Row {
    name: String,
    tier: String,
    group: String,
    deps: usize,
    classes: usize,
    props: usize,
    inds: usize,
    examples: usize,
    advisory_done: usize,
    advisory_total: usize,
    guide: String,
}

/// Render the full matrix document.
pub fn render_matrix(root: &Path) -> Result<String, gmeow_errors::Diag> {
    // Collect rows keyed by slice IRI (the discover_slices ordering).
    let mut rows: BTreeMap<String, Row> = BTreeMap::new();
    for module in module_files(root)? {
        let dir = module.parent().unwrap();
        let manifest = dir.join("manifest.ttl");
        if !manifest.is_file() {
            continue;
        }
        let (iri, tier, deps) = parse_manifest(&manifest)?;
        let name = iri.rsplit('/').next().unwrap_or(&iri).to_string();
        // group = the directory under slices/ (…/slices/<group>/<name>/module.ttl)
        let group = dir
            .parent()
            .and_then(|p| p.file_name())
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        let (classes, props, inds, adv_done, adv_total) = term_counts(&module)?;
        let examples = count_examples(&dir.join("examples"));
        let guide = guide_status(&dir.join("docs.md"));
        let is_core = tier == "core";
        rows.insert(
            iri,
            Row {
                name,
                tier,
                group,
                deps,
                classes,
                props,
                inds,
                examples,
                advisory_done: if is_core { adv_done } else { 0 },
                advisory_total: if is_core { adv_total } else { 0 },
                guide,
            },
        );
    }

    let total = rows.len();
    let stubs = rows.values().filter(|r| r.guide == "stub").count();
    let adv_done: usize = rows.values().map(|r| r.advisory_done).sum();
    let adv_total: usize = rows.values().map(|r| r.advisory_total).sum();

    let mut lines: Vec<String> = Vec::with_capacity(total);
    for r in rows.values() {
        let advisory = if r.tier == "core" {
            format!("{}/{}", r.advisory_done, r.advisory_total)
        } else {
            "-".to_string()
        };
        lines.push(format!(
            "| {} | {} | {} | {} | {} | {} | {} | {} | {} | {} |",
            r.name,
            r.tier,
            r.group,
            r.deps,
            r.classes,
            r.props,
            r.inds,
            r.examples,
            advisory,
            r.guide
        ));
    }
    let footer = format!(
        "\n**{total} slices** · documentation: {} full guides, {stubs} stubs remaining; advisory coverage: {adv_done}/{adv_total} core class/property terms.\n",
        total - stubs
    );
    Ok(format!("{HEADER}{}\n{footer}", lines.join("\n")))
}

fn parse_store(path: &Path) -> Result<std::sync::Arc<RdfDataset>, gmeow_errors::Diag> {
    let bytes = std::fs::read(path)?;
    parse_dataset(&bytes, "text/turtle", None).map_err(|e| {
        gmeow_errors::Diag::of_kind(crate::error::Parse {
            message: format!("syntax error in {}: {e}", path.display()),
        })
    })
}

/// Resolve an IRI to its dataset-local term id (absent IRIs have no id → `None`).
fn id(ds: &RdfDataset, iri: &str) -> Option<TermId> {
    ds.term_id_by_value(&TermValue::iri(iri))
}

/// `(slice_iri, tier, depends_on count)` from a manifest.
fn parse_manifest(path: &Path) -> Result<(String, String, usize), gmeow_errors::Diag> {
    let ds = parse_store(path)?;
    let ds: &RdfDataset = &ds;
    let mut iri = None;
    if let (Some(p), Some(o)) = (id(ds, RDF_TYPE), id(ds, &format!("{NS}Slice"))) {
        for q in ds.quads_for_pattern(None, Some(p), Some(o), GraphMatch::Default) {
            if let TermRef::Iri(n) = ds.resolve(q.s) {
                iri = Some(n.to_owned());
            }
        }
    }
    let iri = iri.ok_or_else(|| {
        gmeow_errors::Diag::of_kind(crate::error::Parse {
            message: format!("no slice in {}", path.display()),
        })
    })?;
    let subj = id(ds, &iri);
    let mut tier = "extension".to_string();
    if let (Some(s), Some(p)) = (subj, id(ds, &format!("{NS}sliceTier"))) {
        for q in ds.quads_for_pattern(Some(s), Some(p), None, GraphMatch::Default) {
            if let TermRef::Iri(n) = ds.resolve(q.o) {
                if n == format!("{NS}tierCore") {
                    tier = "core".to_string();
                } else if n == format!("{NS}tierProfile") {
                    tier = "profile".to_string();
                }
            }
        }
    }
    let deps = match (subj, id(ds, &format!("{NS}sliceDependsOn"))) {
        (Some(s), Some(p)) => ds
            .quads_for_pattern(Some(s), Some(p), None, GraphMatch::Default)
            .filter(|q| matches!(ds.resolve(q.o), TermRef::Iri(_)))
            .count(),
        _ => 0,
    };
    Ok((iri, tier, deps))
}

/// `(classes, props, individuals, advisory_complete, public_total)` from a module.
fn term_counts(path: &Path) -> Result<(usize, usize, usize, usize, usize), gmeow_errors::Diag> {
    let ds = parse_store(path)?;
    let ds: &RdfDataset = &ds;
    let in_ns = |s: &str| s.starts_with(NS) || s.starts_with(LOGIC_NS);
    let subjects_of = |class: &str| -> BTreeSet<String> {
        let mut set = BTreeSet::new();
        let (Some(p), Some(o)) = (id(ds, RDF_TYPE), id(ds, class)) else {
            return set;
        };
        for q in ds.quads_for_pattern(None, Some(p), Some(o), GraphMatch::Default) {
            if let TermRef::Iri(n) = ds.resolve(q.s)
                && in_ns(n)
            {
                set.insert(n.to_owned());
            }
        }
        set
    };
    // A module authors its typing markers in the canonical `logic:` spelling; the
    // generated OWL view uses `owl:`. Count subjects under BOTH so a re-authored
    // module is never read as term-less (the `logic:`→`owl:` surface flip).
    let both = |owl: &str, logic: &str| -> BTreeSet<String> {
        let mut set = subjects_of(owl);
        set.extend(subjects_of(logic));
        set
    };
    let classes = both(gmeow_ns::OWL_CLASS, gmeow_ns::LOGIC_CLASS);
    let obj = both(
        gmeow_ns::OWL_OBJECT_PROPERTY,
        gmeow_ns::LOGIC_OBJECT_PROPERTY,
    );
    let dt = both(
        gmeow_ns::OWL_DATATYPE_PROPERTY,
        gmeow_ns::LOGIC_DATATYPE_PROPERTY,
    );
    let ann = both(
        gmeow_ns::OWL_ANNOTATION_PROPERTY,
        gmeow_ns::LOGIC_ANNOTATION_PROPERTY,
    );
    let inds = both(
        gmeow_ns::OWL_NAMED_INDIVIDUAL,
        gmeow_ns::LOGIC_NAMED_INDIVIDUAL,
    );
    let props = obj.len() + dt.len() + ann.len();
    let mut public: BTreeSet<String> = classes.clone();
    public.extend(obj);
    public.extend(dt);
    public.extend(ann);
    let has = |subj: &str, pred: &str| -> bool {
        let (Some(s), Some(p)) = (id(ds, subj), id(ds, pred)) else {
            return false;
        };
        ds.quads_for_pattern(Some(s), Some(p), None, GraphMatch::Default)
            .next()
            .is_some()
    };
    let advisory = public
        .iter()
        .filter(|t| has(t, &format!("{NS}useWhen")) && has(t, &format!("{NS}howToUse")))
        .count();
    Ok((classes.len(), props, inds.len(), advisory, public.len()))
}

fn count_examples(dir: &Path) -> usize {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return 0;
    };
    entries
        .filter_map(|e| e.ok())
        .filter(|e| e.path().extension().is_some_and(|x| x == "ttl"))
        .count()
}

fn guide_status(docs: &Path) -> String {
    match std::fs::read_to_string(docs) {
        Err(_) => "MISSING".to_string(),
        Ok(text) if text.contains("This is a STUB guide") => "stub".to_string(),
        Ok(_) => "full".to_string(),
    }
}

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `matrix` export-leaf stage.
pub struct MatrixStage;

impl Stage for MatrixStage {
    fn id(&self) -> &str {
        "stage-export-matrix"
    }
    fn consumes(&self) -> &[String] {
        &[]
    }
    fn impl_version(&self) -> &str {
        "matrix.v1"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<std::path::PathBuf>, gmeow_errors::Diag> {
        // Pure source read over the slice tree: each row's tier/deps come from the
        // manifest, term counts from the module, the guide column from `docs.md`,
        // and the example count from `examples/*.ttl`. Declare ALL of those so any
        // edit (a new term, a flipped guide, an added example) busts the cache.
        // `consumes() == []`; the data is partly NON-fold (docs.md / example count).
        let mut files: Vec<std::path::PathBuf> = Vec::new();
        for module in crate::stages::source_load::module_files(root)? {
            let dir = module.parent().unwrap_or(root);
            files.push(module.clone());
            let manifest = dir.join("manifest.ttl");
            if manifest.is_file() {
                files.push(manifest);
            }
            let docs = dir.join("docs.md");
            if docs.is_file() {
                files.push(docs);
            }
            let examples = dir.join("examples");
            if let Ok(entries) = std::fs::read_dir(&examples) {
                for entry in entries.flatten() {
                    let p = entry.path();
                    if p.extension().is_some_and(|x| x == "ttl") {
                        files.push(p);
                    }
                }
            }
        }
        Ok(files)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, gmeow_errors::Diag> {
        let md = render_matrix(input.root)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(MATRIX_PATH.to_string(), md.into_bytes());
        Ok(StageOutput::new(StageProduct::from_artifacts(
            self.id(),
            artifacts,
        )))
    }
}
