fn iri_pairs(view: &DslView, pred: &str) -> Vec<(String, String)> {
    view.quads_with_predicate(pred)
        .into_iter()
        .filter_map(|(s, o)| match (s.as_iri(), o.as_iri()) {
            (Some(s), Some(o)) => Some((s.to_owned(), o.to_owned())),
            _ => None,
        })
        .collect()
}

fn suppression_vocab(onto: &DslView) -> SuppressionVocab {
    let classes = subclass_closure(onto, GM_APPELLATION);
    let mut bearer = BTreeSet::new();
    for (prop, rng) in iri_pairs(onto, RDFS_RANGE) {
        if classes.contains(&rng) {
            bearer.insert(prop);
        }
    }
    let mut domain_props = BTreeSet::new();
    for (prop, dom) in iri_pairs(onto, RDFS_DOMAIN) {
        if classes.contains(&dom) {
            domain_props.insert(prop);
        }
    }
    let mut coarsen = BTreeSet::new();
    for (s, o) in onto.quads_with_predicate(GM_COARSEN_GUARDED) {
        if let (DslTerm::Iri(s), Some(lex)) = (&s, crate::ingest::literal_lexical(&o))
            && lex == "true"
        {
            coarsen.insert(s.clone());
        }
    }
    SuppressionVocab {
        bearer_props: bearer.into_iter().collect(),
        appellation_domain_props: domain_props,
        appellation_classes: classes,
        coarsen_guarded: coarsen,
    }
}

fn subclass_closure(onto: &DslView, root: &str) -> BTreeSet<String> {
    let mut closure = BTreeSet::new();
    closure.insert(root.to_owned());
    let edges = iri_pairs(onto, RDFS_SUBCLASS_OF);
    loop {
        let mut grew = false;
        for (sub, sup) in &edges {
            if closure.contains(sup) && !closure.contains(sub) {
                closure.insert(sub.clone());
                grew = true;
            }
        }
        if !grew {
            break;
        }
    }
    closure
}

