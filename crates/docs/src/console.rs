/// When the console fetches one emitted asset.
///
/// This is the console's OWN fetch behaviour, read off the shipped modules, and it is the
/// single partition three separate surfaces are derived from: the install-time `SHELL`, the
/// published byte table, and the ceiling assertion. One partition means the offline
/// pre-cache, the documented cost and the asserted budget cannot disagree.
///
/// [`PageLoad`](Self::PageLoad) and [`InstallOnly`](Self::InstallOnly) are BOTH pre-cached
/// (see [`is_precached`](Self::is_precached)) and are separated because they answer two
/// different questions that were previously answered with one number: what the worker stores
/// at install, and what a reader's page load actually costs. The published table now states
/// both, under headings that say which is which.
#[derive(Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Debug)]
pub enum Fetch {
    /// Fetched by the PAGE on a first visit, before any pane can run: the document, the
    /// element and its worker, the session module, the vignette gallery, the transport, the
    /// always-resident core engine image and the ontology snapshot it boots over. Pre-cached
    /// too, so a returning reader gets them offline.
    PageLoad,
    /// Pre-cached at install, but NOT fetched by a page load: the service worker itself, the
    /// PWA manifest and its icon set (a browser reads those when a reader installs the
    /// console, not to paint it), and the vendored purrdf RDF/JS engine, which no pane
    /// dispatches to but which the published tree offers an embedder to import. All of it is
    /// pre-cached because it is part of the OFFLINE surface: an importable engine or a
    /// declared icon that was not cached would 404 for exactly the reader the offline
    /// contract is for.
    InstallOnly,
    /// Fetched only when a pane first needs it — the demand-loaded reasoning segment. It is
    /// NOT pre-cached at install; the worker's cache-first handler stores it the first time
    /// something actually asks for it, which is what makes the deferral real.
    Demand,
    /// Shipped in the tree but never fetched by the console: the documentation site's own
    /// controller, its conjecture library, and this README. They ride along because the
    /// console and the site share one `assets/` tree; the console asks for none of them.
    Never,
}

impl Fetch {
    /// Whether `sw.mjs` pre-caches this tier at install — the set the ceiling bounds.
    ///
    /// EXHAUSTIVE over the four variants, with no catch-all: a fifth tier has to say whether
    /// it is downloaded on install, and a `_` arm would answer for it silently.
    #[must_use]
    pub const fn is_precached(self) -> bool {
        match self {
            Self::PageLoad | Self::InstallOnly => true,
            Self::Demand | Self::Never => false,
        }
    }
}

/// Which tier an assembled key belongs to.
///
/// TOTAL BY REFUSAL, never by guess. Every console key is looked up in [`SHELL_FILES`] or
/// [`GENERATED_CONSOLE_FILES`], and every shared key in [`ASSET_TIERS`]; a key in none of
/// them panics. The classification this replaced fell through an `else` to the first-load
/// tier, so any newly emitted asset silently joined the set the published byte table calls
/// the first load and the service worker downloads at install — which is how the vendored
/// purrdf engine, the PWA manifest and four icons came to be published as bytes "fetched
/// before any pane runs" when no page load fetches any of them.
///
/// The tiers themselves are read off the shipped modules' own fetch routes: `assets/mcp/…`
/// is what `mcp-transport.mjs`'s `loadSegment` imports on the typed `mcp.segment-not-loaded`
/// signal, and `docs-controller.mjs` / `conjectures.ttl` are reached only from the
/// documentation site's pages, which are outside this worker's scope.
///
/// # Panics
///
/// If `key` is not a declared console file and matches no declared asset entry — an asset
/// was added to the emitted tree without being given a tier.
#[must_use]
pub fn fetch_tier(key: &str) -> Fetch {
    if let Some(name) = key.strip_prefix(CONSOLE_PREFIX) {
        return SHELL_FILES
            .iter()
            .find(|(shell, _, _)| *shell == name)
            .map(|(_, _, tier)| *tier)
            .or_else(|| {
                GENERATED_CONSOLE_FILES
                    .iter()
                    .find(|(generated, _)| *generated == name)
                    .map(|(_, tier)| *tier)
            })
            .unwrap_or_else(|| {
                panic!(
                    "the assembled console emits {key}, which is neither a declared shell \
                     file nor a generated console file — add it to SHELL_FILES or to \
                     GENERATED_CONSOLE_FILES with the tier it belongs to, in \
                     crates/docs/src/console.rs"
                )
            });
    }
    ASSET_TIERS
        .iter()
        .find(|(pattern, _)| covers(pattern, key))
        .map(|(_, tier)| *tier)
        .unwrap_or_else(|| {
            panic!(
                "the assembled console emits {key}, which no ASSET_TIERS entry covers — \
                 declare its tier in crates/docs/src/console.rs rather than letting it join \
                 one by default"
            )
        })
}

/// Whether an [`ASSET_TIERS`] pattern covers `key`: a directory prefix, or an exact key.
fn covers(pattern: &str, key: &str) -> bool {
    if pattern.ends_with('/') {
        key.starts_with(pattern)
    } else {
        key == pattern
    }
}

/// The complete standalone-console tree for an exec-backed render.
///
/// Keys span two prefixes and that is deliberate: `console/…` is the shell, and `assets/…`
/// is the shared engine set the documentation site already emits — the console does not
/// carry a second copy of a 7 MB wasm image.
///
/// Empty when the render is not interactive: a console with no engine is not a smaller
/// console, it is a broken one, so none of it is emitted rather than half of it.
///
/// # Panics
///
/// If the assembled tree has no pre-cached tier at all, if any generated surface's marker is
/// missing from its authored source, or if an emitted key has no declared [`Fetch`] tier.
#[must_use]
pub fn console_files(exec: &ExecutableDocsData) -> BTreeMap<String, Vec<u8>> {
    let mut files = interactive_asset_files(exec);
    if files.is_empty() {
        return files;
    }
    for (name, bytes, _) in SHELL_FILES {
        files.insert(format!("{CONSOLE_PREFIX}{name}"), bytes.to_vec());
    }
    files.insert(
        TRANSPORT_FORWARDER_KEY.to_string(),
        TRANSPORT_FORWARDER.as_bytes().to_vec(),
    );

    // The deployed-site sections go in FIRST, before anything is digested or measured. The
    // authored README is the npm package's own document and carries none of them; the site's
    // copy carries all of them, and both are then one file whose bytes this producer knows.
    files.insert(README_KEY.to_string(), site_readme(&files).into_bytes());

    // The build digest is taken over the assembled tree BEFORE the two derived surfaces are
    // written into it, so it is a function of the build inputs alone and cannot chase its
    // own tail. The README is digested with its site sections but WITHOUT its measured
    // table: the table is a pure function of the very files already digested here, so
    // nothing it could say is unrepresented.
    let build = build_digest(&files);

    // The worker is generated over the finished key set and then inserted — so its own path
    // is part of the shell it caches while its bytes stay a pure function of everything
    // else. The pre-cache set is every PRE-CACHED tier: pre-caching the demand-loaded
    // reasoning segment would download it on install and make the deferral a fiction.
    let mut shell: Vec<String> = files
        .keys()
        .filter(|key| fetch_tier(key).is_precached())
        .map(|key| sw_relative(key))
        .collect();
    shell.push(sw_relative(&format!("{CONSOLE_PREFIX}sw.mjs")));
    shell.sort();
    files.insert(
        format!("{CONSOLE_PREFIX}sw.mjs"),
        service_worker(&shell, &build).into_bytes(),
    );

    // The published byte table is measured over the FINAL runtime tree (the worker
    // included), and the ceiling the table publishes is DERIVED from that same measurement
    // — so the two numbers cannot disagree and the factor between them is an identity.
    //
    // What is asserted here is the one thing the derivation cannot supply: that there IS a
    // measurement, in each of the two tiers the table reports separately. A tree with an
    // empty page-load tier would publish a zero page-load total against which the browser's
    // recorded wire log would agree only by fetching nothing; a tree with an empty pre-cache
    // would publish a zero ceiling. Both would pass every downstream check vacuously over a
    // console that boots nothing.
    let report = ByteReport::of(&files);
    assert!(
        report.page_load_total > 0,
        "the assembled console has an empty page-load tier — there is nothing to measure, \
         so the published page-load total would be zero and the browser lane would assert \
         it against an empty wire log"
    );
    assert!(
        report.precache_total() > 0,
        "the assembled console has an empty pre-cache tier — there is nothing to measure, \
         so the published byte table and the ceiling derived from it would both be zero"
    );
    let readme = String::from_utf8(files[README_KEY].clone()).expect("the console README is UTF-8");
    assert!(
        readme.contains(BYTE_TABLE_MARKER),
        "crates/docs/assets/console-site-readme.md no longer carries the \
         {BYTE_TABLE_MARKER} marker — the measured byte table cannot be substituted"
    );
    files.insert(
        README_KEY.to_string(),
        readme
            .replacen(BYTE_TABLE_MARKER, &report.markdown(), 1)
            .into_bytes(),
    );
    files
}

/// The site's copy of the console README: the authored (npm) document with the deployed-site
/// sections substituted at [`SITE_SECTIONS_MARKER`].
///
/// # Panics
///
/// If the authored README no longer carries the marker. Shipping it unsubstituted would
/// deploy a console whose own document says nothing about the worker that serves it.
fn site_readme(files: &BTreeMap<String, Vec<u8>>) -> String {
    let readme = String::from_utf8(files[README_KEY].clone()).expect("the console README is UTF-8");
    assert!(
        readme.contains(SITE_SECTIONS_MARKER),
        "crates/docs/assets/console/README.md no longer carries the {SITE_SECTIONS_MARKER} \
         marker — the deployed-site sections cannot be substituted"
    );
    assert_eq!(
        hand_authored_byte_magnitudes(SITE_SECTIONS_SOURCE),
        Vec::<String>::new(),
        "crates/docs/assets/console-site-readme.md states a byte magnitude in its prose. \
         Every byte figure in that document is GENERATED from the assembled tree; a typed \
         one is a second source of truth that goes stale the next time an engine is \
         re-vendored, which is exactly what happened to the reasoning segment's size. Refer \
         to the measured table instead of restating a number beside it"
    );
    readme.replacen(SITE_SECTIONS_MARKER, SITE_SECTIONS_SOURCE.trim(), 1)
}

/// The units a hand-typed byte magnitude can be spelled in, longest spelling first.
///
/// Matched case-insensitively and longest-first, so `megabytes` is recognised before `b`
/// could match its tail. Bare `b` is included because `8 MB` and `8b` are the same defect.
const BYTE_UNITS: &[&str] = &[
    "gigabytes",
    "megabytes",
    "kilobytes",
    "gigabyte",
    "megabyte",
    "kilobyte",
    "bytes",
    "byte",
    "gib",
    "mib",
    "kib",
    "gb",
    "mb",
    "kb",
    "b",
];

/// Every hand-authored byte magnitude in `text` — a number immediately followed by a byte
/// unit — as the matched substrings, in order.
///
/// The gate on the spliced site sections, and the whole of it. `10 MB` sat twenty-two lines
/// above a GENERATED table reading `12 373 564` under a heading asserting "Nothing in this
/// section is typed in", because the image grew and the prose did not; the same class of
/// defect had been closed once already and came back in the next commit. Prose cannot be
/// kept in step with a measurement by remembering to retype it, so a magnitude in prose is
/// refused outright and the reader is sent to the measured table.
///
/// Deliberately SYNTACTIC and unit-anchored: it catches `10 MB`, `10MB`, `1.5 GiB`,
/// `12 373 564 bytes` and `8b`, and leaves alone the numbers that are not sizes — `icon-192`,
/// `RDF-1.2`, `BLAKE3`, `start_url`. A number with no unit beside it is not a byte claim.
#[must_use]
pub fn hand_authored_byte_magnitudes(text: &str) -> Vec<String> {
    let bytes = text.as_bytes();
    let mut found = Vec::new();
    let mut at = 0usize;
    while at < bytes.len() {
        // Anchor on a digit that starts a number (not one inside a longer token).
        if !bytes[at].is_ascii_digit() || (at > 0 && is_number_body(bytes[at - 1])) {
            at += 1;
            continue;
        }
        // The numeral: digits, with `.`, `,`, `_` or a single space allowed BETWEEN digits,
        // so grouped forms like `12 373 564` and `1.5` are one number rather than three.
        let start = at;
        let mut end = at;
        while end < bytes.len()
            && (bytes[end].is_ascii_digit()
                || (matches!(bytes[end], b'.' | b',' | b'_' | b' ')
                    && bytes.get(end + 1).is_some_and(u8::is_ascii_digit)))
        {
            end += 1;
        }
        at = end;
        // The unit, after at most one separating space.
        let unit_at = if bytes.get(end) == Some(&b' ') {
            end + 1
        } else {
            end
        };
        let tail = &text[unit_at..];
        if let Some(unit) = BYTE_UNITS.iter().find(|unit| {
            tail.len() >= unit.len()
                && tail[..unit.len()].eq_ignore_ascii_case(unit)
                // A unit must END the word: `10 Mbps` and `3blind` are not byte claims.
                && !tail[unit.len()..]
                    .chars()
                    .next()
                    .is_some_and(|c| c.is_alphanumeric())
        }) {
            found.push(text[start..unit_at + unit.len()].to_string());
        }
    }
    found
}

/// Whether `byte` continues a numeral or an identifier, so a digit after it does not start
/// a fresh number (`icon-512` starts one; `blake3x2` does not start one at `2`).
const fn is_number_body(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'.' | b',' | b'_')
}

/// The console's transport entry, as emitted into the SITE tree.
///
/// One generated forwarder, and it exists so that ONE import specifier
/// (`./pkg/mcp-transport.mjs`, in `console/engine.worker.mjs`) resolves in BOTH trees the
/// console ships as. On the site the real module is the shared `assets/mcp-transport.mjs`
/// the documentation controller also imports, so forwarding is what keeps the site at one
/// engine copy instead of two; in the published npm package there is no site around the
/// console, so the package's `prepack` stages the real module — and the whole engine
/// payload it imports — at this same path.
///
/// A re-export is not a second implementation: it resolves to the SAME module instance, so
/// the transport's configured asset base and its cached engine promise are shared, not
/// duplicated.
const TRANSPORT_FORWARDER: &str = "// SPDX-FileCopyrightText: 2026 Blackcat Informatics® Inc. <paudley@blackcatinformatics.ca>\n\
     // SPDX-License-Identifier: AGPL-3.0-only\n\
     \n\
     // GENERATED by crates/docs/src/console.rs. Do not edit.\n\
     //\n\
     // The console's engine worker imports its transport as `./pkg/mcp-transport.mjs` so that\n\
     // one specifier resolves both in this site tree and in the published npm package, where\n\
     // the whole engine payload is staged under `pkg/`. Here the real module is the shared\n\
     // `assets/mcp-transport.mjs` the documentation controller imports too, so this forwards\n\
     // to it rather than duplicating a 29 kB module — and, transitively, the 7 MB engine\n\
     // image it pulls in.\n\
     //\n\
     // `export *` re-exports the SAME module instance: the transport's configured asset base\n\
     // and its cached boot promise are shared with every other importer, not re-created.\n\
     \n\
     export * from \"../../assets/mcp-transport.mjs\";\n";

/// A console-tree key expressed relative to `console/sw.mjs` (the worker's own URL).
///
/// `console/element.mjs` → `./element.mjs`; `assets/mcp-core/index.mjs` →
/// `../assets/mcp-core/index.mjs`. The worker resolves each against its own location, so
/// the console works at any site depth and from `file://`.
fn sw_relative(key: &str) -> String {
    match key.strip_prefix(CONSOLE_PREFIX) {
        Some(rest) => format!("./{rest}"),
        None => format!("../{key}"),
    }
}

/// The BLAKE3 content digest of an assembled tree, as the hex the cache name carries.
///
/// Keyed on BYTES, because the cache name's whole job is to make a rebuild un-reusable when
/// the bytes changed. Keying it on the shell's entry count and joined path length — which
/// is what it used to do — means any rebuild that keeps the same paths keeps the same cache
/// name and serves the OLD bytes to every returning reader, which is the exact failure a
/// versioned cache exists to prevent.
///
/// The encoding is length-prefixed per entry, so no pair of distinct trees can hash to the
/// same digest by moving bytes across a key boundary.
fn build_digest(files: &BTreeMap<String, Vec<u8>>) -> String {
    let mut hasher = blake3::Hasher::new();
    for (key, bytes) in files {
        hasher.update(&(key.len() as u64).to_le_bytes());
        hasher.update(key.as_bytes());
        hasher.update(&(bytes.len() as u64).to_le_bytes());
        hasher.update(bytes);
    }
    hasher.finalize().to_hex()[..16].to_string()
}

/// The service-worker source with its `SHELL` array and cache name substituted.
///
/// # Panics
///
/// If the authored `sw.mjs` no longer carries [`SHELL_MARKER`] or [`BUILD_MARKER`]. That is
/// a build-input break, not a runtime condition: shipping the unsubstituted source would
/// cache the literal string `__GMEOW_CONSOLE_SHELL__` and produce a console that appears to
/// work online and fails offline.
fn service_worker(shell: &[String], build: &str) -> String {
    assert!(
        SW_SOURCE.contains(SHELL_MARKER),
        "crates/docs/assets/console/sw.mjs no longer carries the {SHELL_MARKER} marker — the \
         generated SHELL cannot be substituted"
    );
    assert!(
        SW_SOURCE.contains(BUILD_MARKER),
        "crates/docs/assets/console/sw.mjs no longer carries the {BUILD_MARKER} marker — the \
         generated build digest cannot be substituted"
    );
    let rendered = shell
        .iter()
        .map(|path| format!("  {},", json_string(path)))
        .collect::<Vec<_>>()
        .join("\n");
    SW_SOURCE
        .replacen(SHELL_MARKER, &format!("[\n{rendered}\n]"), 1)
        .replacen(BUILD_MARKER, &json_string(build), 1)
}

/// A JSON string literal (the only escapes a site-relative path can need).
fn json_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            _ => out.push(c),
        }
    }
    out.push('"');
    out
}

// ── the measured byte report ────────────────────────────────────────────────

/// The measured byte cost of an assembled console tree, partitioned by [`Fetch`].
///
/// MEASURED, never authored. The hand-written table this replaced was wrong on nearly
/// every row and omitted two assets the console fetches on every boot, because a table
/// typed into a document is a second source of truth for bytes that move on every build.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ByteReport {
    /// `(key, bytes, tier)` for every emitted asset, in key order.
    pub rows: Vec<(String, u64, Fetch)>,
    /// What the PAGE fetches on a first visit, before any pane can run.
    pub page_load_total: u64,
    /// What the worker pre-caches at install that a page load never asks for.
    pub install_only_total: u64,
    /// The total the demand-loaded reasoning segment costs, when a pane first needs it.
    pub demand_total: u64,
}

impl ByteReport {
    /// What `cache.addAll` downloads at install: the page-load tier plus the install-only
    /// tier. This is the set the ceiling bounds, and it is strictly larger than
    /// [`page_load_total`](Self::page_load_total) — which is exactly why the two are
    /// published as separate numbers under headings that name them.
    #[must_use]
    pub const fn precache_total(&self) -> u64 {
        self.page_load_total + self.install_only_total
    }

    /// The published ceiling for THIS measurement — the derived identity
    /// [`precache_ceiling`], never a stored number. The ratio of this to
    /// [`precache_total`](Self::precache_total) is [`PRECACHE_CEILING_FACTOR`] by
    /// construction, which is what the generated README sentence states.
    #[must_use]
    pub const fn ceiling(&self) -> u64 {
        precache_ceiling(self.precache_total())
    }

    /// Measure an assembled tree.
    #[must_use]
    pub fn of(files: &BTreeMap<String, Vec<u8>>) -> Self {
        let rows: Vec<(String, u64, Fetch)> = files
            .iter()
            .map(|(key, bytes)| (key.clone(), bytes.len() as u64, fetch_tier(key)))
            .collect();
        let total = |tier: Fetch| {
            rows.iter()
                .filter(|(_, _, row)| *row == tier)
                .map(|(_, bytes, _)| *bytes)
                .sum()
        };
        Self {
            page_load_total: total(Fetch::PageLoad),
            install_only_total: total(Fetch::InstallOnly),
            demand_total: total(Fetch::Demand),
            rows,
        }
    }

    /// The report as the Markdown section the shipped README publishes.
    ///
    /// FOUR tiers, each under a heading that says what it is. The heading this replaced read
    /// "First load — everything fetched before any pane runs" over a table that also carried
    /// 8 MB of vendored purrdf, a PWA manifest and four icons — none of which a page load
    /// fetches, a fact the same document stated forty lines further down. The set was always
    /// the install pre-cache; only its title was wrong. Both numbers are published now, so
    /// neither has to stand in for the other.
    #[must_use]
    pub fn markdown(&self) -> String {
        let mut out = String::new();
        out.push_str(
            "*Generated by `crates/docs/src/console.rs` from the assembled tree — measured \
             uncompressed on-disk bytes, no transfer encoding assumed. Nothing in this \
             section is typed in.*\n",
        );
        self.section(
            &mut out,
            Fetch::PageLoad,
            "Page load",
            "what the page itself fetches on a first visit, before any pane can run. The \
             browser smoke lane records a real first load in Chromium and asserts the \
             recorded set against this one in BOTH directions, so a row here that no page \
             load asks for fails the gate instead of inflating the number",
        );
        self.section(
            &mut out,
            Fetch::InstallOnly,
            "Pre-cached at install, not fetched by a page load",
            "the service worker itself, the PWA manifest and its icons (a browser reads \
             those when a reader installs the console, not to paint it), and the vendored \
             purrdf engine an embedding page may import. Nothing here is on the boot path; \
             all of it is stored at install, because an offline reader who cannot install \
             the console or import the engine is exactly the reader the offline contract is \
             for",
        );
        self.section(
            &mut out,
            Fetch::Demand,
            "Demand-loaded reasoning segment",
            "fetched only when a pane first needs a reasoning-segment tool, and never at \
             all for a reader who only looks things up",
        );
        self.section(
            &mut out,
            Fetch::Never,
            "Shipped, never fetched by the console",
            "shared with the documentation site, which reaches them from its own pages. \
             This document is the one emitted file the table omits: it is where the table \
             is published, so a row for its own size could never be the size it reports",
        );
        out.push_str(&format!(
            "\n**Totals** — the sums of the sections above:\n\n| Set | Bytes |\n|---|---:|\n\
             | **Page-load total** | **{}** |\n\
             | **Install-only total** | **{}** |\n\
             | **Install pre-cache total** | **{}** |\n\
             | **Demand-loaded segment total** | **{}** |\n",
            grouped(self.page_load_total),
            grouped(self.install_only_total),
            grouped(self.precache_total()),
            grouped(self.demand_total),
        ));
        // Every number AND the factor in this sentence come from the same measurement and
        // the same constant the ceiling is derived from, so it cannot state a ratio the two
        // numbers above it contradict. The sentence it replaced was hard-coded prose
        // ("plus ten percent of headroom") sitting directly under a pair of numbers whose
        // real ratio had drifted to 1.09609.
        //
        // What the sentence then SAID about that derived number was still false. It read
        // "it bounds what `cache.addAll` downloads at install", which a reader takes for a
        // budget somebody chose and something enforces. A fixed multiple of a measurement
        // bounds nothing: the measured pre-cache moved by megabytes and the published
        // ceiling moved with it, staying exactly the same factor away, and no assertion
        // anywhere could have reddened — every check over it was of the form `2n > n`. So
        // the document now says what the number is (a ratio that TRACKS the measurement)
        // and says outright that no size-regression gate exists here, rather than
        // presenting an identity as a limit.
        out.push_str(&format!(
            "\nThe install pre-cache ceiling is **{}** bytes — the pre-cache total above × \
             {}, recomputed from that same measurement on every render.\n\
             \n{NO_SIZE_GATE_DISCLOSURE}\n\
             \nThe measured figures above are the load-bearing ones, and they are asserted \
             against reality rather than against each other: the assembled tree on disk must \
             sum to the published totals, and a recorded first load in a real browser must \
             fetch EXACTLY the published page-load set, checked in both directions. Those \
             checks red when the artifact and this document disagree. What `cache.addAll` \
             downloads at install is the two pre-cached sections together — not the \
             page-load figure, which is smaller and is the one asserted against the \
             browser's recorded wire log.\n",
            grouped(self.ceiling()),
            PRECACHE_CEILING_FACTOR,
        ));
        out
    }

    /// One tier's table.
    fn section(&self, out: &mut String, tier: Fetch, title: &str, gloss: &str) {
        out.push_str(&format!(
            "\n**{title}** — {gloss}:\n\n| Asset | Bytes |\n|---|---:|\n"
        ));
        for (key, bytes, row) in &self.rows {
            // The README carries this table, so its emitted size is strictly larger than
            // the size any row here could state. Omitting it is the only honest option: a
            // number that is wrong the instant it is written is worse than an absence that
            // is explained.
            if *row == tier && key != README_KEY {
                out.push_str(&format!("| `{key}` | {} |\n", grouped(*bytes)));
            }
        }
    }
}

/// A byte count with thousands separated by a space, matching the table's own style.
fn grouped(value: u64) -> String {
    let digits = value.to_string();
    let mut out = String::with_capacity(digits.len() + digits.len() / 3);
    for (index, digit) in digits.chars().enumerate() {
        if index > 0 && (digits.len() - index).is_multiple_of(3) {
            out.push(' ');
        }
        out.push(digit);
    }
    out
}

/// The generated `SHELL` set of an assembled console tree, read back out of its `sw.mjs`.
///
/// Exposed so the acceptance assertion can compare the GENERATED set against the PRE-CACHED
/// tiers in both directions, over the shipped bytes rather than over the producer's
/// intermediate state.
///
/// # Panics
///
/// If the tree carries no `console/sw.mjs`, or its `SHELL` array cannot be read.
#[must_use]
pub fn generated_shell(files: &BTreeMap<String, Vec<u8>>) -> Vec<String> {
    let text = sw_text(files);
    let open = text
        .find("const SHELL = [")
        .expect("sw.mjs declares const SHELL")
        + "const SHELL = [".len();
    let close = open + text[open..].find(']').expect("the SHELL array closes");
    text[open..close]
        .split(',')
        .map(str::trim)
        .filter(|entry| !entry.is_empty())
        .map(|entry| entry.trim_matches('"').to_string())
        .collect()
}

/// The generated cache name of an assembled console tree, read back out of its `sw.mjs`.
///
/// # Panics
///
/// If the tree carries no `console/sw.mjs`, or its `BUILD` constant cannot be read.
#[must_use]
pub fn generated_build_digest(files: &BTreeMap<String, Vec<u8>>) -> String {
    let text = sw_text(files);
    let open = text
        .find("const BUILD = \"")
        .expect("sw.mjs declares const BUILD")
        + "const BUILD = \"".len();
    let close = open + text[open..].find('"').expect("the BUILD literal closes");
    text[open..close].to_string()
}

/// The assembled tree's service worker, as text.
fn sw_text(files: &BTreeMap<String, Vec<u8>>) -> String {
    let sw = files
        .get(&format!("{CONSOLE_PREFIX}sw.mjs"))
        .expect("an assembled console tree carries console/sw.mjs");
    String::from_utf8(sw.clone()).expect("sw.mjs is UTF-8")
}

