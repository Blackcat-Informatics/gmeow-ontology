//! The `result-shapes` export leaf (P4/P17): the SHACL projection of the canonical
//! `logic:ResultShape` type contracts.
//!
//! Every `logic:ResultShape` authored on a competency question (via
//! `gmeow:cqResultShape`) is the Rust-canonical row-schema (its authority is
//! `gmeow-logic-compile::result_shape`, enforced live by the slice-test harness).
//! This leaf emits the **projection** half of P17: one byte-deterministic
//! `sh:NodeShape` per shape that re-expresses its column contract in SHACL, so the
//! type contract travels in the published SHACL surface (REP_SHAPES / the bundle),
//! not only in the Rust harness.
//!
//! ## Why `sh:sparql`, not `sh:property` paths
//!
//! The reified result-row model is **value-keyed**, not predicate-keyed: a row's
//! bindings hang off `gmeow:rowCell → gmeow:ExpectedCell`, where the variable NAME
//! is the string literal `gmeow:cellVar` and the value is `gmeow:cellValueIri` /
//! `gmeow:cellValueLiteral`. A plain `sh:path` cannot say "the cell named `agent`
//! must bind an IRI". SHACL qualified value shapes could, but the native engine
//! does not implement them — so each column projects to `sh:sparql` constraints
//! (which the engine DOES support), keyed on `cellVar`. The shapes target the
//! `gmeow:ExpectedRow` instances a question links via `gmeow:cqResultShape`, so a
//! consumer that materialises result rows in this reified form validates them.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use oxigraph::sparql::{QueryResults, QuerySolution, SparqlEvaluator};
use oxigraph::store::Store;

use crate::error::PipelineError;
use crate::node::{Stage, StageInput, StageKind, StageOutput, StageProduct};
use crate::stages::source_load::turtle_bytes_into_store_scoped;

/// Committed logical path of the generated result-shape projection.
pub const RESULT_SHAPES_PATH: &str = "generated/shapes/result-shapes.ttl";

const GMEOW_NS: &str = "https://blackcatinformatics.ca/gmeow/";

const HEADER: &str = "# GENERATED by `gmeow regenerate` (result-shapes) from logic:ResultShape\n# declarations on competency questions — DO NOT EDIT (P4/P17: logic: is canonical,\n# SHACL is the projection; the Rust authority is gmeow-logic-compile::result_shape).\n@prefix gmeow: <https://blackcatinformatics.ca/gmeow/> .\n@prefix sh:    <http://www.w3.org/ns/shacl#> .\n@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .\n";

/// The term kind a column requires, in the closed result-shape vocabulary.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Iri,
    Literal,
    BlankNode,
}

/// One projected column of a shape: variable, kind, and whether it is required.
#[derive(Debug, Clone)]
struct Column {
    var: String,
    kind: Kind,
    required: bool,
}

/// Recursively collect every `slices/**/tests/competency.ttl` (sorted).
pub(crate) fn competency_files(root: &Path) -> Result<Vec<PathBuf>, PipelineError> {
    let mut out = Vec::new();
    let slices = root.join("slices");
    collect_competency(&slices, &mut out)?;
    out.sort();
    Ok(out)
}

fn collect_competency(dir: &Path, out: &mut Vec<PathBuf>) -> Result<(), PipelineError> {
    let entries = match std::fs::read_dir(dir) {
        Ok(e) => e,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(e) => return Err(PipelineError::Io(e)),
    };
    for entry in entries {
        let entry = entry.map_err(PipelineError::Io)?;
        let path = entry.path();
        if path.is_dir() {
            collect_competency(&path, out)?;
        } else if path.file_name().is_some_and(|n| n == "competency.ttl") {
            out.push(path);
        }
    }
    Ok(())
}

/// Load every competency spec into one store (scoped so per-file blanks stay disjoint).
fn load_competency_store(root: &Path) -> Result<Store, PipelineError> {
    let store =
        Store::new().map_err(|e| PipelineError::Parse(format!("store creation failed: {e}")))?;
    for path in competency_files(root)? {
        let bytes = std::fs::read(&path).map_err(PipelineError::Io)?;
        turtle_bytes_into_store_scoped(&store, &bytes, &path.display().to_string())?;
    }
    Ok(store)
}

fn lit(sol: &QuerySolution, var: &str) -> Option<String> {
    sol.get(var).and_then(|t| match t {
        oxigraph::model::Term::Literal(l) => Some(l.value().to_owned()),
        oxigraph::model::Term::NamedNode(n) => Some(n.as_str().to_owned()),
        _ => None,
    })
}

fn iri(sol: &QuerySolution, var: &str) -> Option<String> {
    sol.get(var).and_then(|t| match t {
        oxigraph::model::Term::NamedNode(n) => Some(n.as_str().to_owned()),
        _ => None,
    })
}

fn local_kind(kind_iri: &str) -> Result<Kind, PipelineError> {
    match kind_iri.rsplit('/').next().unwrap_or(kind_iri) {
        "TermKindIri" => Ok(Kind::Iri),
        "TermKindLiteral" => Ok(Kind::Literal),
        "TermKindBlankNode" => Ok(Kind::BlankNode),
        other => Err(PipelineError::InvalidDeclaration(format!(
            "result-shapes: unknown logic:columnTermKind <…/{other}>"
        ))),
    }
}

/// Extract `shape IRI -> sorted columns` from the competency store.
fn shapes(store: &Store) -> Result<BTreeMap<String, Vec<Column>>, PipelineError> {
    let query = "\
        PREFIX gmeow: <https://blackcatinformatics.ca/gmeow/>\n\
        PREFIX logic: <https://blackcatinformatics.ca/logic/>\n\
        SELECT ?shape ?var ?kind ?binding WHERE {\n\
          ?cq gmeow:cqResultShape ?shape .\n\
          ?shape logic:declaresColumn ?col .\n\
          ?col logic:columnVariable ?var ;\n\
               logic:columnTermKind ?kind ;\n\
               logic:columnBinding ?binding .\n\
        }";
    let results = SparqlEvaluator::new()
        .parse_query(query)
        .map_err(|e| PipelineError::Parse(format!("result-shapes introspection parse: {e}")))?
        .on_store(store)
        .execute()
        .map_err(|e| PipelineError::Parse(format!("result-shapes introspection eval: {e}")))?;
    let QueryResults::Solutions(solutions) = results else {
        return Err(PipelineError::Parse(
            "result-shapes introspection must be a SELECT".to_owned(),
        ));
    };

    let mut by_shape: BTreeMap<String, BTreeMap<String, Column>> = BTreeMap::new();
    for sol in solutions {
        let sol = sol.map_err(|e| PipelineError::Parse(format!("result-shapes solution: {e}")))?;
        let shape = iri(&sol, "shape").ok_or_else(|| {
            PipelineError::Parse("result-shapes: ?shape did not bind an IRI".to_owned())
        })?;
        let var = lit(&sol, "var").ok_or_else(|| {
            PipelineError::Parse("result-shapes: a column has no logic:columnVariable".to_owned())
        })?;
        let kind = local_kind(&iri(&sol, "kind").ok_or_else(|| {
            PipelineError::Parse("result-shapes: ?kind did not bind an IRI".to_owned())
        })?)?;
        let required = iri(&sol, "binding")
            .map(|b| b.rsplit('/').next().unwrap_or(&b) == "BindingRequired")
            .unwrap_or(false);
        by_shape.entry(shape).or_default().insert(
            var.clone(),
            Column {
                var,
                kind,
                required,
            },
        );
    }
    Ok(by_shape
        .into_iter()
        .map(|(s, cols)| (s, cols.into_values().collect()))
        .collect())
}

/// A deterministic, collision-free local name for the generated NodeShape of a
/// source shape IRI (sanitise the IRI tail after the gmeow namespace).
fn nodeshape_local(shape_iri: &str) -> String {
    let tail = shape_iri.strip_prefix(GMEOW_NS).unwrap_or(shape_iri);
    let sanitized: String = tail
        .chars()
        .map(|c| if c.is_ascii_alphanumeric() { c } else { '_' })
        .collect();
    format!("GenResultRowShape_{sanitized}")
}

fn kind_word(kind: Kind) -> &'static str {
    match kind {
        Kind::Iri => "an IRI",
        Kind::Literal => "a literal",
        Kind::BlankNode => "a blank node",
    }
}

/// The reified cell value-property for a kind (`None` for a blank node — the cell
/// model has no value property for it, so only presence is checkable).
fn value_prop(kind: Kind) -> Option<&'static str> {
    match kind {
        Kind::Iri => Some("cellValueIri"),
        Kind::Literal => Some("cellValueLiteral"),
        Kind::BlankNode => None,
    }
}

/// Render the result-shape projection document.
pub fn render_result_shapes(root: &Path) -> Result<String, PipelineError> {
    let store = load_competency_store(root)?;
    let mut blocks: Vec<String> = vec![HEADER.to_string()];

    for (shape_iri, columns) in shapes(&store)? {
        let local = nodeshape_local(&shape_iri);
        let mut lines: Vec<String> = vec![
            format!("gmeow:{local}"),
            "    a sh:NodeShape ;".to_string(),
            format!("    rdfs:label \"result-row shape for <{shape_iri}> (generated)\"@en ;"),
            "    sh:target [".to_string(),
            "        a sh:SPARQLTarget ;".to_string(),
            format!(
                "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT ?this WHERE {{ ?cq gmeow:cqResultShape <{shape_iri}> . ?cq gmeow:cqExpectRow ?this }}\"\"\" ;"
            ),
            "    ] ;".to_string(),
        ];

        for col in &columns {
            let v = &col.var;
            let want = kind_word(col.kind);
            // Presence + right-kind for required columns.
            if col.required {
                let presence = match value_prop(col.kind) {
                    Some(prop) => format!(
                        "FILTER NOT EXISTS {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' ; gmeow:{prop} ?val }}"
                    ),
                    None => format!(
                        "FILTER NOT EXISTS {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' }}"
                    ),
                };
                lines.push("    sh:sparql [".to_string());
                lines.push("        sh:severity sh:Violation ;".to_string());
                lines.push(format!(
                    "        sh:message \"result column ?{v} must be present and bind {want}\" ;"
                ));
                lines.push(format!(
                    "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT $this WHERE {{ {presence} }}\"\"\" ;"
                ));
                lines.push("    ] ;".to_string());
            }
            // Wrong-kind: a cell for this var binding the OTHER value property.
            if let Some(wrong) = wrong_value_prop(col.kind) {
                lines.push("    sh:sparql [".to_string());
                lines.push("        sh:severity sh:Violation ;".to_string());
                lines.push(format!(
                    "        sh:message \"result column ?{v} must bind {want}\" ;"
                ));
                lines.push(format!(
                    "        sh:select \"\"\"PREFIX gmeow: <{GMEOW_NS}> SELECT $this WHERE {{ $this gmeow:rowCell ?c . ?c gmeow:cellVar '{v}' ; gmeow:{wrong} ?val }}\"\"\" ;"
                ));
                lines.push("    ] ;".to_string());
            }
        }

        // Close the node shape: replace the trailing " ;" of the last line with " .".
        let last = lines.len() - 1;
        if let Some(stripped) = lines[last].strip_suffix(" ;") {
            lines[last] = format!("{stripped} .");
        }
        blocks.push(lines.join("\n") + "\n");
    }
    Ok(blocks.join("\n"))
}

/// The value property a binding of the WRONG kind would use (`None` for a blank
/// node, whose kind the value-keyed cell model cannot distinguish).
fn wrong_value_prop(kind: Kind) -> Option<&'static str> {
    match kind {
        Kind::Iri => Some("cellValueLiteral"),
        Kind::Literal => Some("cellValueIri"),
        Kind::BlankNode => None,
    }
}

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `result-shapes` export-leaf stage.
pub struct ResultShapesStage;

impl Stage for ResultShapesStage {
    fn id(&self) -> &str {
        "stage-export-result-shapes"
    }
    fn kind(&self) -> StageKind {
        StageKind::ExportLeaf
    }
    fn consumes(&self) -> &[String] {
        &[]
    }
    fn impl_version(&self) -> &str {
        "result_shapes.v1"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<PathBuf>, PipelineError> {
        // The leaf reads every competency spec's logic:ResultShape declarations;
        // declare them as cache inputs so a shape edit busts the cache.
        competency_files(root)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, PipelineError> {
        let ttl = render_result_shapes(input.root)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(RESULT_SHAPES_PATH.to_string(), ttl.into_bytes());
        Ok(StageOutput {
            product: StageProduct::from_artifacts(self.id(), artifacts),
        })
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("..")
            .join("..")
            .canonicalize()
            .unwrap()
    }

    #[test]
    fn result_shapes_are_byte_identical_to_committed() {
        let root = repo_root();
        let fresh = render_result_shapes(&root).expect("render");
        let committed = std::fs::read_to_string(root.join(RESULT_SHAPES_PATH))
            .expect("committed result-shapes");
        assert_eq!(fresh, committed, "result-shapes.ttl drifted from committed");
    }

    #[test]
    fn every_competency_shape_is_projected() {
        // Every logic:ResultShape authored on a competency question must produce a
        // generated NodeShape — the projection is not silently dropping any.
        let root = repo_root();
        let store = load_competency_store(&root).expect("load");
        let projected = shapes(&store).expect("shapes");
        assert!(
            projected.len() >= 50,
            "expected every competency ResultShape projected, got {}",
            projected.len()
        );
        let rendered = render_result_shapes(&root).expect("render");
        for shape_iri in projected.keys() {
            assert!(
                rendered.contains(&nodeshape_local(shape_iri)),
                "shape {shape_iri} is missing from the projection"
            );
        }
    }

    #[test]
    fn projection_fires_on_a_wrong_kind_row_and_passes_a_conforming_one() {
        // Prove the projection is NOT vacuous: the generated SHACL must FAIL a row
        // that binds the wrong term-kind and PASS a conforming row. We synthesise a
        // tiny shape + two rows and validate them with the native engine.
        use gmeow_shacl::engine::{parse_shapes, validate};

        let shapes_ttl = "\
            @prefix gmeow: <https://blackcatinformatics.ca/gmeow/> .\n\
            @prefix sh: <http://www.w3.org/ns/shacl#> .\n\
            gmeow:T a sh:NodeShape ;\n\
                sh:target [ a sh:SPARQLTarget ; sh:select \"\"\"PREFIX gmeow: <https://blackcatinformatics.ca/gmeow/> SELECT ?this WHERE { ?cq gmeow:cqResultShape <https://example.org/s> . ?cq gmeow:cqExpectRow ?this }\"\"\" ] ;\n\
                sh:sparql [ sh:severity sh:Violation ; sh:message \"x must bind an IRI\" ;\n\
                    sh:select \"\"\"PREFIX gmeow: <https://blackcatinformatics.ca/gmeow/> SELECT $this WHERE { $this gmeow:rowCell ?c . ?c gmeow:cellVar 'x' ; gmeow:cellValueLiteral ?val }\"\"\" ] .\n";
        let shapes = parse_shapes(shapes_ttl).expect("parse generated-style shapes");

        let data = "\
            @prefix gmeow: <https://blackcatinformatics.ca/gmeow/> .\n\
            @prefix ex: <https://example.org/> .\n\
            ex:cq gmeow:cqResultShape <https://example.org/s> ; gmeow:cqExpectRow ex:good, ex:bad .\n\
            ex:good gmeow:rowCell [ gmeow:cellVar \"x\" ; gmeow:cellValueIri ex:a ] .\n\
            ex:bad  gmeow:rowCell [ gmeow:cellVar \"x\" ; gmeow:cellValueLiteral \"oops\" ] .\n";
        let store = Store::new().unwrap();
        turtle_bytes_into_store_scoped(&store, data.as_bytes(), "test").unwrap();
        let report = validate(&store, &shapes);

        let flagged: Vec<String> = report
            .results
            .iter()
            .map(|r| r.focus_node.to_string())
            .collect();
        assert!(
            flagged.iter().any(|f| f.contains("/bad")),
            "the wrong-kind row must be flagged; flagged: {flagged:?}"
        );
        assert!(
            !flagged.iter().any(|f| f.contains("/good")),
            "the conforming row must NOT be flagged; flagged: {flagged:?}"
        );
    }
}
