//! The `constraint-shapes` export leaf (P4/P17): the SHACL projection of the `logic:`
//! open-world FOL axioms that were previously hand-authored as `sh:sparql` constraints.
//!
//! Four families, one canonical `logic:` source each, projected to `sh:SPARQLConstraint`
//! node shapes (the validation peer of the `sh:SPARQLRule` computation surface in
//! `shacl_af`; `design/LOGIC-VALIDATION.md`):
//!
//! * **irreflexivity** — a `logic:PropertyCharacteristicAssertion` with
//!   `logic:characteristicSort logic:irreflexiveProperty` (gmeow:counterGoal,
//!   gmeow:overrides): `$this P $this`.
//! * **acyclicity** — `logic:characteristicSort logic:acyclicProperty` (gmeow:linkNext):
//!   `$this P+ $this`.
//! * **relatum-distinctness** — a `logic:RelatumDistinctnessAssertion` naming a target
//!   class and two roles: `$this r1 ?v . $this r2 ?v` (a coincident-value equality join).
//! * **class-disjointness** — a NAMED `owl:AllDisjointClasses` carrying `logic:formalizes`
//!   (gmeow:identityAxisDisjointness, gmeow:softwareFacetDisjointness): an ordered pair of
//!   member classes on one focus node (subclass-closure form).
//!
//! Each shape carries a `logic:formalizes` back-reference to its canonical `logic:` source,
//! so it is self-evidently a projection (the shape-half projection-purity gate keys on it).
//! Byte-deterministic → compared byte-for-byte to the committed
//! `generated/shapes/constraint-shapes.ttl`. Emit-only; the canon is the authoring ground.

