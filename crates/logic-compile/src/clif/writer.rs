/// Quote a CL name (IRI) as `'…'`, escaping `'` and `\`.
fn name_term(iri: &str) -> String {
    format!("'{}'", escape_name(iri))
}

/// Quote a string literal as `"…"`, escaping `"` and `\`.
fn quote_string(s: &str) -> String {
    format!("\"{}\"", escape_string(s))
}
