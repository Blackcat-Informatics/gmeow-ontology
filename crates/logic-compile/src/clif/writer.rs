//! The CLIF **writer**: [`LogicProgram`] → CLIF text (`generated/cl/gmeow.clif`).
//!
//! See [`crate::clif`] for the two-channel architecture. This module emits the
//! idiomatic FOL channel (`rules` + `formulas`) as Common Logic sentences and the
//! RDF/predication channel (everything else) as `(<P> <S> <O>)` predications after the
//! `RDF_META_SENTINEL`.

use gmeow_errors::Diag;

use crate::ir::{Formula, LogicAxiom, LogicProgram, Term};
use crate::projections::{ProjectionResult, rdf, target_meta};

use super::{RDF_META_SENTINEL, escape_name, escape_string};

use purrdf::{RdfDataset, TermRef, parse_dataset};

/// `xsd:string` — the datatype the dataset assigns a plain literal; emitted CLIF
/// distinguishes a plain `(lit "x")` from a typed `(lit "x" 'dt')` by suppressing this
/// datatype (so the round-trip reconstructs the plain literal).
const XSD_STRING: &str = "http://www.w3.org/2001/XMLSchema#string";
/// `xsd:integer` — the datatype emitted for a path shape's integer min/max depths.
const XSD_INTEGER: &str = "http://www.w3.org/2001/XMLSchema#integer";

/// Project a [`LogicProgram`] to CLIF text.
///
/// Returns `Err` if the lossless RDF/predication carrier cannot be built (the
/// canonical-RDF-1.2 projection or its re-parse failing is an invariant break, not a
/// recoverable condition) — surfacing a structured error to `compile_program` exactly like
/// the sibling projectors, rather than panicking.
pub fn project_clif(program: &LogicProgram) -> gmeow_errors::Result<ProjectionResult> {
    // Registry is the single source of truth for (preservation, complexity, drops);
    // mirror `project_datalog`'s pattern so the ledger and the result agree.
    let (kind, cx, _) = target_meta("clif");

    let mut lines: Vec<String> = vec![
        ";; GENERATED by `gmeow logic compile` — DO NOT EDIT.".to_owned(),
        ";; CLIF (Common Logic Interchange Format) projection of the canonical logic: program."
            .to_owned(),
        String::new(),
    ];

    // ── Idiomatic FOL channel (human-readable rendering) ────────────────────────
    // Rules and formulas are rendered as readable Common Logic sentences for human
    // consumption. This channel is WRITE-ONLY: the canonical IR carries an
    // `obj_is_literal` bit on a rule term (and a rule's minted reifier-node identity)
    // that idiomatic CL syntax cannot express, so reconstructing the byte-exact IR from a
    // `(forall …)` sentence would be lossy. The lossless carrier is the RDF/predication
    // channel below (the Exact `canonical-rdf12` leg), from which the reader reconstructs
    // the WHOLE program — rules and formulas included. The FOL sentences are therefore an
    // idiomatic view over the same content, never the round-trip authority.
    lines.push(
        ";; === Rules (idiomatic Common Logic sentences; human-readable view) ===".to_owned(),
    );
    for rule in &program.rules {
        lines.push(rule_to_clif(rule));
    }
    lines.push(String::new());
    lines.push(";; === Full first-order formulas (idiomatic view) ===".to_owned());
    for formula in &program.formulas {
        lines.push(formula_to_clif(formula));
    }

    // ── RDF / predication channel (the lossless round-trip carrier): the WHOLE program
    //    — axioms (+ scope), rules, formulas, contracts, correspondences — re-emitted as
    //    sorted CL predications from the Exact canonical-RDF-1.2 serializer. ───────────
    let meta_lines = meta_predications(program)?;
    if !meta_lines.is_empty() {
        lines.push(String::new());
        lines.push(RDF_META_SENTINEL.to_owned());
        lines.push(
            ";; RDF/predication channel — flat (logic:) triples as CL predications (P S O)."
                .to_owned(),
        );
        lines.extend(meta_lines);
    }

    let content = format!("{}\n", lines.join("\n"));
    Ok(ProjectionResult {
        target: "clif".to_owned(),
        content,
        is_rdf: false,
        preservation: kind,
        complexity: cx.to_owned(),
        // Exact target: every construct is carried (FOL channel verbatim, RDF channel via
        // the lossless canonical-RDF-1.2 leg). Nothing is dropped, so it interns nothing
        // into the single loss store (its report/ledger rows carry no `gmeow:lossyDrop`).
    })
}

// --------------------------------------------------------------------------- //
// Idiomatic FOL channel — rules
// --------------------------------------------------------------------------- //

/// Encode a [`LogicAxiom`] (a Horn triple) as a CL atom `(<pred> <subj> <obj>)`.
fn axiom_atom(axiom: &LogicAxiom) -> String {
    let pred = name_term(&axiom.predicate);
    let subj = horn_term(&axiom.subject, false);
    let obj = horn_term(&axiom.obj, axiom.obj_is_literal);
    format!("({pred} {subj} {obj})")
}

/// A Horn subject/object token: a `?var`, a typed/plain literal, or a quoted CL name.
fn horn_term(value: &str, is_literal: bool) -> String {
    if let Some(var) = value.strip_prefix('?') {
        format!("?{var}")
    } else if is_literal {
        // A plain literal in the Horn fragment (the canonical IR carries no datatype on
        // `LogicAxiom.obj`; that detail lives in the RDF channel). Encode as a plain lit.
        format!("(lit {})", quote_string(value))
    } else {
        name_term(value)
    }
}

/// Encode a [`crate::ir::LogicRule`] as `(forall (vars) (if (and body…) head))`, or — for
/// the degenerate empty-body rule — the bare head atom.
fn rule_to_clif(rule: &crate::ir::LogicRule) -> String {
    let head = axiom_atom(&rule.head);

    let mut body_atoms: Vec<String> = Vec::new();
    for ba in &rule.body {
        let atom = axiom_atom(ba);
        if ba.negated {
            body_atoms.push(format!("(not {atom})"));
        } else {
            body_atoms.push(atom);
        }
    }
    // `distinct_pairs` (a, b) → `(/= ?a ?b)` body conjuncts.
    for (a, b) in &rule.distinct_pairs {
        body_atoms.push(format!("(/= {} {})", var_token(a), var_token(b)));
    }

    if body_atoms.is_empty() {
        // A fact: emit the head alone (universally closed over its own variables).
        let vars = collect_rule_vars(rule);
        return if vars.is_empty() {
            head
        } else {
            format!("(forall ({}) {head})", vars.join(" "))
        };
    }

    let body = if body_atoms.len() == 1 {
        body_atoms.into_iter().next().expect("len==1")
    } else {
        format!("(and {})", body_atoms.join(" "))
    };

    let vars = collect_rule_vars(rule);
    let conditional = format!("(if {body} {head})");
    if vars.is_empty() {
        conditional
    } else {
        format!("(forall ({}) {conditional})", vars.join(" "))
    }
}

/// Collect the rule's universally-quantified variables (the `?`-vars appearing in head,
/// body, and distinct pairs), in first-appearance order, deduplicated.
fn collect_rule_vars(rule: &crate::ir::LogicRule) -> Vec<String> {
    let mut seen = std::collections::HashSet::new();
    let mut out = Vec::new();
    let consider =
        |s: &str, out: &mut Vec<String>, seen: &mut std::collections::HashSet<String>| {
            if let Some(name) = s.strip_prefix('?') {
                let tok = format!("?{name}");
                if seen.insert(tok.clone()) {
                    out.push(tok);
                }
            }
        };
    consider(&rule.head.subject, &mut out, &mut seen);
    consider(&rule.head.obj, &mut out, &mut seen);
    for ba in &rule.body {
        consider(&ba.subject, &mut out, &mut seen);
        consider(&ba.obj, &mut out, &mut seen);
    }
    for (a, b) in &rule.distinct_pairs {
        consider(a, &mut out, &mut seen);
        consider(b, &mut out, &mut seen);
    }
    out
}

/// Normalize a possibly-`?`-prefixed variable string to a CL `?name` token.
fn var_token(s: &str) -> String {
    match s.strip_prefix('?') {
        Some(name) => format!("?{name}"),
        None => format!("?{s}"),
    }
}

// --------------------------------------------------------------------------- //
// Idiomatic FOL channel — formulas
// --------------------------------------------------------------------------- //

/// Encode a [`Formula`] recursively as a CL sentence.
fn formula_to_clif(formula: &Formula) -> String {
    match formula {
        Formula::Atom { relation, args } => {
            let rel = term_to_clif(relation);
            let mut parts = vec![rel];
            for a in args {
                parts.push(term_to_clif(a));
            }
            format!("({})", parts.join(" "))
        }
        Formula::Not(inner) => format!("(not {})", formula_to_clif(inner)),
        Formula::And(fs) => {
            let parts: Vec<String> = fs.iter().map(formula_to_clif).collect();
            format!("(and {})", parts.join(" "))
        }
        Formula::Or(fs) => {
            let parts: Vec<String> = fs.iter().map(formula_to_clif).collect();
            format!("(or {})", parts.join(" "))
        }
        Formula::Implies(a, b) => {
            format!("(if {} {})", formula_to_clif(a), formula_to_clif(b))
        }
        Formula::Iff(a, b) => {
            format!("(iff {} {})", formula_to_clif(a), formula_to_clif(b))
        }
        Formula::Forall { vars, body } => {
            let vs: Vec<String> = vars.iter().map(|v| format!("?{v}")).collect();
            format!("(forall ({}) {})", vs.join(" "), formula_to_clif(body))
        }
        Formula::Exists { vars, body } => {
            let vs: Vec<String> = vars.iter().map(|v| format!("?{v}")).collect();
            format!("(exists ({}) {})", vs.join(" "), formula_to_clif(body))
        }
    }
}

/// Encode a [`Term`] as a CL term.
fn term_to_clif(term: &Term) -> String {
    match term {
        Term::Var(n) => format!("?{n}"),
        Term::Iri(i) => name_term(i),
        Term::Literal { lexical, datatype } => match datatype {
            None => format!("(lit {})", quote_string(lexical)),
            Some(dt) => format!("(lit {} {})", quote_string(lexical), name_term(dt)),
        },
        // A sequence marker → `(seq n)` reserved form.
        Term::SequenceMarker(n) => format!("(seq {})", quote_string(n)),
    }
}

