_EDOAL_KIND = {
    "class": EDOAL.Class,
    "relation": EDOAL.Relation,
    "property": EDOAL.Property,
}


def _edoal_entity(graph: Graph, term: URIRef, kind: str) -> BNode:
    node = BNode()
    graph.add((node, RDF.type, _EDOAL_KIND[kind]))
    graph.add((node, EDOAL.uri, term))
    return node


def _edoal_restriction(
    graph: Graph, source: URIRef, attr: URIRef, value: URIRef
) -> BNode:
    cls = BNode()
    graph.add((cls, RDF.type, EDOAL.Class))
    restriction = BNode()
    graph.add((restriction, RDF.type, EDOAL.AttributeValueRestriction))
    on_attr = BNode()
    graph.add((on_attr, RDF.type, EDOAL.Relation))
    graph.add((on_attr, EDOAL.uri, attr))
    graph.add((restriction, EDOAL.onAttribute, on_attr))
    graph.add((restriction, EDOAL.comparator, EDOAL.equals))
    val = BNode()
    graph.add((val, EDOAL.uri, value))
    graph.add((restriction, EDOAL.value, val))
    base = _edoal_entity(graph, source, "class")
    _attach_list(graph, cls, EDOAL["and"], [base, restriction])
    return cls


def _flatten_atoms(items: tuple[Atom | OptionalGroup, ...]) -> list[Atom]:
    """Flatten a pattern's items (recursing OPTIONAL groups) to bare atoms."""
    out: list[Atom] = []
    for item in items:
        if isinstance(item, OptionalGroup):
            out.extend(_flatten_atoms(item.items))
        else:
            out.append(item)
    return out


def _nav_edges(pattern: MappingPattern) -> list[tuple[str, str, Atom]]:
    """Navigation edges (subjVar, objVar, atom): atoms relating two variables."""
    edges: list[tuple[str, str, Atom]] = []
    for atom in _flatten_atoms(pattern.atoms):
        has_pred = (
            atom.predicate is not None
            or atom.predicate_var is not None
            or atom.path is not None
            or atom.path_alts
        )
        if atom.object_var is not None and has_pred:
            edges.append((atom.subject_var, atom.object_var, atom))
    return edges


def _find_var_path(
    edges: list[tuple[str, str, Atom]], anchor: str, value: str
) -> list[tuple[Atom, bool]] | None:
    """BFS a simple variable path anchor→value; steps carry a forward/inverse flag."""
    from collections import deque

    adj: dict[str, list[tuple[str, Atom, bool]]] = {}
    for subj, obj, atom in edges:
        adj.setdefault(subj, []).append((obj, atom, True))
        adj.setdefault(obj, []).append((subj, atom, False))
    queue: deque[tuple[str, list[tuple[Atom, bool]]]] = deque([(anchor, [])])
    seen = {anchor}
    while queue:
        node, steps = queue.popleft()
        if node == value:
            return steps
        for nbr, atom, forward in adj.get(node, []):
            if nbr not in seen:
                seen.add(nbr)
                queue.append((nbr, [*steps, (atom, forward)]))
    return None


def _edoal_relation_step(graph: Graph, atom: Atom, forward: bool) -> BNode:
    """Render one navigation step as an EDOAL relation (inverse when backward)."""
    if atom.path_alts:
        if len(atom.path_alts) == 1:
            base = _edoal_entity(graph, atom.path_alts[0], "relation")
        else:
            # An alternation of relations: EDOAL edoal:or over the alternatives
            # (validator-safe; the executor still matches `a|b`).
            base = BNode()
            graph.add((base, RDF.type, EDOAL.Relation))
            _attach_list(
                graph,
                base,
                EDOAL["or"],
                [_edoal_entity(graph, a, "relation") for a in atom.path_alts],
            )
    elif atom.predicate is not None:
        base = _edoal_entity(graph, atom.predicate, "relation")
    else:  # an opaque seq/zero-or-more path — degrade to a commented relation node
        base = BNode()
        graph.add((base, RDF.type, EDOAL.Relation))
        graph.add(
            (base, RDFS.comment, Literal(atom.path or atom.predicate_var or "path"))
        )
    if forward:
        return base
    inverse = BNode()
    graph.add((inverse, RDF.type, EDOAL.Relation))
    graph.add((inverse, EDOAL.inverse, base))
    return inverse


def _edoal_path(graph: Graph, pattern: MappingPattern) -> BNode | None:
    """Derive entity1 as the anchor→value relation path (compose/inverse), or None."""
    if pattern.value is None:
        return None
    steps = _find_var_path(_nav_edges(pattern), pattern.anchor, pattern.value)
    if not steps:
        return None
    relations = [_edoal_relation_step(graph, atom, fwd) for atom, fwd in steps]
    if len(relations) == 1:
        return relations[0]
    compose = BNode()
    graph.add((compose, RDF.type, EDOAL.Relation))
    _attach_list(graph, compose, EDOAL.compose, relations)
    return compose


def emit_edoal(dsl: Dsl, profile: str) -> Graph:
    """Render the EDOAL alignment for one profile."""
    graph = Graph()
    bind_prefixes(graph)
    align = URIRef(f"{ONTOLOGY_IRI}/projections/{profile}")
    graph.add((align, RDF.type, ALIGN.Alignment))
    graph.add(
        (
            align,
            RDFS.label,
            Literal(f"GMEOW → {profile} (EDOAL)", lang="x-gmeow-english"),
        )
    )
    graph.add((align, DCTERMS.isPartOf, URIRef(ONTOLOGY_IRI)))
    graph.add((align, RDFS.comment, Literal(_GENERATED_BANNER, lang="x-gmeow-english")))
    graph.add((align, ALIGN.level, Literal("2EDOAL")))
    for n, name in ((ALIGN.onto1, "GMEOW"), (ALIGN.onto2, profile)):
        onto = BNode()
        graph.add((onto, RDF.type, ALIGN.Ontology))
        formalism = BNode()
        graph.add((formalism, ALIGN.name, Literal(name)))
        graph.add((onto, ALIGN.formalism, formalism))
        graph.add((align, n, onto))

    for cell in dsl.projections:
        for b in cell.bindings:
            if b.profile != profile:
                continue
            for map_cell in _edoal_cells(graph, cell, b):
                graph.add((align, ALIGN.map, map_cell))
    return graph


def _edoal_cells(graph: Graph, cell: ProjectionCell, b: ProfileBinding) -> list[BNode]:
    """Return the EDOAL align:Cell node(s) for one binding (0, 1, or N)."""
    pattern = cell.pattern
    cells: list[BNode] = []

    def _cell(entity1: Node, entity2: Node, label: str, key: str) -> BNode:
        # Deterministic, meaningful blank-node id (issue #36) — keyed on the source
        # projection cell, the profile, and a fan-out key so it is unique and stable.
        node = _stable_bnode(f"cell-{b.profile}-{_local(cell.iri)}-{key}")
        graph.add((node, RDF.type, ALIGN.Cell))
        graph.add((node, RDFS.label, Literal(label, lang="x-gmeow-english")))
        graph.add((node, ALIGN.entity1, entity1))
        graph.add((node, ALIGN.entity2, entity2))
        graph.add((node, ALIGN.relation, Literal(b.relation)))
        if b.transform is not None:
            trans = BNode()
            graph.add((trans, RDFS.seeAlso, b.transform))
            graph.add((node, EDOAL.transformation, trans))
        if b.confidence is not None:
            graph.add((node, EDOAL.measure, Literal(b.confidence)))
        return node

    if b.value_class_map:
        if pattern.edoal_source is None:
            raise CompileError(f"{cell.iri}: value-class map needs edoalSource")
        for i, vc in enumerate(b.value_class_map):
            entity1 = _edoal_restriction(
                graph, pattern.edoal_source, _attr_of(pattern), vc.when_value
            )
            entity2 = _edoal_entity(graph, vc.to_class, "class")
            cells.append(
                _cell(
                    entity1,
                    entity2,
                    f"{curie(pattern.edoal_source)} "
                    f"[{curie(vc.when_value)}] → {curie(vc.to_class)}",
                    key=f"{i}-{_local(vc.to_class)}",
                )
            )
        return cells

    # entity1: a derived relation path (compose/inverse) when opted in; else the
    # authored salient term; else no cell (structural / SSSOM-backed projection).
    target, target_kind = _edoal_target(b)
    if target is None:
        return cells

    source: Node | None
    if pattern.edoal_path:
        source = _edoal_path(graph, pattern)
        if source is None:
            raise CompileError(f"{cell.iri}: edoalPath set but no anchor→value path")
    elif pattern.edoal_source is not None:
        source = _edoal_entity(graph, pattern.edoal_source, pattern.edoal_source_kind)
    else:
        return cells

    target_entity = _edoal_entity(graph, target, target_kind)
    cells.append(
        _cell(source, target_entity, cell.label or f"→ {curie(target)}", key="0")
    )
    return cells


def _attr_of(pattern: MappingPattern) -> URIRef:
    """The value->class restriction attribute (the placeType-style predicate)."""
    for atom in _flatten_atoms(pattern.atoms):
        if atom.object_var == pattern.value and atom.predicate is not None:
            return atom.predicate
    raise CompileError("value-class pattern has no value-binding predicate")


def _edoal_target(b: ProfileBinding) -> tuple[URIRef | None, str]:
    if b.edoal_target is not None:
        return b.edoal_target, b.edoal_target_kind or "class"
    if b.to_class is not None:
        return b.to_class, b.edoal_target_kind or "class"
    if b.to_predicate is not None:
        return b.to_predicate, b.edoal_target_kind or "property"
    return None, "property"


