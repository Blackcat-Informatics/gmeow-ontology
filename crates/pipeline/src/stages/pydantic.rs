//! The SHACL-derived Pydantic v2 model package (`gmeow_models/`).
//!
//! This emitter is CO-DERIVED from the SAME shape compilation the JSON-Schema
//! stage runs ([`crate::stages::json_schema`]) and the developer-schema stage
//! ([`crate::stages::schemas`]): it loads the fresh shape union, compiles +
//! value-vocab-enriches it via the ONE shared
//! [`crate::stages::schema_compile::enriched_compiled_schema`] builder, and
//! renders the result with `purrdf::shapes::pydantic::emit_pydantic` — the
//! native, filesystem-free Pydantic v2 package emitter. Because every schema
//! surface compiles through the SAME enriched `$defs`, a class's Pydantic
//! `model_json_schema()` agrees with the packed JSON Schema by construction.
//!
//! # Package layout (purrdf-owned; a flat single-module package)
//!
//! * `gmeow_models/_base.py` — the shared `PurrdfBaseModel` config.
//! * `gmeow_models/models.py` — every model + StrEnum, ONE flat module.
//! * `gmeow_models/__init__.py` — re-exports every model, resolving deferred
//!   forward references via a `model_rebuild()` sweep.
//! * `gmeow_models/py.typed` — the PEP 561 marker.
//! * `gmeow_models/__about__.py` — the gmeow-orchestrated wheel-version stamp
//!   (NOT part of purrdf's emitted package — see below).
//!
//! This REPLACES gmeow's former hand-rolled slice-routed renderer, which
//! emitted one module per owning slice, per-class docs-digest linkage
//! (`gmeow:definitionDigest`), and a generated `README.md`. purrdf's emitter
//! produces a flat single-module package with none of that — an explicitly
//! user-approved capability regression tracked in `.deficiencies` with an
//! upstream purrdf feature request as the forward path.
//!
//! # Wheel version stamping (kept as gmeow orchestration)
//!
//! `purrdf::shapes::pydantic::emit_pydantic` carries no notion of a package
//! version. gmeow stamps its own `gmeow_models/__about__.py` (the ontology's
//! `owl:versionInfo`, PEP 440-validated) alongside purrdf's artifacts;
//! `packages/python/pyproject.toml`'s `[tool.hatch.version]` reads it.
//!
//! The [`PydanticStage`] production leaf (`stage-export-pydantic`) renders
//! through [`render_pydantic_package`] over the FRESH shape union
//! ([`crate::stages::shape_union_fresh`] — the generated members are THIS
//! run's consumed product bytes, never a stale disk read); the standalone
//! `gmeow-dev sync --mode update --outputs docs` entry
//! ([`render_models_python_package`]) reads the committed union. The carrier
//! folds the stage output into the `models-python` blob and writes the
//! package tree to [`PACKAGE_DISK_PREFIX`] on disk.

use std::collections::BTreeMap;
