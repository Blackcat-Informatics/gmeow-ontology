/// N3 term token (port of `_n3_term`).
fn n3_term(value: &str, is_literal: bool) -> String {
    if value.starts_with('?') {
        value.to_owned()
    } else if is_literal {
        python_repr(value)
    } else {
        format!("<{value}>")
    }
}

/// Project to N3 rules (`generated/n3/gmeow.n3`).
pub fn project_n3(program: &LogicProgram) -> ProjectionResult {
    let (kind, cx, drops) = target_meta("n3");
    let mut lines: Vec<String> = vec![
        format!("@prefix logic: <{LOGIC_NS}> ."),
        format!("@prefix gmeow: <{GMEOW_NS}> ."),
        "@prefix rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .".to_owned(),
        "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .".to_owned(),
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .".to_owned(),
        "@prefix log: <http://www.w3.org/2000/10/swap/log#> .".to_owned(),
        String::new(),
        "# GENERATED by `gmeow logic compile` — DO NOT EDIT.".to_owned(),
        "# N3 projection of the canonical logic: program.".to_owned(),
        String::new(),
        "# === Axioms ===".to_owned(),
    ];

    for axiom in &program.axioms {
        let subj_n3 = format!("<{}>", axiom.subject);
        let pred_n3 = if axiom.predicate == RDF_TYPE {
            "a".to_owned()
        } else {
            format!("<{}>", axiom.predicate)
        };
        let obj_n3 = if axiom.obj_is_literal {
            python_repr(&axiom.obj)
        } else {
            format!("<{}>", axiom.obj)
        };

        if is_modal_or_scoped(axiom) {
            let modal = axiom.scope.modality.as_str();
            lines.push(format!("# modal context: {modal}"));
            lines.push(format!(
                "{{ {subj_n3} {pred_n3} {obj_n3} }} log:implies \
                 {{ {subj_n3} <{LOGIC_NS}holds> {obj_n3} }} ."
            ));
        } else {
            lines.push(format!("{subj_n3} {pred_n3} {obj_n3} ."));
        }
    }

    lines.push(String::new());
    lines.push("# === Rules ===".to_owned());
    for rule in &program.rules {
        let head = &rule.head;
        let head_subj = n3_term(&head.subject, false);
        let head_pred = if head.predicate == RDF_TYPE {
            "a".to_owned()
        } else {
            format!("<{}>", head.predicate)
        };
        let head_obj = n3_term(&head.obj, head.obj_is_literal);

        let mut body_parts: Vec<String> = Vec::new();
        for b in &rule.body {
            let bs = n3_term(&b.subject, false);
            let bp = if b.predicate == RDF_TYPE {
                "a".to_owned()
            } else {
                format!("<{}>", b.predicate)
            };
            let bo = n3_term(&b.obj, b.obj_is_literal);
            body_parts.push(format!("{bs} {bp} {bo}"));
        }
        for (a, b) in &rule.distinct_pairs {
            body_parts.push(format!("{a} log:notEqualTo {b}"));
        }
        let body_str = if body_parts.is_empty() {
            "true .".to_owned()
        } else {
            format!("{} .", body_parts.join(" . "))
        };
        lines.push(format!(
            "{{ {body_str} }} log:implies {{ {head_subj} {head_pred} {head_obj} . }} ."
        ));
    }

    let content = format!("{}\n", lines.join("\n"));
    ProjectionResult {
        target: "n3".to_owned(),
        content,
        is_rdf: false,
        preservation: kind,
        complexity: cx.to_owned(),
        lossy_drops: drops.into_iter().map(str::to_owned).collect(),
        actual_drops: Vec::new(),
    }
}

