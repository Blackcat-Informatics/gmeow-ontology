// The real `logic:` namespace (see `crate::ir::LOGIC_NAMESPACE`); a meta-channel triple
// is only re-classified as a domain axiom when its predicate sits in this namespace, so the
// round-trip fixtures must mint their IRIs here.
const LOGIC: &str = "https://blackcatinformatics.ca/logic/";

fn iri(local: &str) -> String {
    format!("{LOGIC}{local}")
}

/// Build a small program with one rule + a few formulas (quantifier, disjunction, strong
/// negation, sequence marker) + one axiom — the emit-shape fixture.
fn shape_program() -> LogicProgram {
    let axiom = LogicAxiom::ground(
        iri("a"),
        iri("knows"),
        crate::ir::AtomicTerm::resource(iri("b")),
    )
    .expect("axiom");

    let rule = LogicRule::new(
        LogicAxiom::new(
            "?x",
            iri("ancestor"),
            crate::ir::AtomicTerm::resource("?z"),
            false,
            ContextualScope::default(),
        )
        .expect("head"),
        vec![
            LogicAxiom::new(
                "?x",
                iri("parent"),
                crate::ir::AtomicTerm::resource("?y"),
                false,
                ContextualScope::default(),
            )
            .expect("b1"),
            LogicAxiom::new(
                "?y",
                iri("parent"),
                crate::ir::AtomicTerm::resource("?z"),
                false,
                ContextualScope::default(),
            )
            .expect("b2"),
        ],
        vec![("?x".to_owned(), "?z".to_owned())],
        ContextualScope::default(),
    );

    // (forall (?p) (or (mortal ?p) (not (mortal ?p))))  with a sequence marker arg.
    let inner_or = Formula::Or(vec![
        Formula::atom(
            Term::iri(iri("mortal")).unwrap(),
            vec![
                Term::var("p").unwrap(),
                Term::sequence_marker("rest").unwrap(),
            ],
        )
        .unwrap(),
        Formula::Not(Box::new(
            Formula::atom(
                Term::iri(iri("mortal")).unwrap(),
                vec![Term::var("p").unwrap()],
            )
            .unwrap(),
        )),
    ]);
    let formula = Formula::Forall {
        vars: vec!["p".to_owned()],
        body: Box::new(inner_or),
    };

    LogicProgram::new(
        vec![axiom],
        vec![rule],
        Vec::new(),
        Some("urn:test:shape".to_owned()),
    )
    .with_formulas(vec![formula])
}

#[test]
fn emit_shape_contains_idiomatic_forms() {
    let p = shape_program();
    let out = project_clif(&p).expect("project_clif").content;

    assert!(out.contains(";; GENERATED by"), "banner missing:\n{out}");
    assert!(out.contains("(forall"), "no (forall …):\n{out}");
    assert!(out.contains("(if "), "no (if …) for the rule:\n{out}");
    assert!(
        out.contains("(/= "),
        "no (/=) for the distinct pair:\n{out}"
    );
    assert!(out.contains("(or "), "no (or …):\n{out}");
    assert!(out.contains("(not "), "no (not …):\n{out}");
    assert!(
        out.contains("(seq "),
        "no (seq …) for the sequence marker:\n{out}"
    );
    // The axiom rides the RDF channel after the sentinel.
    assert!(
        out.contains("@@gmeow-rdf-meta@@"),
        "no RDF-meta sentinel for the axiom channel:\n{out}"
    );
}

#[test]
fn comprehensive_round_trip_is_isomorphic() {
    // An axiom, a rule (negated body atom + distinct pair), a full-FOL formula (quantifier
    // + disjunction + sequence marker), plus meta: a reasoning contract and a correspondence.
    let axiom = LogicAxiom::ground(
        iri("socrates"),
        iri("isA"),
        crate::ir::AtomicTerm::resource(iri("Human")),
    )
    .unwrap();

    let rule = LogicRule::new(
        LogicAxiom::new(
            "?x",
            iri("eligible"),
            crate::ir::AtomicTerm::resource("?y"),
            false,
            ContextualScope::default(),
        )
        .unwrap(),
        vec![
            LogicAxiom::new(
                "?x",
                iri("member"),
                crate::ir::AtomicTerm::resource("?y"),
                false,
                ContextualScope::default(),
            )
            .unwrap(),
            // A negation-as-failure body atom (negated = the 5th arg).
            LogicAxiom::new(
                "?x",
                iri("banned"),
                crate::ir::AtomicTerm::resource("?y"),
                true,
                ContextualScope::default(),
            )
            .unwrap(),
        ],
        vec![("?x".to_owned(), "?y".to_owned())],
        ContextualScope::default(),
    );

    let formula = Formula::Exists {
        vars: vec!["w".to_owned()],
        body: Box::new(Formula::Or(vec![
            Formula::atom(
                Term::iri(iri("rel")).unwrap(),
                vec![
                    Term::var("w").unwrap(),
                    Term::sequence_marker("rest").unwrap(),
                ],
            )
            .unwrap(),
            Formula::Not(Box::new(
                Formula::atom(
                    Term::iri(iri("rel")).unwrap(),
                    vec![Term::literal("v", Some(iri("Tag"))).unwrap()],
                )
                .unwrap(),
            )),
        ])),
    };

    let contract = ReasoningContract::from_preset(SemanticProfileId::StratifiedNaf);

    let correspondence = Correspondence::new(
        iri("corr/test"),
        CorrespondenceRelation::Equiv,
        MorphismClass::Isomorphism,
        MorphismKind::InstitutionMorphism,
        true,
        None,
        None,
        None,
        Vec::new(),
        Some(
            crate::ir::UnitInterval::new(purrdf::RdfLiteral::typed(
                "0.9".to_owned(),
                "http://www.w3.org/2001/XMLSchema#decimal".to_owned(),
            ))
            .expect("valid authored confidence"),
        ),
        None,
        None,
        None,
        None,
        None,
    )
    .unwrap();

    let orig = LogicProgram::new(
        vec![axiom],
        vec![rule],
        vec![contract],
        Some("urn:test:comprehensive".to_owned()),
    )
    .with_correspondences(vec![correspondence])
    .unwrap()
    .with_formulas(vec![formula]);

    // First normalization: a programmatically-built program is not yet at the frontend's
    // canonical fixpoint (e.g. the frontend re-classifies a correspondence's `logic:`
    // predicates as flat axioms too, and re-derives a rule's structural head/body axioms).
    // The Exact property is that CLIF is an IDEMPOTENT lossless codec at that fixpoint: round-
    // tripping once reaches it, and EVERY further round-trip is the identity. Each leg also
    // checks the correspondence / contract / formula survive (none silently dropped).
    let src = Some("urn:test:comprehensive".to_owned());
    let clif1 = project_clif(&orig).expect("project_clif").content;
    let (fp, diags1) = parse_clif_str(&clif1, src.clone()).expect("parse_clif_str #1");
    assert!(
        diags1.iter().all(|d| d.code != "CLIF_MALFORMED_SENTENCE"),
        "malformed-sentence diagnostics on a well-formed round-trip: {diags1:?}\n--- CLIF ---\n{clif1}"
    );
    // The exercised constructs all survive into the fixpoint.
    assert_eq!(
        fp.correspondences.len(),
        1,
        "the correspondence must survive the round-trip"
    );
    assert_eq!(
        fp.contracts.len(),
        1,
        "the reasoning contract must survive the round-trip"
    );
    assert_eq!(
        fp.formulas.len(),
        1,
        "the full-FOL formula must survive the round-trip"
    );
    assert!(
        fp.rules.iter().any(|r| !r.distinct_pairs.is_empty()),
        "the rule's distinct pair must survive"
    );
    assert!(
        fp.rules.iter().any(|r| r.body.iter().any(|b| b.negated)),
        "the rule's negated body atom must survive"
    );

    // Idempotence: the second round-trip is the exact identity on the fixpoint.
    let clif2 = project_clif(&fp).expect("project_clif").content;
    assert_eq!(
        clif1, clif2,
        "CLIF emission is not idempotent at the fixpoint (byte drift):\n--- 1 ---\n{clif1}\n--- 2 ---\n{clif2}"
    );
    let (fp2, _diags2) = parse_clif_str(&clif2, src).expect("parse_clif_str #2");
    assert_ir_isomorphic(&fp, &fp2).unwrap_or_else(|e| {
        panic!("comprehensive round-trip not idempotent: {e}\n--- CLIF ---\n{clif2}")
    });
    assert!(
        fp == fp2,
        "comprehensive fixpoint round-trip differs (scope / correspondences)"
    );
}

#[test]
fn forbidden_iriref_chars_are_refused_by_the_rdf_ir() {
    // `{ } | ^ ` `` ` ``, a space and a TAB are not legal in an IRI (RFC 3987), so the RDF
    // IR refuses to intern one carrying them and names the offending character and its byte
    // offset. This test used to assert the opposite — that such an IRI SURVIVED a
    // `project_clif` ∘ `parse_clif_str` round trip verbatim. It did survive, because the IR
    // interned it unchecked and the codec emitted Turtle no conforming parser would read
    // back; the round trip agreed with itself while agreeing with nothing else.
    //
    // Refusal is the correct behaviour and is pinned here so a regression to silent
    // acceptance is caught. The `\uXXXX` escaping this test formerly reached only
    // indirectly is covered directly by `crate::nt::tests`.
    let weird = format!("{LOGIC}weird/a{{b}}c|d^e`f g\th");
    let axiom = LogicAxiom::ground(
        weird,
        iri("knows"),
        crate::ir::AtomicTerm::resource(iri("target")),
    )
    .unwrap();
    let orig = LogicProgram::new(
        vec![axiom],
        Vec::new(),
        Vec::new(),
        Some("urn:test:iri".to_owned()),
    );
    let error = project_clif(&orig).expect_err("invalid IRI must fail closed");
    assert!(
        error.to_string().contains("iri-disallowed-char"),
        "unexpected projection error: {error}"
    );
}

