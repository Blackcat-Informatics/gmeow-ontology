_DSL_STATS_FILE = "generated/mappings/dsl-stats.json"


def emit_dsl_stats(dsl: Dsl) -> str:
    """Render the DSL's surface counts as a committed, drift-gated artifact.

    Replaces hand-pinned counts in the test suite: a vocabulary addition
    changes THIS file (regenerate to resolve, the delta is reviewable in the
    PR diff) instead of a Python assertion that conflicts on every branch.
    Tests keep only structural invariants and catastrophe floors.
    """
    cells_by_set: dict[str, int] = {}
    for cell in dsl.equivalences:
        cells_by_set[cell.sssom_file] = cells_by_set.get(cell.sssom_file, 0) + 1
    stats = {
        "equivalences": len(dsl.equivalences),
        "functions": len(dsl.functions),
        "mapping_sets": len(dsl.mapping_sets),
        "projections": len(dsl.projections),
        "cells_by_set": dict(sorted(cells_by_set.items())),
    }
    return json.dumps(stats, indent=1, sort_keys=True) + "\n"


def _artifacts(
    dsl: Dsl, onto: Graph
) -> tuple[dict[str, Graph], dict[str, str], dict[str, str]]:
    """Render every artifact. Returns (rdf_graphs, sparql_texts, sssom_texts)."""
    rdf_graphs: dict[str, Graph] = {
        f"generated/projections/{_FNO_FILE}": emit_fno(dsl, onto)
    }
    sparql_texts: dict[str, str] = {}
    vocab = suppression_vocab(onto)

    # Per-profile EDOAL + SPARQL work is embarrassingly parallel.
    workers = max(1, min(os.cpu_count() or 1, 8, len(_PROFILES)))
    if workers == 1:
        for profile in _PROFILES:
            rdf_graphs[f"generated/projections/{profile}.edoal.ttl"] = emit_edoal(
                dsl, profile
            )
            sparql_texts[f"generated/queries/{profile}.rq"] = emit_sparql(
                dsl, profile, vocab
            )
    else:
        with concurrent.futures.ProcessPoolExecutor(
            max_workers=workers,
            initializer=_init_profile_worker,
            initargs=(dsl, vocab),
        ) as executor:
            for profile, edoal_graph, sparql_text in executor.map(
                _emit_profile_pair, _PROFILES, chunksize=1
            ):
                rdf_graphs[f"generated/projections/{profile}.edoal.ttl"] = edoal_graph
                sparql_texts[f"generated/queries/{profile}.rq"] = sparql_text

    sparql_texts[_STANDPOINT_OWL2_QUERY] = emit_standpoint_owl2_sparql()
    sparql_texts[_STANDPOINT_CRMINF_QUERY] = emit_standpoint_crminf_sparql()
    sparql_texts[_STANDPOINT_PROV_QUERY] = emit_standpoint_prov_sparql()
    sparql_texts[_STANDPOINT_OA_QUERY] = emit_standpoint_oa_sparql()
    sparql_texts[_STANDPOINT_SCHEMA_QUERY] = emit_standpoint_schema_sparql()
    sparql_texts[_STANDPOINT_BBC_QUERY] = emit_standpoint_bbc_sparql()
    sssom_texts = {
        f"generated/mappings/{file}": text for file, text in emit_sssom(dsl).items()
    }
    sssom_texts[_DSL_STATS_FILE] = emit_dsl_stats(dsl)
    return rdf_graphs, sparql_texts, sssom_texts


def _write_tree(
    root: Path,
    rdf_graphs: dict[str, Graph],
    sparql_texts: dict[str, str],
    sssom_texts: dict[str, str],
) -> None:
    for rel, graph in rdf_graphs.items():
        retag_graph(graph)  # projection boundary: public BCP-47 only (#287)
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        # Normalise the trailing newline so the pre-commit end-of-file fixer
        # never re-touches a generated file.
        turtle = graph.serialize(format="turtle").rstrip("\n") + "\n"
        path.write_text(turtle, encoding="utf-8")
    for rel, text in {**sparql_texts, **sssom_texts}.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")


def _run_invariants(root: Path) -> list[str]:
    """Run the three projection-lint invariants against a rendered tree."""
    # transforms.fno.ttl is hand-authored — copy it in so the FnO lint sees it.
    shutil.copy2(
        MAPPING_DSL_DIR / _TRANSFORMS_FILE,
        root / "generated" / "projections" / _TRANSFORMS_FILE,
    )
    proj = root / "generated" / "projections"
    queries = root / "generated" / "queries"
    maps = root / "generated" / "mappings"
    return [
        *fno_type_mismatches(proj),
        *fno_reference_integrity(proj),
        *projection_spec_drift(proj, queries, maps),
    ]


#: Canonical tool/code namespace for this surface's diagnostics (#809).
TOOL = "mapping-compile"


def compile_diagnostics_report(
    *,
    tool: str = TOOL,
) -> diagnostics.DiagnosticsReport:
    """Surface the mapping **DSL/compile** diagnostics as canonical findings (#809).

    Deliberately scoped to the DSL → artifact compile path: it loads the mapping
    DSL and builds the artifacts, mapping any ``CompileError`` (a malformed cell,
    missing binding, or unresolved value pattern) to a ``mapping-compile.dsl-error``
    finding. It does NOT run the FnO ``projection_lint`` trio or ``_validate_sssom``
    — those graph/SSSOM checks are being subsumed natively into ``gmeow-rdf`` by
    #848, so wrapping the current Python would only churn code #848 deletes; their
    Findings are tracked in #854 to ride #848's native SSSOM/FnO core. The
    mapping DSL compiler itself is still Python, so this surface is an honest thin
    forward into the Rust ``diagnostics.finding`` model until that too is subsumed.
    """
    report = diagnostics.report(tool)
    try:
        dsl = load_dsl()
        onto = load_merged_graph(include_imports=False)
        _artifacts(dsl, onto)
    except CompileError as exc:
        report.add(
            diagnostics.finding(
                severity="error",
                code=f"{tool}.dsl-error",
                message=str(exc),
                tool=tool,
            )
        )
    return report


def _committed_paths() -> dict[str, Path]:
    paths: dict[str, Path] = {
        f"generated/projections/{_FNO_FILE}": PROJECTIONS_DIR / _FNO_FILE
    }
    for profile in _PROFILES:
        paths[f"generated/projections/{profile}.edoal.ttl"] = (
            PROJECTIONS_DIR / f"{profile}.edoal.ttl"
        )
        paths[f"generated/queries/{profile}.rq"] = (
            PROJECTION_QUERY_DIR / f"{profile}.rq"
        )
    paths[_STANDPOINT_OWL2_QUERY] = PROJECTION_QUERY_DIR / "standpoint-owl2.rq"
    paths[_STANDPOINT_CRMINF_QUERY] = PROJECTION_QUERY_DIR / "standpoint-crminf.rq"
    paths[_STANDPOINT_PROV_QUERY] = PROJECTION_QUERY_DIR / "standpoint-prov.rq"
    paths[_STANDPOINT_OA_QUERY] = PROJECTION_QUERY_DIR / "standpoint-oa.rq"
    paths[_STANDPOINT_SCHEMA_QUERY] = PROJECTION_QUERY_DIR / "standpoint-schema.rq"
    paths[_STANDPOINT_BBC_QUERY] = PROJECTION_QUERY_DIR / "standpoint-bbc.rq"
    paths[_DSL_STATS_FILE] = MAPPINGS_DIR / "dsl-stats.json"
