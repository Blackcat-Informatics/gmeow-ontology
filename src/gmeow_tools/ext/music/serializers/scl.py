"""Scala ``.scl`` projection for a GMEOW :py:class:`TuningSystem`."""

from __future__ import annotations

from typing import TYPE_CHECKING

from gmeow_tools.ext.music.model import Piece

if TYPE_CHECKING:
    from gmeow_tools.ext.music.loss_manifest import NotationProfile


def _edo_degrees(division_count: int) -> list[float]:
    """Return equal-division cents degrees, origin first, octave last."""
    return [i * (1200.0 / division_count) for i in range(division_count + 1)]


def render(piece: Piece, profile: NotationProfile) -> str:
    """Render the first voice's tuning frame to a Scala ``.scl`` string."""
    voice = piece.voices[0] if piece.voices else None
    tuning = voice.tuning if voice else None

    if tuning is not None and tuning.degrees_cents is not None:
        degrees = list(tuning.degrees_cents)
    elif tuning is not None and tuning.division_count is not None:
        degrees = _edo_degrees(tuning.division_count)
    else:
        # Default to 12-EDO when no explicit tuning is supplied.
        degrees = _edo_degrees(12)

    title = piece.title or "GMEOW tuning projection"
    lines = [
        f"! {title}",
        "! Generated by gmeow music render --to scl",
        f"! Projection profile: {profile.projection_function}",
        str(len(degrees) - 1),
        title,
    ]
    for cents in degrees:
        if cents == 0.0:
            lines.append("0.")
        else:
            lines.append(f"{cents:.6f}")
    return "\n".join(lines) + "\n"
