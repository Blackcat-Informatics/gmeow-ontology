// Datalog
// --------------------------------------------------------------------------- //

/// Project to Datalog text (`generated/datalog/gmeow.dl`).
pub fn project_datalog(
    program: &LogicProgram,
    loss: &mut crate::loss_ledger::LossLedger,
) -> ProjectionResult {
    let (kind, cx, drops) = target_meta("datalog");
    let mut lines: Vec<String> = vec![
        "% GENERATED by `gmeow logic compile` — DO NOT EDIT.".to_owned(),
        "% Datalog projection of the canonical logic: program.".to_owned(),
        String::new(),
        "% === Ground facts (axioms) ===".to_owned(),
    ];
    for axiom in &program.axioms {
        let pred = if axiom.predicate == RDF_TYPE {
            "type".to_owned()
        } else {
            datalog_local(&axiom.predicate)
        };
        let obj = dl_term(&axiom.obj, axiom.obj_is_literal);
        let subj = dl_term(&axiom.subject, false);
        lines.push(format!("{pred}({subj}, {obj}, \"{}\").", ctx_str(axiom)));
    }

    lines.push(String::new());
    lines.push("% === Rules ===".to_owned());
    for rule in &program.rules {
        // Aggregation (reduce) rules are outside the Datalog fragment emitted here; they are
        // ledgered (see actual_drops) and projected to the SHACL-AF reduce surface, not
        // mis-emitted as a plain Horn rule.
        if rule.aggregation.is_some() {
            continue;
        }
        let head = &rule.head;
        let head_pred = if head.predicate == RDF_TYPE {
            "type".to_owned()
        } else {
            datalog_local(&head.predicate)
        };
        let head_subj = dl_term(&head.subject, false);
        let head_obj = dl_term(&head.obj, head.obj_is_literal);
        let world = fresh_world_var(rule, "?C");

        let mut body_parts: Vec<String> = Vec::new();
        for ba in &rule.body {
            let bp = if ba.predicate == RDF_TYPE {
                "type".to_owned()
            } else {
                datalog_local(&ba.predicate)
            };
            let bs = dl_term(&ba.subject, false);
            let bo = dl_term(&ba.obj, ba.obj_is_literal);
            let prefix = if ba.negated { "not " } else { "" };
            body_parts.push(format!("{prefix}{bp}({bs}, {bo}, {world})"));
        }
        for (a, b) in &rule.distinct_pairs {
            body_parts.push(format!("{a} != {b}"));
        }
        let body_str = if body_parts.is_empty() {
            "true".to_owned()
        } else {
            body_parts.join(",\n    ")
        };
        lines.push(format!("{head_pred}({head_subj}, {head_obj}, {world}) :-"));
        lines.push(format!("    {body_str}."));
    }

    let content = format!("{}\n", lines.join("\n"));
    let structural: Vec<String> = drops.into_iter().map(str::to_owned).collect();
    let mut actual_drops: Vec<(String, Option<String>)> =
        contract_drop_notes(program, "Datalog", &|_| false)
            .into_iter()
            .map(|n| (n, None))
            .collect();
    actual_drops.extend(aggregation_drop_notes(program, "Datalog"));
    loss.record_projection_drops_attributed("datalog", kind, &structural, &actual_drops);
    ProjectionResult {
        target: "datalog".to_owned(),
        content,
        is_rdf: false,
        preservation: kind,
        complexity: cx.to_owned(),
    }
}

