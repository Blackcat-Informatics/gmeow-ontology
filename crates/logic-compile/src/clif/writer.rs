/// Assemble the RDF/predication channel as sorted CL predications `(<P> <S> <O>)`. This is
/// the **lossless round-trip carrier** — built only from serializers the canonical frontend
/// round-trips at its fixpoint:
///
/// * **the whole program** — axioms (+ scope), rules, formulas, and contracts → the Exact
///   `canonical-rdf12` projection (which reifies rule head/body and full-FOL formula trees
///   and emits contract facets, all of which `parse_logic_dataset` reconstructs);
/// * **correspondences** → `project_correspondence` (round-trips to a content-key-equal
///   correspondence program — `correspondence/tests::projection_round_trips_to_equal_content_key`).
///
/// `path_shapes` are emitted DIRECTLY as the `logic:PathShape` triples the frontend's
/// `extract_path_shapes` reads (a faithful inverse). `transaction_programs` (a correspondence
/// leg's `gm:path` body) are emitted as the `gm:` leg-body triples the frontend's
/// `extract_leg_programs` reads (the faithful inverse of `parse_leg_path`): each leg's body is
/// serialized as a `gm:InversePath` / `gm:SeqPath` / `gm:AltPath` node graph and bound to its
/// leg IRI via `gm:path`. A leg round-trips because the correspondence channel re-emits the
/// `logic:getLeg` / `logic:putLeg` IRIs that name the leg, so the reconstructed leg registry
/// is exactly the original. The Exact claim therefore carries every construct losslessly.
///
/// Returns `Err` if the canonical-RDF-1.2 leg (or its re-parse) fails — the lossless carrier
/// cannot be assembled, which is an invariant break surfaced to the caller, not a panic.
fn meta_predications(program: &LogicProgram) -> gmeow_errors::Result<Vec<String>> {
    let mut preds: Vec<String> = Vec::new();

    // (0) Path shapes — emitted as the logic:PathShape triples `extract_path_shapes` reads.
    for shape in &program.path_shapes {
        preds.extend(path_shape_predications(shape));
    }

    // (0b) Transaction programs (correspondence leg bodies) — emitted as the `gm:` leg-body
    //      triples `extract_leg_programs` reads (the faithful inverse of `parse_leg_path`).
    //      A single counter mints deterministic structural node/cell IRIs so the sorted output
    //      is byte-stable.
    let mut leg_node_counter: usize = 0;
    for tp in &program.transaction_programs {
        let body_root = emit_leg_path(&tp.iri, &tp.body, &mut preds, &mut leg_node_counter);
        // (gm:path <leg-iri> <body-root-node>)
        preds.push(format!(
            "({} {} {})",
            name_term(&gm("path")),
            name_term(&tp.iri),
            name_term(&body_root)
        ));
    }

    // (1) The whole program (axioms + scope + rules + formulas + contracts) → the lossless
    //     canonical RDF 1.2 projection. Rules are reified as nodes (re-deriving the flat
    //     structural axioms exactly on re-parse) and formulas as logic:Formula trees, so the
    //     reconstruction is the Exact `canonical-rdf12` round-trip the frontend already pins.
    //
    //     A correspondence's `logic:` triples (e.g. `logic:confidence` / `logic:mnemomorphic`
    //     on the correspondence node) are DOUBLE-extracted by the frontend as flat axioms too;
    //     emitting them through canonical-rdf12 AND re-projecting them through the
    //     correspondence channel (2) would duplicate them with a different datatype (plain vs
    //     `xsd:decimal`), breaking idempotence. They are owned by the correspondence channel,
    //     so the axiom channel here EXCLUDES any axiom whose subject is a correspondence node
    //     (or one of its child / program nodes).
    //     Path shapes are likewise owned by their own channel (0): the frontend re-extracts a
    //     shape's defining `logic:pathMinDepth` / `pathMaxDepth` / `pathStepPredicate` triples
    //     as flat axioms too, so emitting them through canonical-rdf12 AS WELL would duplicate
    //     them — and with a different lexical form (the path channel emits typed `xsd:integer`
    //     depths, the axiom channel a plain literal), defeating dedup and breaking idempotence.
    //     Exclude any axiom whose subject is a path-shape node.
    let corr_subjects = correspondence_subjects(program);
    let path_subjects: std::collections::HashSet<&str> =
        program.path_shapes.iter().map(|p| p.iri.as_str()).collect();
    let axioms: Vec<_> = program
        .axioms
        .iter()
        .filter(|a| {
            !is_correspondence_owned(&a.subject, &corr_subjects)
                && !path_subjects.contains(a.subject.as_str())
        })
        .cloned()
        .collect();
    let canon_meta = LogicProgram::new(
        axioms,
        program.rules.clone(),
        program.contracts.clone(),
        program.source_iri.clone(),
    )
    .with_formulas(program.formulas.clone());
    let ttl = rdf::project_canonical_rdf12(&canon_meta)
        .map_err(|e| {
            Diag::of_kind(crate::error::Clif {
                detail: format!("CLIF meta channel: canonical-rdf12 projection failed: {e}"),
            })
        })?
        .content;
    preds.extend(quads_as_predications(ttl.as_bytes(), "text/turtle")?);

    // (2) Correspondences → the faithful correspondence N-Triples projection.
    if !program.correspondences.is_empty() {
        let cp = crate::projections::correspondence::CorrespondenceProgram::new(
            program.correspondences.clone(),
            Vec::new(),
            crate::ir::PreservationKind::Exact,
        );
        let nt = crate::projections::correspondence::project_correspondence(&cp);
        preds.extend(quads_as_predications(
            nt.as_bytes(),
            "application/n-triples",
        )?);
    }

    preds.sort();
    preds.dedup();
    Ok(preds)
}

/// The `gm:` namespace (`gmeow:`) — the leg-body path vocabulary the transaction layer uses.
/// Mirrors `crate::projections::correspondence::GM_NAMESPACE` and the frontend's `parse_leg_path`.
const GM_NAMESPACE: &str = "https://blackcatinformatics.ca/gmeow/";
/// `rdf:type`.
const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";

/// A `gm:`-namespaced IRI.
fn gm(local: &str) -> String {
    format!("{GM_NAMESPACE}{local}")
}

/// Emit the structural `gm:` triples for a [`crate::ir::LegPath`] (the faithful inverse of the
/// frontend's `parse_leg_path`) into `preds`, returning the body node IRI a `gm:path` (or a
/// parent combinator) should reference.
///
/// * `Step(pred)` → the predicate IRI itself, with NO structural triples.
/// * `Inverse(inner)` → a `gm:InversePath` node with `gm:pathStep` → the inner body node.
/// * `Seq(members)` / `Alt(members)` → a `gm:SeqPath` / `gm:AltPath` node with `gm:pathSteps` /
///   `gm:pathAlts` heading a `gm:pathNext`-linked cell chain; each cell carries `gm:pathItem`.
///
/// `base` (the leg IRI) only seeds the deterministic node/cell IRI scheme — `parse_leg_path`
/// ignores the structural node names, so any unique deterministic naming round-trips. `counter`
/// is shared across all minted node/cell IRIs to keep them unique and the emission deterministic.
fn emit_leg_path(
    base: &str,
    path: &crate::ir::LegPath,
    preds: &mut Vec<String>,
    counter: &mut usize,
) -> String {
    use crate::ir::LegPath;
    match path {
        LegPath::Step(pred) => pred.clone(),
        LegPath::Inverse(inner) => {
            let node = format!("{base}/legnode/{counter}");
            *counter += 1;
            preds.push(format!(
                "({} {} {})",
                name_term(RDF_TYPE),
                name_term(&node),
                name_term(&gm("InversePath"))
            ));
            let inner_node = emit_leg_path(base, inner, preds, counter);
            preds.push(format!(
                "({} {} {})",
                name_term(&gm("pathStep")),
                name_term(&node),
                name_term(&inner_node)
            ));
            node
        }
        LegPath::Seq(members) => emit_leg_list(
            base,
            members,
            &gm("SeqPath"),
            &gm("pathSteps"),
            preds,
            counter,
        ),
        LegPath::Alt(members) => emit_leg_list(
            base,
            members,
            &gm("AltPath"),
            &gm("pathAlts"),
            preds,
            counter,
        ),
    }
}

/// Emit a `gm:SeqPath` / `gm:AltPath` combinator node and its `gm:pathNext`-linked cell chain,
/// returning the combinator node IRI. `type_iri` is `gm:SeqPath` / `gm:AltPath`; `head_pred` is
/// `gm:pathSteps` / `gm:pathAlts`.
fn emit_leg_list(
    base: &str,
    members: &[crate::ir::LegPath],
    type_iri: &str,
    head_pred: &str,
    preds: &mut Vec<String>,
    counter: &mut usize,
) -> String {
    let node = format!("{base}/legnode/{counter}");
    *counter += 1;
    preds.push(format!(
        "({} {} {})",
        name_term(RDF_TYPE),
        name_term(&node),
        name_term(type_iri)
    ));
    // Mint every cell IRI first so the (node head_pred cell0) and (cell_i pathNext cell_{i+1})
    // links use a stable, deterministic naming independent of recursion order.
    let cell_iris: Vec<String> = members
        .iter()
        .map(|_| {
            let cell = format!("{base}/legcell/{counter}");
            *counter += 1;
            cell
        })
        .collect();
    for (i, member) in members.iter().enumerate() {
        let cell = &cell_iris[i];
        let member_node = emit_leg_path(base, member, preds, counter);
        preds.push(format!(
            "({} {} {})",
            name_term(&gm("pathItem")),
            name_term(cell),
            name_term(&member_node)
        ));
        if let Some(next) = cell_iris.get(i + 1) {
            preds.push(format!(
                "({} {} {})",
                name_term(&gm("pathNext")),
                name_term(cell),
                name_term(next)
            ));
        }
    }
    // (node head_pred cell0)
    if let Some(first) = cell_iris.first() {
        preds.push(format!(
            "({} {} {})",
            name_term(head_pred),
            name_term(&node),
            name_term(first)
        ));
    }
    node
}

/// Emit a [`PathShapeIr`] as the `logic:PathShape` CL predications its frontend extractor
/// reads (a faithful inverse of `extract_path_shapes`). Predicate-first `(P S O)` shape.
fn path_shape_predications(shape: &crate::ir::PathShapeIr) -> Vec<String> {
    let s = name_term(&shape.iri);
    let logic = |local: &str| name_term(&format!("{}{local}", crate::ir::LOGIC_NAMESPACE));
    let rdf_type = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";

    let mut out = vec![format!(
        "({} {s} {})",
        name_term(rdf_type),
        logic("PathShape")
    )];
    match &shape.base {
        crate::ir::PathBase::NamedPredicate(p) => {
            out.push(format!(
                "({} {s} {})",
                logic("pathStepPredicate"),
                name_term(p)
            ));
        }
        crate::ir::PathBase::Wildcard => {
            out.push(format!("({} {s} (lit \"true\"))", logic("pathWildcard")));
        }
    }
    // Depths are integers in the IR (`u32`); emit them as typed `xsd:integer` literals so the
    // generated CL is type-faithful (a consumer reads an integer, not a bare string). The
    // frontend's `parse_positive_int` reads the lexical regardless, so this round-trips.
    let xsd_int = name_term(XSD_INTEGER);
    out.push(format!(
        "({} {s} (lit \"{}\" {xsd_int}))",
        logic("pathMinDepth"),
        shape.min_depth
    ));
    if let Some(max) = shape.max_depth {
        out.push(format!(
            "({} {s} (lit \"{max}\" {xsd_int}))",
            logic("pathMaxDepth")
        ));
    }
    if let Some(ns) = &shape.namespace_scope {
        out.push(format!(
            "({} {s} (lit {}))",
            logic("pathNamespaceScope"),
            quote_string(ns)
        ));
    }
    if let Some(param) = &shape.depth_param {
        out.push(format!(
            "({} {s} (lit {}))",
            logic("pathDepthParam"),
            quote_string(param)
        ));
    }
    out
}

/// The set of correspondence node IRIs whose flat axioms are owned by the correspondence
/// channel (the correspondence individuals, named recovery cases, and singleton
/// `correspondence-program` node). Their projected formula / law-claim / caveat children are
/// matched by IRI prefix in [`is_correspondence_owned`].
fn correspondence_subjects(program: &LogicProgram) -> Vec<String> {
    let mut subjects: Vec<String> = program
        .correspondences
        .iter()
        .flat_map(|c| {
            std::iter::once(c.iri.clone()).chain(c.recovery_cases.iter().map(|r| r.iri.clone()))
        })
        .collect();
    // The `project_correspondence` wrapper node (one per build).
    subjects.push(format!(
        "{}correspondence-program",
        crate::ir::LOGIC_NAMESPACE
    ));
    subjects
}

/// Whether `subject` is a correspondence node (exact match) or one of its child nodes (the
/// `project_correspondence` law-claim IRIs are minted as `<corr-iri>/law-claim/<i>`, so an
/// IRI-prefix test catches them).
fn is_correspondence_owned(subject: &str, corr_subjects: &[String]) -> bool {
    // Zero-allocation prefix test: a child node is `<corr-iri>/…`, so strip the parent IRI
    // and require the remainder to start with `/` (avoids a `format!` per axiom×correspondence).
    corr_subjects.iter().any(|c| {
        subject == c
            || subject
                .strip_prefix(c.as_str())
                .is_some_and(|r| r.starts_with('/'))
    })
}

/// Parse RDF `bytes` of `media_type` and emit each quad as a sorted-later CL predication.
/// Returns `Err` if the projection's own serialized output cannot be re-parsed (an invariant
/// break in the canonical leg, surfaced to the caller rather than panicking).
fn quads_as_predications(bytes: &[u8], media_type: &str) -> gmeow_errors::Result<Vec<String>> {
    let ds = parse_dataset(bytes, media_type, None).map_err(|e| {
        Diag::of_kind(crate::error::Clif {
            detail: format!("CLIF meta channel: re-parse of {media_type} failed: {e}"),
        })
    })?;
    Ok(ds
        .quad_refs()
        .map(|q| {
            let s = term_ref_to_clif(ds.as_ref(), q.s);
            let p = term_ref_to_clif(ds.as_ref(), q.p);
            let o = term_ref_to_clif(ds.as_ref(), q.o);
            format!("({p} {s} {o})")
        })
        .collect())
}

/// Encode a resolved RDF [`TermRef`] as a CL term, faithfully preserving datatype / lang.
fn term_ref_to_clif(ds: &RdfDataset, term: TermRef<'_>) -> String {
    match term {
        TermRef::Iri(iri) => name_term(iri),
        TermRef::Blank { label, .. } => name_term(&format!("_:{label}")),
        TermRef::Literal {
            lexical,
            datatype,
            language,
            ..
        } => {
            if let Some(lang) = language {
                format!("(lit {} @{lang})", quote_string(lexical))
            } else {
                let dt = match ds.resolve(datatype) {
                    TermRef::Iri(s) => s,
                    _ => XSD_STRING,
                };
                if dt == XSD_STRING {
                    format!("(lit {})", quote_string(lexical))
                } else {
                    // Any non-string datatype is carried as `(lit "lex" dt)` — including a
                    // langString with no language (malformed RDF the parser never produces), so
                    // the round-trip stays total rather than silently dropping the datatype.
                    format!("(lit {} {})", quote_string(lexical), name_term(dt))
                }
            }
        }
        // A triple term (RDF 1.2 quoted triple) — the canonical projection uses classic
        // reification, not `<<>>`, so this should not occur; if it does, recurse faithfully.
        TermRef::Triple { s, p, o } => {
            let st = term_ref_to_clif(ds, ds.resolve(s));
            let pt = term_ref_to_clif(ds, ds.resolve(p));
            let ot = term_ref_to_clif(ds, ds.resolve(o));
            format!("(triple {st} {pt} {ot})")
        }
    }
}

