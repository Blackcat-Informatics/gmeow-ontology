fn nemo_iri(iri: &str) -> String {
    format!("<{iri}>")
}

fn nemo_literal(value: &str) -> String {
    let escaped = value.replace('\\', "\\\\").replace('"', "\\\"");
    format!("\"{escaped}\"")
}

/// Project to Nemo `.rls` rule source (`generated/logic/gmeow.rls`).
///
/// # Errors
///
/// Returns `Err` if a rule head contains a variable absent from every body atom
/// (a Nemo safety violation), mirroring the Python `ValueError`.
pub fn project_nemo(program: &LogicProgram) -> Result<ProjectionResult, String> {
    let (kind, cx, drops) = target_meta("nemo");
    let mut lines: Vec<String> = vec![
        "% GENERATED by `gmeow logic compile` — DO NOT EDIT.".to_owned(),
        "% Nemo (.rls) projection of the canonical logic: program.".to_owned(),
        String::new(),
        "% === Ground facts (axioms) ===".to_owned(),
    ];
    for axiom in &program.axioms {
        let pred = nemo_iri(&axiom.predicate);
        let subj = nemo_iri(&axiom.subject);
        let obj = if axiom.obj_is_literal {
            nemo_literal(&axiom.obj)
        } else {
            nemo_iri(&axiom.obj)
        };
        let ctx = if is_modal_or_scoped(axiom) && axiom.scope.modality != LogicModality::None {
            nemo_literal(axiom.scope.modality.as_str())
        } else {
            nemo_literal("default")
        };
        lines.push(format!("{pred}({subj}, {obj}, {ctx})."));
    }

    lines.push(String::new());
    lines.push("% === Rules ===".to_owned());
    for rule in &program.rules {
        let head = &rule.head;
        let head_pred = nemo_iri(&head.predicate);
        let head_subj = if head.subject.starts_with('?') {
            head.subject.clone()
        } else {
            nemo_iri(&head.subject)
        };
        let head_obj = if head.obj.starts_with('?') {
            head.obj.clone()
        } else if head.obj_is_literal {
            nemo_literal(&head.obj)
        } else {
            nemo_iri(&head.obj)
        };

        // Safety: every variable in the head, in a negated body atom, or in a
        // distinct_pairs guard must be bound by at least one POSITIVE (non-negated)
        // body atom.  Variables that appear ONLY in negated atoms or only in a !=
        // guard are unsafe and make Nemo fail or produce wrong results.
        let mut head_vars: Vec<&str> = Vec::new();
        if head.subject.starts_with('?') {
            head_vars.push(&head.subject);
        }
        if head.obj.starts_with('?') {
            head_vars.push(&head.obj);
        }
        let mut positive_body_vars: std::collections::HashSet<&str> =
            std::collections::HashSet::new();
        let mut negated_body_vars: std::collections::HashSet<&str> =
            std::collections::HashSet::new();
        for ba in &rule.body {
            if ba.negated {
                if ba.subject.starts_with('?') {
                    negated_body_vars.insert(&ba.subject);
                }
                if ba.obj.starts_with('?') {
                    negated_body_vars.insert(&ba.obj);
                }
            } else {
                if ba.subject.starts_with('?') {
                    positive_body_vars.insert(&ba.subject);
                }
                if ba.obj.starts_with('?') {
                    positive_body_vars.insert(&ba.obj);
                }
            }
        }
        let mut guard_vars: std::collections::HashSet<&str> = std::collections::HashSet::new();
        for (a, b) in &rule.distinct_pairs {
            if a.starts_with('?') {
                guard_vars.insert(a.as_str());
            }
            if b.starts_with('?') {
                guard_vars.insert(b.as_str());
            }
        }
        let required_vars: std::collections::HashSet<&str> = head_vars
            .iter()
            .copied()
            .chain(negated_body_vars.iter().copied())
            .chain(guard_vars.iter().copied())
            .collect();
        let mut unbound: Vec<&str> = required_vars
            .iter()
            .copied()
            .filter(|v| !positive_body_vars.contains(v))
            .collect();
        if !unbound.is_empty() {
            unbound.sort_unstable();
            return Err(format!(
                "Nemo safety violation: rule head variables {unbound:?} do not appear in \
                 any body atom. Head: {} {} {}",
                head.subject, head.predicate, head.obj
            ));
        }

        let world = fresh_world_var(rule, "?W");
        let mut body_parts: Vec<String> = Vec::new();
        for ba in &rule.body {
            let bp = nemo_iri(&ba.predicate);
            let bs = if ba.subject.starts_with('?') {
                ba.subject.clone()
            } else {
                nemo_iri(&ba.subject)
            };
            let bo = if ba.obj.starts_with('?') {
                ba.obj.clone()
            } else if ba.obj_is_literal {
                nemo_literal(&ba.obj)
            } else {
                nemo_iri(&ba.obj)
            };
            let prefix = if ba.negated { "~" } else { "" };
            body_parts.push(format!("{prefix}{bp}({bs}, {bo}, {world})"));
        }
        for (a, b) in &rule.distinct_pairs {
            body_parts.push(format!("{a} != {b}"));
        }

        let rule_name_iri = rule
            .scope
            .provenance
            .clone()
            .unwrap_or_else(|| format!("{LOGIC_NS}rule/anonymous"));
        let rule_name_escaped = rule_name_iri.replace('\\', "\\\\").replace('"', "\\\"");
        lines.push(format!("#[name(\"{rule_name_escaped}\")]"));

        if body_parts.is_empty() {
            lines.push(format!(
                "{head_pred}({head_subj}, {head_obj}, \"default\")."
            ));
        } else {
            let body_str = body_parts.join(",\n    ");
            lines.push(format!("{head_pred}({head_subj}, {head_obj}, {world}) :-"));
            lines.push(format!("    {body_str} ."));
        }
    }

    let content = format!("{}\n", lines.join("\n"));
    Ok(ProjectionResult {
        target: "nemo".to_owned(),
        content,
        is_rdf: false,
        preservation: kind,
        complexity: cx.to_owned(),
        lossy_drops: drops.into_iter().map(str::to_owned).collect(),
        actual_drops: Vec::new(),
    })
}

/// Extract the `% === Rules ===` section of a `.rls` string (port of
/// `extract_nemo_rules_section`).
///
/// # Errors
///
/// Returns `Err` if the rules marker is absent (corrupt projection output).
pub fn extract_nemo_rules_section(nemo_content: &str) -> Result<String, String> {
    const MARKER: &str = "% === Rules ===";
    match nemo_content.find(MARKER) {
        Some(idx) => Ok(nemo_content[idx + MARKER.len()..].trim().to_owned()),
        None => Err(
            "Nemo projection is missing the \"% === Rules ===\" marker; cannot extract \
             certifier input safely."
                .to_owned(),
        ),
    }
}
