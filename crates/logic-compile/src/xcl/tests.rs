// The real `logic:` namespace (see `crate::ir::LOGIC_NAMESPACE`); a meta-channel triple is only
// re-classified as a domain axiom when its predicate sits in this namespace, so the round-trip
// fixtures must mint their IRIs here.
const LOGIC: &str = "https://blackcatinformatics.ca/logic/";

fn iri(local: &str) -> String {
    format!("{LOGIC}{local}")
}

/// Build a small program with one rule + a formula (quantifier, disjunction, strong negation,
/// sequence marker) + one axiom — the emit-shape fixture.
fn shape_program() -> LogicProgram {
    let axiom = LogicAxiom::ground(iri("a"), iri("knows"), iri("b"), false).expect("axiom");

    let rule = LogicRule::new(
        LogicAxiom::new(
            "?x",
            iri("ancestor"),
            "?z",
            false,
            false,
            ContextualScope::default(),
        )
        .expect("head"),
        vec![
            LogicAxiom::new(
                "?x",
                iri("parent"),
                "?y",
                false,
                false,
                ContextualScope::default(),
            )
            .expect("b1"),
            LogicAxiom::new(
                "?y",
                iri("parent"),
                "?z",
                false,
                false,
                ContextualScope::default(),
            )
            .expect("b2"),
        ],
        vec![("?x".to_owned(), "?z".to_owned())],
        ContextualScope::default(),
    );

    // (forall (?p) (or (mortal ?p …rest) (not (mortal ?p))))  with a sequence marker arg.
    let inner_or = Formula::Or(vec![
        Formula::atom(
            Term::iri(iri("mortal")).unwrap(),
            vec![
                Term::var("p").unwrap(),
                Term::sequence_marker("rest").unwrap(),
            ],
        )
        .unwrap(),
        Formula::Not(Box::new(
            Formula::atom(
                Term::iri(iri("mortal")).unwrap(),
                vec![Term::var("p").unwrap()],
            )
            .unwrap(),
        )),
    ]);
    let formula = Formula::Forall {
        vars: vec!["p".to_owned()],
        body: Box::new(inner_or),
    };

    LogicProgram::new(
        vec![axiom],
        vec![rule],
        Vec::new(),
        Some("urn:test:shape".to_owned()),
    )
    .with_formulas(vec![formula])
}

#[test]
fn emit_shape_contains_idiomatic_xcl_sentences() {
    let p = shape_program();
    let out = project_xcl(&p).expect("project_xcl").content;

    assert!(out.contains("<!-- GENERATED by"), "banner missing:\n{out}");
    assert!(out.contains("<rule>"), "no <rule> for the rule:\n{out}");
    assert!(
        out.contains("<not>"),
        "no <not> for the distinct pair / negation:\n{out}"
    );
    assert!(
        out.contains("<forall>"),
        "no <forall> universal for the formula:\n{out}"
    );
    assert!(
        out.contains("<seq>"),
        "no <seq> for the sequence marker:\n{out}"
    );
    // The axiom rides the RDF channel inside the meta element.
    assert!(
        out.contains("<gmeow-rdf-meta>"),
        "no <gmeow-rdf-meta> carrier for the axiom channel:\n{out}"
    );
}

#[test]
fn projection_is_well_formed_single_root_xml() {
    // The whole document — idiomatic sentence channel + meta carrier — must be well-formed XML
    // with exactly one root element, so any conformant XML/XCL consumer can read it.
    let p = shape_program();
    let out = project_xcl(&p).expect("project_xcl").content;
    let doc = roxmltree::Document::parse(&out).expect("XCL projection must be well-formed XML");
    assert_eq!(
        doc.root_element().tag_name().name(),
        "gmeow-xcl",
        "unexpected root element"
    );
    // Exactly one element child of the document root (the single-root XML invariant).
    let root_elems = doc
        .root()
        .children()
        .filter(roxmltree::Node::is_element)
        .count();
    assert_eq!(
        root_elems, 1,
        "XCL document must have exactly one root element"
    );
}

#[test]
fn comprehensive_round_trip_is_isomorphic() {
    // An axiom, a rule (negated body atom + distinct pair), a full-FOL formula (quantifier +
    // disjunction + sequence marker), plus meta: a reasoning contract and a correspondence.
    let axiom = LogicAxiom::ground(iri("socrates"), iri("isA"), iri("Human"), false).unwrap();

    let rule = LogicRule::new(
        LogicAxiom::new(
            "?x",
            iri("eligible"),
            "?y",
            false,
            false,
            ContextualScope::default(),
        )
        .unwrap(),
        vec![
            LogicAxiom::new(
                "?x",
                iri("member"),
                "?y",
                false,
                false,
                ContextualScope::default(),
            )
            .unwrap(),
            // A negation-as-failure body atom (negated = the 5th arg).
            LogicAxiom::new(
                "?x",
                iri("banned"),
                "?y",
                false,
                true,
                ContextualScope::default(),
            )
            .unwrap(),
        ],
        vec![("?x".to_owned(), "?y".to_owned())],
        ContextualScope::default(),
    );

    let formula = Formula::Exists {
        vars: vec!["w".to_owned()],
        body: Box::new(Formula::Or(vec![
            Formula::atom(
                Term::iri(iri("rel")).unwrap(),
                vec![
                    Term::var("w").unwrap(),
                    Term::sequence_marker("rest").unwrap(),
                ],
            )
            .unwrap(),
            Formula::Not(Box::new(
                Formula::atom(
                    Term::iri(iri("rel")).unwrap(),
                    vec![Term::literal("v", Some(iri("Tag"))).unwrap()],
                )
                .unwrap(),
            )),
        ])),
    };

    let contract = ReasoningContract::from_preset(SemanticProfileId::StratifiedNaf);

    let correspondence = Correspondence::new(
        iri("corr/test"),
        CorrespondenceRelation::Equiv,
        MorphismClass::Isomorphism,
        MorphismKind::InstitutionMorphism,
        true,
        None,
        None,
        None,
        Vec::new(),
        Some(0.9),
        None,
        None,
        None,
        None,
        None,
    )
    .unwrap();

    let orig = LogicProgram::new(
        vec![axiom],
        vec![rule],
        vec![contract],
        Some("urn:test:comprehensive".to_owned()),
    )
    .with_correspondences(vec![correspondence])
    .unwrap()
    .with_formulas(vec![formula]);

    // First normalization: a programmatically-built program is not yet at the frontend's
    // canonical fixpoint. The Exact property is that XCL is an IDEMPOTENT lossless codec at that
    // fixpoint: round-tripping once reaches it, and EVERY further round-trip is identity.
    let src = Some("urn:test:comprehensive".to_owned());
    let xcl1 = project_xcl(&orig).expect("project_xcl").content;
    let (fp, diags1) = parse_xcl_str(&xcl1, src.clone()).expect("parse_xcl_str #1");
    assert!(
        diags1.iter().all(|d| d.code != "XCL_MALFORMED_SENTENCE"),
        "malformed-sentence diagnostics on a well-formed round-trip: {diags1:?}\n--- XCL ---\n{xcl1}"
    );
    // The exercised constructs all survive into the fixpoint.
    assert_eq!(
        fp.correspondences.len(),
        1,
        "the correspondence must survive the round-trip"
    );
    assert_eq!(
        fp.contracts.len(),
        1,
        "the reasoning contract must survive the round-trip"
    );
    assert_eq!(
        fp.formulas.len(),
        1,
        "the full-FOL formula must survive the round-trip"
    );
    assert!(
        fp.rules.iter().any(|r| !r.distinct_pairs.is_empty()),
        "the rule's distinct pair must survive"
    );
    assert!(
        fp.rules.iter().any(|r| r.body.iter().any(|b| b.negated)),
        "the rule's negated body atom must survive"
    );

    // Idempotence: the second round-trip is the exact identity on the fixpoint.
    let xcl2 = project_xcl(&fp).expect("project_xcl").content;
    assert_eq!(
        xcl1, xcl2,
        "XCL emission is not idempotent at the fixpoint (byte drift):\n--- 1 ---\n{xcl1}\n--- 2 ---\n{xcl2}"
    );
    let (fp2, _diags2) = parse_xcl_str(&xcl2, src).expect("parse_xcl_str #2");
    assert_ir_isomorphic(&fp, &fp2).unwrap_or_else(|e| {
        panic!("comprehensive round-trip not idempotent: {e}\n--- XCL ---\n{xcl2}")
    });
    assert!(
        fp == fp2,
        "comprehensive fixpoint round-trip differs (scope / correspondences)"
    );
}

#[test]
#[should_panic(expected = "iri-disallowed-char")]
fn xml_and_ntriples_forbidden_chars_are_refused_by_the_rdf_ir() {
    // `{ } | ^ ` `` ` ``, a space, a TAB and an XML-significant `&` are not legal in an IRI
    // (RFC 3987), so the RDF IR refuses to intern one carrying them and names the offending
    // character and its byte offset. This test used to assert the opposite — that such an
    // IRI SURVIVED a `project_xcl` round trip verbatim. It did, because the IR interned it
    // unchecked and the codec emitted output no conforming parser would read back.
    //
    // Refusal is the correct behaviour and is pinned here so a regression to silent
    // acceptance is caught. The N-Triples `\uXXXX` escaping is covered directly by
    // `crate::nt::tests`; the XML attribute/text escaping keeps its own dedicated
    // `xml_escape_attr` / `xml_escape_text` coverage in this module.
    let weird_iri = format!("{LOGIC}weird/a{{b}}c|d^e`f g\th&amp");
    let axiom = LogicAxiom::ground(weird_iri, iri("knows"), iri("target"), false).unwrap();
    let orig = LogicProgram::new(
        vec![axiom],
        Vec::new(),
        Vec::new(),
        Some("urn:test:iri".to_owned()),
    );
    let _ = project_xcl(&orig);
}

#[test]
#[should_panic(expected = "iri-disallowed-char")]
fn control_chars_del_c1_c0_are_refused_by_the_rdf_ir() {
    // DEL (0x7F), a C1 control (0x85) and a C0 control (0x01) are not legal in an IRI
    // (RFC 3987), so the RDF IR refuses to intern one carrying them and names the offending
    // codepoint and its byte offset. This test used to assert the opposite — that such an
    // IRI SURVIVED the round trip verbatim. It did, because the IR interned it unchecked
    // and the codec emitted output no conforming parser would read back.
    //
    // Refusal is the correct behaviour and is pinned here so a regression to silent
    // acceptance is caught. The full-control-range `\uXXXX` escaping this test formerly
    // reached only indirectly is covered directly by `crate::nt::tests`.
    let weird = format!("{LOGIC}weird/a\u{7F}b\u{85}c\u{01}d");
    let axiom = LogicAxiom::ground(weird, iri("knows"), iri("target"), false).unwrap();
    let orig = LogicProgram::new(
        vec![axiom],
        Vec::new(),
        Vec::new(),
        Some("urn:test:iri".to_owned()),
    );
    let _ = project_xcl(&orig);
}

#[test]
fn xml_escape_renders_del_and_c1_as_char_refs_not_replacement() {
    // The sentence-view escaper must treat DEL (0x7F) and the C1 block (0x80-0x9F) as legal XML
    // 1.0 `Char`s — emitting them as numeric character references — and reserve U+FFFD only for
    // the C0 controls XML forbids outright (here 0x01). Tab/LF/CR pass through raw.
    let s = "a\u{7F}b\u{85}c\u{01}d\t&<>";
    let text = xml_escape_text(s);
    assert!(
        text.contains("&#x7F;"),
        "DEL must ride as a char ref: {text}"
    );
    assert!(
        text.contains("&#x85;"),
        "C1 must ride as a char ref: {text}"
    );
    assert!(
        text.contains('\u{FFFD}'),
        "an XML-illegal C0 control must become U+FFFD: {text}"
    );
    assert!(
        !text.contains('\u{01}'),
        "raw 0x01 must not survive: {text}"
    );
    assert!(text.contains('\t'), "TAB must pass through raw: {text}");
    assert_eq!(&text[text.len() - 15..], "d\t&amp;&lt;&gt;");
    // The whole escaped text node must be legal inside a well-formed XML document.
    let doc = format!("<r>{text}</r>");
    roxmltree::Document::parse(&doc).expect("escaped text must be well-formed XML");

    // Attribute escaping shares the rule and additionally escapes the double quote.
    let attr = xml_escape_attr("q\"\u{85}\u{01}");
    assert!(attr.contains("&quot;") && attr.contains("&#x85;") && attr.contains('\u{FFFD}'));
}

#[test]
fn path_shape_round_trips_with_typed_integer_depths() {
    // A logic:PathShape rides the RDF/predication channel. Its min/max depths are integers in the
    // IR (`u32`) and are emitted as typed `xsd:integer` literals; the whole shape must survive.
    let shape = PathShapeIr::new(
        iri("shape/ancestry"),
        PathBase::NamedPredicate(iri("parent")),
        1,
        Some(7),
        None,
        None,
    )
    .unwrap();
    let orig = LogicProgram::new(
        Vec::new(),
        Vec::new(),
        Vec::new(),
        Some("urn:test:pathshape".to_owned()),
    )
    .with_path_shapes(vec![shape]);

    let src = Some("urn:test:pathshape".to_owned());
    let xcl1 = project_xcl(&orig).expect("project_xcl").content;
    // The depths are carried as typed xsd:integer literals, not bare strings.
    assert!(
        xcl1.contains("http://www.w3.org/2001/XMLSchema#integer"),
        "path-shape depths are not emitted as typed xsd:integer literals:\n{xcl1}"
    );

    let (fp, _diags) = parse_xcl_str(&xcl1, src.clone()).expect("parse_xcl_str");
    assert_eq!(fp.path_shapes.len(), 1, "the path shape must survive");
    let got = &fp.path_shapes[0];
    assert_eq!(got.min_depth, 1, "min_depth lost");
    assert_eq!(got.max_depth, Some(7), "max_depth lost");
    assert!(
        matches!(&got.base, PathBase::NamedPredicate(p) if *p == iri("parent")),
        "path base predicate lost: {:?}",
        got.base
    );

    // Idempotent at the fixpoint.
    let xcl2 = project_xcl(&fp).expect("project_xcl").content;
    assert_eq!(xcl1, xcl2, "path-shape XCL emission is not idempotent");
}

#[test]
fn cl_modules_and_importation_round_trip_at_fixpoint() {
    // CL modules + importation + per-statement module membership survive XCL at Exact, exactly
    // like CLIF/CGIF. Module objects and the import graph ride the axiom channel; per-statement
    // membership rides the reifier-scope carrier (`logic:inModule`). Compared at the canonical
    // FIXPOINT (the Exact reference).
    let m1 = "https://example.org/module/geometry".to_owned();
    let m2 = "https://example.org/module/algebra".to_owned();
    let rdf_type = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";

    let m1_is_module = LogicAxiom::ground(m1.clone(), rdf_type, iri("Module"), false).unwrap();
    let m2_is_module = LogicAxiom::ground(m2.clone(), rdf_type, iri("Module"), false).unwrap();
    let imports = LogicAxiom::ground(m1.clone(), iri("imports"), m2.clone(), false).unwrap();

    let scope = ContextualScope::new(
        None,
        None,
        None,
        LogicModality::None,
        None,
        Some(m1.clone()),
    )
    .unwrap();
    let scoped = LogicAxiom::new(
        iri("point"),
        iri("liesOn"),
        iri("line"),
        false,
        false,
        scope,
    )
    .unwrap();

    let orig = LogicProgram::new(
        vec![m1_is_module, m2_is_module, imports, scoped],
        Vec::new(),
        Vec::new(),
        Some("urn:test:modules".to_owned()),
    );
    let src = Some("urn:test:modules".to_owned());

    // Reach the canonical fixpoint.
    let (fp, _d0) = parse_xcl_str(
        &project_xcl(&orig).expect("project #0").content,
        src.clone(),
    )
    .expect("parse #0");

    // Module objects + the import edge survive (they ride the ordinary axiom channel).
    assert!(
        fp.axioms
            .iter()
            .any(|a| a.subject == m1 && a.predicate == iri("imports") && a.obj == m2),
        "module import edge lost:\n{:#?}",
        fp.axioms
    );
    assert!(
        fp.axioms
            .iter()
            .any(|a| a.subject == m1 && a.predicate == rdf_type && a.obj == iri("Module")),
        "logic:Module type declaration lost"
    );
    // Per-statement module membership survives on the scoped statement.
    assert!(
        fp.axioms
            .iter()
            .any(|a| a.predicate == iri("liesOn") && a.scope.module.as_deref() == Some(m1.as_str())),
        "logic:inModule membership lost:\n{:#?}",
        fp.axioms
    );

    // Idempotent + isomorphic at the fixpoint.
    let xcl1 = project_xcl(&fp).expect("project #1").content;
    let (fp2, _d) = parse_xcl_str(&xcl1, src).expect("parse #1");
    let xcl2 = project_xcl(&fp2).expect("project #2").content;
    assert_eq!(
        xcl1, xcl2,
        "module XCL emission is not idempotent at the fixpoint"
    );
    assert_ir_isomorphic(&fp, &fp2)
        .unwrap_or_else(|e| panic!("module round-trip not isomorphic: {e}"));
}

#[test]
fn hilog_relation_as_individual_round_trips() {
    // HiLog reflection: a relation is simultaneously an individual. `related` is used BOTH as an
    // atom predicate AND as the subject of a typing (logic:instanceOf logic:Type,
    // logic:orderedType) — reusing existing terms, minting none (P5/P17). Both readings must
    // round-trip through XCL.
    let related = iri("related");
    let ax_pred = LogicAxiom::ground(iri("a"), related.clone(), iri("b"), false).unwrap();
    let ax_instanceof =
        LogicAxiom::ground(related.clone(), iri("instanceOf"), iri("Type"), false).unwrap();
    let ax_ordered = LogicAxiom::ground(
        related.clone(),
        iri("orderedType"),
        iri("BinaryRelation"),
        false,
    )
    .unwrap();

    let orig = LogicProgram::new(
        vec![ax_pred, ax_instanceof, ax_ordered],
        Vec::new(),
        Vec::new(),
        Some("urn:test:hilog".to_owned()),
    );
    let src = Some("urn:test:hilog".to_owned());
    let xcl1 = project_xcl(&orig).expect("project #1").content;
    let (fp, _d) = parse_xcl_str(&xcl1, src.clone()).expect("parse");

    // The relation survives BOTH as a predicate and as a typed individual.
    assert!(
        fp.axioms
            .iter()
            .any(|a| a.predicate == related && a.subject == iri("a") && a.obj == iri("b")),
        "relation-as-predicate reading lost:\n{:#?}",
        fp.axioms
    );
    assert!(
        fp.axioms.iter().any(|a| a.subject == related
            && a.predicate == iri("instanceOf")
            && a.obj == iri("Type")),
        "relation-as-individual (instanceOf Type) reading lost:\n{:#?}",
        fp.axioms
    );
    assert!(
        fp.axioms
            .iter()
            .any(|a| a.subject == related && a.predicate == iri("orderedType")),
        "orderedType typing lost"
    );

    // Idempotent.
    let xcl2 = project_xcl(&fp).expect("project #2").content;
    assert_eq!(xcl1, xcl2, "HiLog XCL emission is not idempotent");
}

