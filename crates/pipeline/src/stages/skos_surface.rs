//! The `skos-surface` export leaf (P4): the generated SKOS concept-scheme surface
//! (AC1/R3).
//!
//! A pure projection of the lifted [`NodeKind::Annotation`] axioms: every
//! GMEOW-authored, carrier-tagged (`@x-gmeow-english`) RDFS/SKOS annotation the
//! `logic:` frontend lifts (`parse_logic_dataset`) is re-emitted as a triple on the
//! authored term, and each term is bound into ONE minted `skos:ConceptScheme`
//! individual. The surface is a pure function of the lifted axiom set (AC1
//! anti-drift): [`render_skos_surface_from_axioms`] never re-reads the source
//! triples. The materialized `generated/skos/gmeow-skos.ttl` (git-ignored) is
//! written back through the RDF-fanout writer's own serializer, so the anti-drift
//! gate compares it to this stage's render SEMANTICALLY (as a set of triples), the
//! same way the superset/fold gate compares the graph.

use std::collections::BTreeMap;
use std::path::Path;

use gmeow_errors::abox::{AboxObject, X_GMEOW_ENGLISH, abox_annotations};
use gmeow_logic_compile::ir::{LogicAxiom, NodeKind};
use purrdf::{RdfDatasetBuilder, RdfLiteral, RdfQuad, RdfTerm, SerializeGraph, serialize_dataset};

use crate::node::{Stage, StageInput, StageOutput, StageProduct};

/// Committed logical path of the generated SKOS concept-scheme surface.
pub const SKOS_SURFACE_PATH: &str = "generated/skos/gmeow-skos.ttl";

const NS: &str = "https://blackcatinformatics.ca/gmeow/";
/// The local name of the one minted concept-scheme individual every projected term is
/// bound into; its IRI is `{NS}{SCHEME_LOCAL}`.
const SCHEME_LOCAL: &str = "GmeowConceptScheme";

const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";
const SKOS_CONCEPT_SCHEME: &str = "http://www.w3.org/2004/02/skos/core#ConceptScheme";
const SKOS_IN_SCHEME: &str = "http://www.w3.org/2004/02/skos/core#inScheme";
const OWL_NAMED_INDIVIDUAL: &str = "http://www.w3.org/2002/07/owl#NamedIndividual";

const HEADER: &str = "# GENERATED by `gmeow-dev sync --mode update --outputs generated` (skos-surface):\n# a projection of the lifted NodeKind::Annotation axioms (GMEOW-authored RDFS/SKOS\n# annotations) into a SKOS concept scheme — DO NOT EDIT.\n";

/// The deterministic per-committed-path graph-identity IRI every minted individual's
/// `rdfs:isDefinedBy` carries — the same identity
/// [`crate::stages::superset::rdf_fanout_graph_iri`] derives for any RDF file under
/// `generated/`.
fn skos_surface_graph_iri() -> String {
    crate::stages::superset::rdf_fanout_graph_iri(SKOS_SURFACE_PATH)
        .expect("SKOS_SURFACE_PATH is a committed .ttl path under generated/")
}

/// A skos-surface serialization diagnostic on the unified Diag substrate.
fn parse_err(message: String) -> gmeow_errors::Diag {
    gmeow_errors::Diag::of_kind(crate::error::Parse { message })
}

/// Push the four A-Box annotation contract triples for `subject_iri` into the builder's
/// DEFAULT graph, routing through the single [`abox_annotations`] contract core (the
/// predicate set + `boxABox` box-role default live ONLY there). The contract triples
/// ride the default graph (not `annotate_builder`'s named graph) so the Turtle
/// serializer — which flattens to the default graph — reproduces them.
fn push_abox_contract(
    builder: &mut RdfDatasetBuilder,
    subject_iri: &str,
    label: &str,
    definition: &str,
    graph_iri: &str,
) {
    let subject = RdfTerm::iri(subject_iri.to_owned());
    for (predicate, object) in abox_annotations(subject_iri, label, definition, graph_iri) {
        let object_term = match object {
            AboxObject::Iri(iri) => RdfTerm::iri(iri),
            AboxObject::CarrierLiteral(value) => {
                RdfTerm::literal(RdfLiteral::language_tagged(value, X_GMEOW_ENGLISH))
            }
        };
        builder.push_owned_quad(&RdfQuad::new(subject.clone(), predicate, object_term));
    }
}

/// Render the SKOS concept-scheme surface as a PURE FUNCTION of the lifted annotation
/// axioms — the AC1 anti-drift contract. The surface is built ONLY from the passed
/// axioms (never a re-read of the source triples): one minted `skos:ConceptScheme`
/// individual carrying the full A-Box annotation contract, every annotation axiom
/// re-emitted as a carrier-tagged triple on its authored subject, and one
/// `skos:inScheme` binding per subject.
pub fn render_skos_surface_from_axioms(
    annotations: &[LogicAxiom],
) -> Result<String, gmeow_errors::Diag> {
    let graph_iri = skos_surface_graph_iri();
    let scheme_iri = format!("{NS}{SCHEME_LOCAL}");
    let mut builder = RdfDatasetBuilder::new();

    // The one minted concept-scheme individual. Typed (so the structural lint holds it
    // to the A-Box contract, which it satisfies); the projected terms below stay
    // UNTYPED so the lint's per-term contract checks never fire on them.
    let scheme = RdfTerm::iri(scheme_iri.clone());
    builder.push_owned_quad(&RdfQuad::new(
        scheme.clone(),
        RDF_TYPE,
        RdfTerm::iri(SKOS_CONCEPT_SCHEME.to_owned()),
    ));
    builder.push_owned_quad(&RdfQuad::new(
        scheme.clone(),
        RDF_TYPE,
        RdfTerm::iri(OWL_NAMED_INDIVIDUAL.to_owned()),
    ));
    push_abox_contract(
        &mut builder,
        &scheme_iri,
        "GMEOW Concept Scheme",
        "The generated SKOS concept scheme projecting every GMEOW-authored term's lifted RDFS/SKOS annotations.",
        &graph_iri,
    );

    // Group the annotation axioms by subject (BTreeMap → deterministic subject order,
    // one `skos:inScheme` binding per subject).
    let mut by_subject: BTreeMap<&str, Vec<&LogicAxiom>> = BTreeMap::new();
    for axiom in annotations {
        by_subject
            .entry(axiom.subject.as_str())
            .or_default()
            .push(axiom);
    }
    for (subject, axioms) in &by_subject {
        let subject_term = RdfTerm::iri((*subject).to_owned());
        for axiom in axioms {
            // The six `ANNOTATION_LIFT_PREDS` are all literal-range predicates, so every
            // `NodeKind::Annotation` axiom must carry a literal object. Assert it rather than
            // silently rendering a future non-literal annotation as a language-tagged literal.
            debug_assert!(
                axiom.obj.is_literal(),
                "NodeKind::Annotation axiom on {subject} ({}) must be literal-valued",
                axiom.predicate
            );
            builder.push_owned_quad(&RdfQuad::new(
                subject_term.clone(),
                axiom.predicate.clone(),
                RdfTerm::literal(axiom.obj.as_literal().expect("literal annotation").clone()),
            ));
        }
        builder.push_owned_quad(&RdfQuad::new(
            subject_term.clone(),
            SKOS_IN_SCHEME,
            scheme.clone(),
        ));
    }

    let dataset = builder
        .freeze()
        .map_err(|e| parse_err(format!("skos-surface: freeze failed: {e}")))?;
    // All projected quads live in the default graph → `SerializeGraph::DefaultGraph` is
    // faithful. Every row of this surface is an independent one-line triple (all
    // IRIs/literals, no blank nodes or `;`/`,` grouping), so we can canonicalize the
    // serializer's output by sorting its rows.
    let bytes = serialize_dataset(
        dataset.as_ref(),
        "text/turtle",
        SerializeGraph::DefaultGraph,
    )
    .map_err(|e| parse_err(format!("skos-surface: serialize failed: {e}")))?;
    let raw = String::from_utf8(bytes)
        .map_err(|e| parse_err(format!("skos-surface: non-UTF8 serialization: {e}")))?;
    // purrdf's parallel de-dup serializer does NOT pin its row order across runs
    // (the order varies with thread scheduling under load). Partition the `@prefix`/
    // `@base` directives from the triple rows and sort each block bytewise so this
    // stage's direct render is a reproducible, byte-stable artifact regardless of thread
    // timing. (The materialized `generated/skos/gmeow-skos.ttl` rides the RDF-fanout
    // writer's own serializer, so the anti-drift gate compares the two SEMANTICALLY —
    // see `skos_surface_matches_the_materialized_projection` — but a stable direct render
    // keeps this producer deterministic in its own right.)
    let mut directives: Vec<&str> = Vec::new();
    let mut triples: Vec<&str> = Vec::new();
    for line in raw.lines() {
        let line = line.trim_end();
        if line.is_empty() {
            continue;
        }
        if line.starts_with('@') || line.starts_with("PREFIX ") || line.starts_with("BASE ") {
            directives.push(line);
        } else {
            triples.push(line);
        }
    }
    directives.sort_unstable();
    triples.sort_unstable();
    let mut body = String::new();
    for directive in &directives {
        body.push_str(directive);
        body.push('\n');
    }
    if !directives.is_empty() && !triples.is_empty() {
        body.push('\n');
    }
    for triple in &triples {
        body.push_str(triple);
        body.push('\n');
    }
    Ok(format!("{HEADER}{body}"))
}

/// Render the SKOS concept-scheme surface for the authored corpus at `root`: load the
/// full authored dataset, lift its RDFS/SKOS annotations into `NodeKind::Annotation`
/// axioms via the `logic:` frontend, then project through the pure
/// [`render_skos_surface_from_axioms`].
pub fn render_skos_surface(root: &Path) -> Result<String, gmeow_errors::Diag> {
    let dataset = crate::stages::source_load::load_authored_dataset(root)?;
    let (program, _diags) =
        gmeow_logic_compile::frontend::parse_logic_dataset(dataset.as_ref(), None)
            .map_err(|e| parse_err(format!("skos-surface: logic lift failed: {e}")))?;
    let mut annotations: Vec<LogicAxiom> = program
        .axioms
        .iter()
        .filter(|a| a.node_kind == NodeKind::Annotation)
        .cloned()
        .collect();
    annotations.sort_by_key(LogicAxiom::sort_key);
    render_skos_surface_from_axioms(&annotations)
}

// ── Stage impl ───────────────────────────────────────────────────────────────

/// The `skos-surface` export-leaf stage.
pub struct SkosSurfaceStage;

impl Stage for SkosSurfaceStage {
    fn id(&self) -> &str {
        "stage-export-skos-surface"
    }
    fn consumes(&self) -> &[String] {
        &[]
    }
    fn impl_version(&self) -> &str {
        "skos_surface.v1"
    }
    fn input_files(&self, root: &Path) -> Result<Vec<std::path::PathBuf>, gmeow_errors::Diag> {
        // The RDFS/SKOS annotations this leaf lifts ARE in the fold's authored default
        // graph; declaring the SAME authored sources (root ontology + slice modules) as
        // cache inputs keeps `consumes() == []` while busting the cache on any authored
        // annotation change (mirrors `frame_shapes`).
        let mut files = vec![root.join("ontology").join("gmeow.ttl")];
        files.extend(crate::stages::source_load::module_files(root)?);
        Ok(files)
    }
    fn run(&self, input: StageInput<'_>) -> Result<StageOutput, gmeow_errors::Diag> {
        let ttl = render_skos_surface(input.root)?;
        let mut artifacts: BTreeMap<String, Vec<u8>> = BTreeMap::new();
        artifacts.insert(SKOS_SURFACE_PATH.to_string(), ttl.into_bytes());
        Ok(StageOutput::new(StageProduct::from_artifacts(
            self.id(),
            artifacts,
        )))
    }
}

