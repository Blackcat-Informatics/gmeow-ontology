def _term(atom: Atom, var_map: dict[str, str] | None = None) -> str:
    if atom.object_var is not None:
        obj_var = atom.object_var
        if var_map and obj_var in var_map:
            obj_var = var_map[obj_var]
        return f"?{obj_var}"
    if atom.object_value is not None:
        return curie(atom.object_value)
    if atom.object_literal is not None:
        lit = atom.object_literal
        if lit.datatype == URIRef(PREFIXES["xsd"] + "boolean"):
            return "true" if str(lit).lower() in ("true", "1") else "false"
        return sparql_string(str(lit))
    raise CompileError("atom has no object")


def _atom_triple(atom: Atom, var_map: dict[str, str] | None = None) -> str:
    subj_var = atom.subject_var
    if var_map and subj_var in var_map:
        subj_var = var_map[subj_var]
    subj = f"?{subj_var}"
    if atom.path is not None:
        pred = atom.path
    elif atom.predicate_var is not None:
        pred = f"?{atom.predicate_var}"
    elif atom.predicate == RDF.type and atom.object_value is not None:
        pred = "a"
    elif atom.predicate is not None:
        pred = curie(atom.predicate)
    else:
        raise CompileError(f"atom on ?{atom.subject_var} has no predicate/path")
    return f"{subj} {pred} {_term(atom, var_map)} ."


def _class_var(pattern: MappingPattern) -> str:
    return f"{pattern.value}Class"


def _where_items(
    items: tuple[Atom | OptionalGroup, ...], indent: str = ""
) -> list[str]:
    """Render WHERE items (atoms + nested OPTIONAL groups) at a relative indent."""
    out: list[str] = []
    for item in items:
        if isinstance(item, OptionalGroup):
            out.append(f"{indent}OPTIONAL {{")
            out.extend(_where_items(item.items, indent + "    "))
            out.append(f"{indent}}}")
        else:
            triple = _atom_triple(item)
            wrapped = f"OPTIONAL {{ {triple} }}" if item.optional else triple
            out.append(f"{indent}{wrapped}")
    return out


@dataclass(frozen=True, slots=True)
class SuppressionVocab:
    """Ontology-derived suppression knowledge for guard injection (#282).

    "Suppression-bearing" is determined from the ontology, never from a
    hand-maintained list: a new appellation subclass or bearer property
    extends the guards on the next regenerate.
    """

    #: Properties whose range is ⊑ gmeow:Appellation — the bearer→appellation
    #: links, used (as an alternation) to guard an appellation whose bearer is
    #: not bound in the branch pattern.
    bearer_props: tuple[URIRef, ...]
    #: Properties whose domain is ⊑ gmeow:Appellation — reading one marks the
    #: subject variable as an appellation.
    appellation_domain_props: frozenset[URIRef]
    #: Classes ⊑ gmeow:Appellation, for explicit ``a gmeow:X`` pattern atoms.
    appellation_classes: frozenset[URIRef]
    #: Properties annotated ``gmeow:coarsenGuarded true`` — reading one means
    #: the subject's precise values must not pass a ``gmeow:coarsenTo`` mark.
    coarsen_guarded: frozenset[URIRef]


def _subclass_closure(graph: Graph, root: URIRef) -> frozenset[URIRef]:
    """``root`` plus every class transitively ``rdfs:subClassOf`` it."""
    closure: set[URIRef] = {root}
    grew = True
    while grew:
        grew = False
        for sub, sup in graph.subject_objects(RDFS.subClassOf):
            if sup in closure and isinstance(sub, URIRef) and sub not in closure:
                closure.add(sub)
                grew = True
    return frozenset(closure)


def suppression_vocab(onto: Graph) -> SuppressionVocab:
    """Derive the suppression vocabulary from the merged ontology."""
    appellation = GM.Appellation
    guarded = GM.coarsenGuarded
    classes = _subclass_closure(onto, appellation)
    bearer: set[URIRef] = set()
    domain_props: set[URIRef] = set()
    for prop, rng in onto.subject_objects(RDFS.range):
        if rng in classes and isinstance(prop, URIRef):
            bearer.add(prop)
    for prop, dom in onto.subject_objects(RDFS.domain):
        if dom in classes and isinstance(prop, URIRef):
            domain_props.add(prop)
    coarsen = {
        s
        for s, o in onto.subject_objects(guarded)
        if isinstance(s, URIRef) and str(o) == "true"
    }
    return SuppressionVocab(
        bearer_props=tuple(sorted(bearer)),
        appellation_domain_props=frozenset(domain_props),
        appellation_classes=classes,
        coarsen_guarded=frozenset(coarsen),
    )


@lru_cache(maxsize=1)
def _default_suppression_vocab() -> SuppressionVocab:
    """The vocab over the merged ontology (cached; used outside _artifacts)."""
    return suppression_vocab(load_merged_graph(include_imports=False))


def _suppression_anchors(p: MappingPattern) -> list[str]:
    """Subject variables of the REQUIRED pattern atoms, in pattern order.

    These are the gmeow-side entities a branch reads; ``gmeow:displayable``
    is deliberately domain-free, so EVERY one of them may carry
    ``displayable false`` and every one gets a withhold guard (#282,
    CONSTITUTION P10 — the producer enforces the display contract; consumers
    are never trusted to). Variables bound only inside OPTIONAL groups (or
    optional atoms) are excluded: a ``FILTER NOT EXISTS`` over a variable the
    solution leaves unbound would match ANY suppressed entity in the dataset
    and silently kill the whole branch.
    """
    anchors: list[str] = []
    for item in p.atoms:
        if isinstance(item, OptionalGroup) or item.optional:
            continue
        if item.subject_var not in anchors:
            anchors.append(item.subject_var)
    return anchors


def _required_atoms(p: MappingPattern) -> list[Atom]:
    """The top-level, non-optional pattern atoms (guard-injection scope)."""
    return [
        item
        for item in p.atoms
        if not isinstance(item, OptionalGroup) and not item.optional
    ]


def _injected_guards(p: MappingPattern, vocab: SuppressionVocab) -> list[str]:
    """The ontology-derived suppression guards for one branch (#282, P10).

    Three families, all fail-closed:

    * a ``displayable false`` withhold per required subject variable;
    * a ``coarsenTo`` filter wherever a required atom reads a
      ``gmeow:coarsenGuarded`` property — precise values never pass the
      mark; the coarse form is published only by a profile's explicit
      coarsening branch;
    * a bearer guard for appellation variables whose bearer is NOT bound in
      the pattern — a suppressed entity's otherwise-unmarked name must not
      surface through a bearer-less lexical branch.
    """
    required = _required_atoms(p)
    guards: list[str] = []
    # A variable whose pattern (or authored guards) already SPEAKS about
    # gmeow:displayable keeps its authored polarity — e.g. the mailmap
    # remapping cell positively matches `displayable false` because emitting
    # superseded identities under the canonical one IS the projection
    # (a licensed, reviewable re-publication; P10's retain-don't-delete).
    displayable_authored = {
        atom.subject_var
        for atom in (*required, *p.suppress_when, *p.project_when)
        if atom.predicate == GM.displayable
    }
    for var in _suppression_anchors(p):
        if var in displayable_authored:
            continue
        guards.append(f"FILTER NOT EXISTS {{ ?{var} gmeow:displayable false . }}")
    coarsen_suppressed = {
        atom.subject_var for atom in p.suppress_when if atom.predicate == GM.coarsenTo
    }
    for atom in required:
        if atom.predicate in vocab.coarsen_guarded:
            if atom.subject_var in coarsen_suppressed:
                continue  # the profile's authored coarsening branch governs
            guard = f"FILTER NOT EXISTS {{ ?{atom.subject_var} gmeow:coarsenTo [] . }}"
            if guard not in guards:
                guards.append(guard)
    bearer_visible = {
        atom.object_var
        for atom in required
        if atom.predicate in vocab.bearer_props
        or (atom.path_alts and set(atom.path_alts) & set(vocab.bearer_props))
    }
    appellation_vars: list[str] = []
    for atom in required:
        is_appellation = atom.predicate in vocab.appellation_domain_props or (
            atom.predicate == RDF.type
            and atom.object_value in vocab.appellation_classes
        )
        if (
            is_appellation
            and atom.subject_var not in bearer_visible
            and atom.subject_var not in appellation_vars
        ):
            appellation_vars.append(atom.subject_var)
    if appellation_vars and vocab.bearer_props:
        alternation = "|".join(curie(prop) for prop in vocab.bearer_props)
        for var in appellation_vars:
            guards.append(
                f"FILTER NOT EXISTS {{ ?_supBearer {alternation} ?{var} . "
                f"?_supBearer gmeow:displayable false . }}"
            )
    return guards


def _branch(cell: ProjectionCell, b: ProfileBinding, vocab: SuppressionVocab) -> str:
    p = cell.pattern
    lines: list[str] = _where_items(p.atoms)
    if b.value_class_map:
        cv = _class_var(p)
        lines.append(f"VALUES ( ?{p.value} ?{cv} ) {{")
        for vc in b.value_class_map:
            lines.append(f"    ( {curie(vc.when_value)} {curie(vc.to_class)} )")
        lines.append("}")
    for mint in p.mints:
        lines.append(f"BIND ( {render_expr(mint.expr)} AS ?{mint.var} )")
    for bind in p.binds:
        lines.append(f"BIND ( {render_expr(bind.expr)} AS ?{bind.var} )")
    authored_guards: set[str] = set()
    for atom in (*p.suppress_when, *p.exclude_when):
        guard = f"FILTER NOT EXISTS {{ {_atom_triple(atom)} }}"
        authored_guards.add(guard)
        lines.append(guard)
    # Suppression by construction (#282): P10's guards are injected into
    # every branch — derived from the pattern + ontology, never hand lists.
    for guard in _injected_guards(p, vocab):
        if guard not in authored_guards:
            lines.append(guard)
    for atom in p.project_when:
        lines.append(f"FILTER EXISTS {{ {_atom_triple(atom)} }}")
    for flt in p.filters:
        lines.append(f"FILTER( {render_expr(flt)} )")

    # Auto-retag GMEOW internal language tags (x-gmeow-...)
    val = p.value
    retag_lines = []
    bind_expr = None
    flat_atoms = _flatten_atoms(p.atoms)
    if p.edoal_source == GM.fullName:
        parent_var = None
        for a in flat_atoms:
            if a.predicate == GM.fullName:
                parent_var = a.subject_var
                break
        if parent_var:
            lang_var = "_lang"
            for a in flat_atoms:
                if a.predicate == GM.nameLanguage and a.subject_var == parent_var:
                    lang_var = a.object_var or lang_var
                    break
            ext_tag_var = "_extTag"
            for a in flat_atoms:
                if a.predicate == GM.bcp47Tag and a.subject_var == lang_var:
                    ext_tag_var = a.object_var or ext_tag_var
                    break
            retag_lines.extend(
                [
                    "OPTIONAL {",
                    f"    ?{parent_var} gmeow:nameLanguage ?{lang_var} .",
                    f"    ?{lang_var} gmeow:languageTag ?_intTag .",
                    f"    FILTER(isLiteral(?{val}) && LANG(?{val}) = ?_intTag)",
                    f"    ?{lang_var} gmeow:bcp47Tag ?{ext_tag_var} .",
                    f"    OPTIONAL {{ ?{parent_var} gmeow:nameScript ?_sc . }}",
                    "}",
                ]
            )
            bind_expr = (
                f"IF(BOUND(?{ext_tag_var}), "
                f"STRLANG(STR(?{val}), "
                f"IF(BOUND(?_sc), CONCAT(STR(?{ext_tag_var}), '-', ?_sc), "
                f"STR(?{ext_tag_var}))), "
                f"?{val})"
            )
    elif p.edoal_source in (GM.partText, GM.partExpansion, GM.romanization):
        np_var = None
        for a in flat_atoms:
            if a.predicate in (
                GM.partText,
                GM.partExpansion,
                GM.romanization,
            ):
                np_var = a.subject_var
                break
        app_var = None
        for a in flat_atoms:
            if a.predicate == GM.hasNamePart and a.object_var == np_var:
                app_var = a.subject_var
                break
        if not app_var and np_var:
            for a in flat_atoms:
                if a.object_var == np_var:
                    app_var = a.subject_var
                    break
        if app_var and np_var:
            retag_lines.extend(
                [
                    "OPTIONAL {",
                    f"    ?{app_var} gmeow:nameLanguage ?_lang .",
                    "    ?_lang gmeow:languageTag ?_intTag .",
                    f"    FILTER(isLiteral(?{val}) && LANG(?{val}) = ?_intTag)",
                    "    ?_lang gmeow:bcp47Tag ?_extTag .",
                    f"    OPTIONAL {{ ?{app_var} gmeow:nameScript ?_sc . }}",
                    "}",
                ]
            )
            bind_expr = (
                f"IF(BOUND(?_extTag), "
                f"STRLANG(STR(?{val}), "
                f"IF(BOUND(?_sc), CONCAT(STR(?_extTag), '-', ?_sc), STR(?_extTag))), "
                f"?{val})"
            )
    elif p.edoal_source in (GM.description, GM.designGoal, GM.title, GM.slogan):
        retag_lines.extend(
            [
                "OPTIONAL {",
                "    ?_lang gmeow:languageTag ?_intTag .",
                f"    FILTER(isLiteral(?{val}) && LANG(?{val}) = ?_intTag)",
                "    ?_lang gmeow:bcp47Tag ?_extTag .",
                "}",
            ]
        )
        bind_expr = f"IF(BOUND(?_extTag), STRLANG(STR(?{val}), STR(?_extTag)), ?{val})"
    elif any(
        a.predicate in (RDFS.label, SKOS.definition, RDFS.comment)
        and a.object_var == val
        for a in flat_atoms
    ):
        # Generic fallback for standard annotation predicates that carry
        # language-tagged literals but have no explicit language link in the
        # pattern (e.g. genderValue rdfs:label, honorific rdfs:label).
        retag_lines.extend(
            [
                "OPTIONAL {",
                "    ?_lang gmeow:languageTag ?_intTag .",
                f"    FILTER(isLiteral(?{val}) && LANG(?{val}) = ?_intTag)",
                "    ?_lang gmeow:bcp47Tag ?_extTag .",
                "}",
            ]
        )
        bind_expr = f"IF(BOUND(?_extTag), STRLANG(STR(?{val}), STR(?_extTag)), ?{val})"

    if retag_lines and bind_expr:
        lines.extend(retag_lines)
        lines.append(f"BIND ( {bind_expr} AS ?_final_{val} )")

    body = "\n".join(f"        {ln}" for ln in lines)
    return "{\n" + body + "\n    }"


def _templates(cell: ProjectionCell, b: ProfileBinding) -> list[str]:
    p = cell.pattern
    var_map: dict[str, str] = {}
    if (
        p.edoal_source
        in (
            GM.fullName,
            GM.partText,
            GM.partExpansion,
            GM.romanization,
            GM.description,
            GM.designGoal,
            GM.title,
            GM.slogan,
        )
        and p.value is not None
    ):
        var_map[p.value] = f"_final_{p.value}"
    elif p.value is not None and any(
        a.predicate in (RDFS.label, SKOS.definition, RDFS.comment)
        and a.object_var == p.value
        for a in _flatten_atoms(p.atoms)
    ):
        # Generic fallback for standard annotation predicates that carry
        # language-tagged literals (e.g. genderValue rdfs:label,
        # honorific rdfs:label).
        var_map[p.value] = f"_final_{p.value}"

    if b.template_atoms:
        return [_atom_triple(a, var_map) for a in b.template_atoms]
    if b.value_class_map:
        return [f"?{p.anchor} a ?{_class_var(p)} ."]
    if b.to_class is not None:
        return [f"?{p.anchor} a {curie(b.to_class)} ."]
    if b.to_predicate is not None:
        val = p.value
        if val in var_map:
            val = var_map[val]
        return [f"?{p.anchor} {curie(b.to_predicate)} ?{val} ."]
    raise CompileError(f"{cell.iri}: binding for {b.profile} has no output")


def _prefix_block(text: str) -> str:
    lines = []
    # Strip absolute IRIs (<...>) first so a prefix is never detected inside a URI
    # path/segment (e.g. "ps:" inside "https://…" or "…/ps:foo"). Then require a
    # token boundary that also excludes "_" (\w) so "foo_ps:" never matches "ps:".
    search_text = re.sub(r"<[^>]*>", "", text)
    for prefix, ns in PREFIXES.items():
        if re.search(rf"(?<!\w){re.escape(prefix)}:", search_text):
            lines.append(f"PREFIX {prefix}: <{ns}>")
    return "\n".join(lines)


#: The Standpoint-OWL 2 projection — re-expresses the standpoint axis as the
#: tool-compatible standpointLabel encoding (cl-tud/standpoint-owl2). The tool
#: matches any annotation property ending in ``#standpointLabel`` and reads a
#: structured ``<standpointAxiom><Box|Diamond><Standpoint name="…"/></…>`` string;
#: GMEOW's own ontology IRI yields ``…/gmeow#standpointLabel`` by that convention.
#:
#: This is the ONLY standpoint projection, and it is deliberately LOSSLESS: it
#: preserves every standpoint. There is no winner-selecting / frame-collapsing
#: projection — choosing one standpoint in a down-projection would re-create the
#: single winning slot the facility exists to abolish (Principle 9: no single slot
#: to win). A flat, perspectiveless format simply cannot carry "according to whom".
_STANDPOINT_OWL2_QUERY = "generated/queries/standpoint-owl2.rq"
_STANDPOINT_LABEL_IRI = f"{ONTOLOGY_IRI}#standpointLabel"


def emit_standpoint_owl2_sparql() -> str:
    """Render the lossless Standpoint-OWL 2 projection (the superset downcast, #43).

    Re-expresses every reified statement's ``gmeow:accordingTo`` +
    ``gmeow:standpointModality`` as a ``standpointLabel`` annotation in the exact
    syntax the cl-tud/standpoint-owl2 translator consumes — ``Box`` for unequivocal
    (□, the default), ``Diamond`` for conceivable (◊), the standpoint IRI as the
    ``Standpoint name`` (``*`` for the universal standpoint or an unindexed claim).
    A standpoint-aware reasoner can then run per-standpoint and cross-standpoint
    consistency over GMEOW's *full* multi-perspective KB. It is LOSSLESS by design —
    every standpoint is preserved, NONE is selected; collapsing to one frame would
    pick a winner (Principle 9). Fixed transformation, so this emitter is the
    canonical source (P4); the ``.rq`` is generated, never hand-edited.
    """
    label_concat = (
        "    BIND(CONCAT("
        '"<standpointAxiom><", ?op, '
        '"><Standpoint name=\\"", ?spName, '
        '"\\"/></", ?op, '
        '"></standpointAxiom>") AS ?label)\n'
    )
    sp_name = (
        "    BIND(IF(!BOUND(?sp) || ?sp = gmeow:universalStandpoint, "
        '"*", STR(?sp)) AS ?spName)\n'
    )
    modality = (
        "    BIND(IF(BOUND(?mod) && (?mod = gmeow:conceivable "
        "|| ?mod = gmeow:probable), "
        '"Diamond", "Box") AS ?op)\n'
    )
    # A refuted claim is the standpoint DENYING the proposition; the standpointLabel
    # encoding labels an ASSERTED axiom, so a denial cannot be expressed here without
    # asserting what S rejects. Refutations are carried losslessly by the CRMinf
    # projection (J5 holds to be 'false'); they are excluded here.
    refuted_filter = "    FILTER(!BOUND(?mod) || ?mod != gmeow:refuted)\n"
    body = (
        "CONSTRUCT {\n"
        # Declare the standpointLabel annotation property so the projected graph is
        # self-contained and DL-clean standalone (no undeclared-entity warnings).
        f"    <{_STANDPOINT_LABEL_IRI}> a owl:AnnotationProperty .\n"
        "    ?ax a owl:Axiom ;\n"
        "        owl:annotatedSource ?s ;\n"
        "        owl:annotatedProperty ?p ;\n"
        "        owl:annotatedTarget ?o ;\n"
        f"        <{_STANDPOINT_LABEL_IRI}> ?label .\n"
        "    ?s ?p ?o .\n"
        "}\n"
        "WHERE {\n"
        "    { ?ax a owl:Axiom ;\n"
        "        owl:annotatedSource ?s ;\n"
        "        owl:annotatedProperty ?p ;\n"
        "        owl:annotatedTarget ?o .\n"
        "      OPTIONAL { ?ax gmeow:accordingTo ?sp }\n"
        "      OPTIONAL { ?ax gmeow:standpointModality ?mod } }\n"
        "    UNION\n"
        "    { ?claim a gmeow:StandpointClaim ;\n"
        "        gmeow:vantage ?sp ;\n"
        "        gmeow:observedFeature ?ax .\n"
        "      ?ax a owl:Axiom ;\n"
        "          owl:annotatedSource ?s ;\n"
        "          owl:annotatedProperty ?p ;\n"
        "          owl:annotatedTarget ?o .\n"
        "      OPTIONAL { ?claim gmeow:claimModality ?mod } }\n"
        f"{refuted_filter}{sp_name}{modality}{label_concat}"
        "}\n"
    )
    header = (
        "# Projection: GMEOW → Standpoint-OWL 2 (standpointLabel). "
        f"{_GENERATED_BANNER}\n"
        "# Lossless multi-perspective downcast: re-expresses gmeow:accordingTo +\n"
        "# gmeow:standpointModality as the cl-tud/standpoint-owl2 standpointLabel\n"
        "# encoding (Box=□ settled, Diamond=◊ possible/probable, name=* universal).\n"
        "# Refuted (denied) claims are excluded — carried by standpoint-crminf.rq.\n"
        "# Branch B (#127): StandpointClaim with reified-statement observedFeature.\n"
        "# Branch C (generic-entity observedFeature) is excluded by design — the\n"
        "# translator matches only owl:Axiom individuals.\n"
    )
    return f"{header}{_prefix_block(body)}\n\n{body}"


#: The CRMinf projection — re-expresses the standpoint axis as the CIDOC-CRM
#: Argumentation/belief model (I1 Argumentation / I2 Belief / I4 Proposition Set /
#: J5 holds to be a belief value). This carries the FULL belief-value space
#: (true/probable/possible/false), so a standpoint's DENIAL is first-class — the
#: parity that makes GMEOW at least as expressive as CRMinf.
_STANDPOINT_CRMINF_QUERY = "generated/queries/standpoint-crminf.rq"


def emit_standpoint_crminf_sparql() -> str:
    """Render the lossless CRMinf (CIDOC-CRM Argumentation) projection (#43).

    Each reified statement becomes an ``I1 Argumentation`` carried out by the
    standpoint (the universal standpoint when unindexed), which ``J2 concluded
    that`` an ``I2 Belief`` ``J4 that`` an ``I4 Proposition Set``; the proposition
    set ``J5 holds to be`` a belief value derived from gmeow:standpointModality —
    ``true`` (unequivocal), ``probable``, ``possible`` (conceivable), or ``false``
    (refuted). Because the value is explicit, a DENIAL is carried faithfully and the
    proposition is never asserted as a fact — GMEOW is thereby at least as expressive
    as CRMinf. Fixed transformation; the ``.rq`` is generated, never hand-edited.
    """
    holder = "    BIND(COALESCE(?sp, gmeow:universalStandpoint) AS ?holder)\n"
    value = (
        '    BIND(IF(!BOUND(?mod), "true",'
        ' IF(?mod = gmeow:refuted, "false",'
        ' IF(?mod = gmeow:conceivable, "possible",'
        ' IF(?mod = gmeow:probable, "probable", "true")))) AS ?value)\n'
    )
    subject_bind = "    BIND(COALESCE(?s, ?feature) AS ?subject)\n"
    prop_text = (
        "    BIND(IF(BOUND(?s), "
        'CONCAT(STR(?s), " ", STR(?p), " ", STR(?o)), '
        "STR(?feature)) AS ?propText)\n"
    )
    mint = (
        '    BIND(IRI(CONCAT(STR(?ax), "/argumentation")) AS ?arg)\n'
        '    BIND(IRI(CONCAT(STR(?ax), "/belief")) AS ?belief)\n'
        '    BIND(IRI(CONCAT(STR(?ax), "/proposition")) AS ?prop)\n'
    )
    body = (
        "CONSTRUCT {\n"
        "    ?arg a crminf:I1_Argumentation ;\n"
        "        crm:P14_carried_out_by ?holder ;\n"
        "        crminf:J2_concluded_that ?belief .\n"
        "    ?belief a crminf:I2_Belief ;\n"
        "        crminf:J4_that ?prop .\n"
        "    ?prop a crminf:I4_Proposition_Set ;\n"
        "        crm:P67_refers_to ?subject ;\n"
        "        rdf:value ?propText ;\n"
        "        crminf:J5_holds_to_be ?value .\n"
        "}\n"
        "WHERE {\n"
        "    { ?ax a owl:Axiom ;\n"
        "        owl:annotatedSource ?s ;\n"
        "        owl:annotatedProperty ?p ;\n"
        "        owl:annotatedTarget ?o .\n"
        "      OPTIONAL { ?ax gmeow:accordingTo ?sp }\n"
        "      OPTIONAL { ?ax gmeow:standpointModality ?mod } }\n"
        "    UNION\n"
        "    { ?ax a gmeow:StandpointClaim ;\n"
        "        gmeow:vantage ?sp ;\n"
        "        gmeow:observedFeature ?stmt .\n"
        "      ?stmt owl:annotatedSource ?s ;\n"
        "            owl:annotatedProperty ?p ;\n"
        "            owl:annotatedTarget ?o .\n"
        "      OPTIONAL { ?ax gmeow:claimModality ?mod } }\n"
        "    UNION\n"
        "    { ?ax a gmeow:StandpointClaim ;\n"
        "        gmeow:vantage ?sp ;\n"
        "        gmeow:observedFeature ?feature .\n"
        "      FILTER NOT EXISTS { ?feature owl:annotatedSource ?s }\n"
        "      OPTIONAL { ?ax gmeow:claimModality ?mod } }\n"
        f"{holder}{value}{subject_bind}{prop_text}{mint}"
        "}\n"
    )
    header = (
        "# Projection: GMEOW → CRMinf (CIDOC-CRM Argumentation). "
        f"{_GENERATED_BANNER}\n"
        "# Lossless belief projection: each standpoint-indexed statement becomes an\n"
        "# I1 Argumentation (carried out by the standpoint) concluding an I2 Belief\n"
        "# J4 that an I4 Proposition Set J5 holds to be true/probable/possible/false.\n"
        "# The explicit belief value carries DENIAL faithfully (≥ CRMinf); the\n"
        "# proposition is referred to, never asserted as fact.\n"
        "# Branches B/C (#127): StandpointClaim with reified-statement or\n"
        "# generic-entity observedFeature. Generic entities use ?feature as the\n"
        "# referred-to subject.\n"
    )
    return f"{header}{_prefix_block(body)}\n\n{body}"


