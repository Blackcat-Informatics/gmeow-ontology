"""Compile canonical OWL → LinkML developer schemas + downstream generators.

``gmeow compile-schemas`` renders, from the merged GMEOW ontology graph:

* ``dist/schemas/gmeow.linkml.yaml`` — the LinkML schema (lossy OWL→LinkML);
* ``dist/schemas/gmeow.schema.json`` — JSON Schema (via LinkML JsonSchemaGenerator);
* ``dist/schemas/gmeow.py`` — Pydantic models (via LinkML PydanticGenerator);
* ``dist/schemas/gmeow.ts`` — TypeScript interfaces (via LinkML TypescriptGenerator);
* ``dist/schemas/gmeow.graphql`` — GraphQL type stubs (via LinkML GraphqlGenerator);
* ``dist/schemas/gmeow.openapi.json`` — OpenAPI 3.1 derived from the JSON Schema.

The OWL→LinkML mapping is intentionally lossy:

* OWL restrictions (intersection, cardinality, value constraints) become BNodes
  and are dropped.
* RDF 1.2 reification, standpoint indexing, and the four-clocks temporal model
  are not representable in LinkML and are dropped.
* ``owl:inverseOf`` is dropped (LinkML has no inverse slot construct).
* External-class ranges degrade to ``string`` with a warning.
* Multiple ``rdfs:domain`` / ``rdfs:range`` values: the first named URIRef is kept,
  the rest warned.

Value vocabularies (individuals of GMEOW classes) are emitted as LinkML enums.
"""

from __future__ import annotations

import json
import tempfile
from collections.abc import Mapping
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml
from rdflib import OWL, RDF, RDFS, Graph, Namespace, URIRef
from rdflib.term import BNode

from gmeow_tools.config import PREFIXES, SCHEMAS_DIR
from gmeow_tools.graph import load_merged_graph
from gmeow_tools.self_desc import load_self_description

_GMEOW = Namespace(PREFIXES["gmeow"])
_XSD = Namespace(PREFIXES["xsd"])

#: Artifacts emitted by the schema compiler.
_LINKML_FILE = "gmeow.linkml.yaml"
_JSON_SCHEMA_FILE = "gmeow.schema.json"
_PYDANTIC_FILE = "gmeow.py"
_TYPESCRIPT_FILE = "gmeow.ts"
_GRAPHQL_FILE = "gmeow.graphql"
_OPENAPI_FILE = "gmeow.openapi.json"

_GENERATED_BANNER = (
    "GENERATED by `gmeow compile-schemas` from canonical OWL — DO NOT EDIT."
)

#: OWL XSD → LinkML built-in type name.
_XSD_TO_LINKML: Mapping[str, str] = {
    str(_XSD.string): "string",
    str(_XSD.boolean): "boolean",
    str(_XSD.integer): "integer",
    str(_XSD.int): "integer",
    str(_XSD.long): "integer",
    str(_XSD.short): "integer",
    str(_XSD.decimal): "decimal",
    str(_XSD.float): "float",
    str(_XSD.double): "double",
    str(_XSD.dateTime): "datetime",
    str(_XSD.date): "date",
    str(_XSD.time): "time",
    str(_XSD.duration): "duration",
    str(_XSD.anyURI): "uri",
    str(RDFS.Literal): "string",
}


@dataclass(slots=True)
class SchemaCompileReport:
    """Outcome of a schema compile (or ``--check``) run."""

    written: list[Path] = field(default_factory=list)
    drifted: list[str] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)


def _local_name(iri: URIRef) -> str:
    """Return the local name of an IRI (after last ``#`` or ``/``)."""
    text = str(iri)
    cut = max(text.rfind("#"), text.rfind("/"))
    return text[cut + 1 :] if cut >= 0 else text


def _is_bnode(iri: URIRef | BNode) -> bool:
    """Whether the term is a blank node."""
    return isinstance(iri, BNode)


def _iri_to_linkml_range(
    iri: URIRef,
    class_names: set[str],
    warnings: list[str],
    prop_local: str,
) -> str:
    """Map an OWL range IRI to a LinkML range string."""
    s = str(iri)
    if s in _XSD_TO_LINKML:
        return _XSD_TO_LINKML[s]
    local = _local_name(iri)
    if _is_gmeow_iri(iri) and local in class_names:
        return local
    # External class → degrade to string with warning
    warnings.append(f"{prop_local}: range {s} is external — degrading to string")
    return "string"


def _gather_owl_properties(graph: Graph) -> list[URIRef]:
    """Return all OWL properties (object, datatype, annotation) as a sorted list."""
    props: set[URIRef] = set()
    for p in (
        *graph.subjects(RDF.type, OWL.ObjectProperty),
        *graph.subjects(RDF.type, OWL.DatatypeProperty),
        *graph.subjects(RDF.type, OWL.AnnotationProperty),
    ):
        if isinstance(p, URIRef):
            props.add(p)
    return sorted(props, key=str)


def _is_gmeow_iri(iri: URIRef) -> bool:
    """Whether the IRI is in the GMEOW namespace."""
    return str(iri).startswith(str(_GMEOW))


def emit_linkml(graph: Graph) -> tuple[dict[str, Any], list[str]]:
    """Extract GMEOW classes, properties, and individuals into a LinkML schema dict.

    Returns the schema dict and a list of non-fatal warnings.
    """
    warnings: list[str] = []

    schema: dict[str, Any] = {
        "id": "https://blackcatinformatics.ca/gmeow/linkml",
        "name": "gmeow",
        "description": (
            "GMEOW developer schema generated from canonical OWL. "
            "Lossy by design: restrictions, reification, standpoint, "
            "inverseOf, and temporal scope are dropped."
        ),
        "prefixes": {
            "gmeow": PREFIXES["gmeow"],
            "linkml": "https://w3id.org/linkml/",
        },
        "imports": ["linkml:types"],
        "default_range": "string",
        "types": {
            "duration": {
                "uri": str(_XSD.duration),
                "typeof": "string",
            }
        },
        "classes": {},
        "slots": {},
        "enums": {},
    }

    # ------------------------------------------------------------------ #
    # Classes
    # ------------------------------------------------------------------ #
    class_names: set[str] = set()
    class_iris: dict[str, URIRef] = {}
    pending_is_a: dict[str, str] = {}
    for cls in sorted(graph.subjects(RDF.type, OWL.Class), key=str):
        if not isinstance(cls, URIRef) or _is_bnode(cls):
            continue
        if not _is_gmeow_iri(cls):
            continue
        local = _local_name(cls)
        if not local:
            continue
        class_names.add(local)
        class_iris[local] = cls

        cls_def: dict[str, Any] = {
            "class_uri": str(cls),
        }
        labels = list(graph.objects(cls, RDFS.label))
        if labels:
            cls_def["title"] = str(labels[0])
        comments = list(graph.objects(cls, RDFS.comment))
        if comments:
            cls_def["description"] = str(comments[0])

        supers = sorted(
            (
                s
                for s in graph.objects(cls, RDFS.subClassOf)
                if isinstance(s, URIRef) and not _is_bnode(s)
            ),
            key=str,
        )
        if supers:
            # Prefer a GMEOW superclass already known in class_names;
            # fall back to the first sorted superclass otherwise.
            chosen = next(
                (
                    s
                    for s in supers
                    if _is_gmeow_iri(s) and _local_name(s) in class_names
                ),
                supers[0],
            )
            super_local = _local_name(chosen)
            super_iri = chosen
            if super_local == local:
                warnings.append(f"{local}: self-referential superclass — dropping is_a")
            elif _is_gmeow_iri(super_iri) and super_local in class_names:
                cls_def["is_a"] = super_local
            elif _is_gmeow_iri(super_iri):
                # GMEOW superclass not yet discovered; defer resolution.
                pending_is_a[local] = super_local
            # External superclasses are silently dropped (they never appear
            # in class_names).  Only warn when there are multiple choices.
            if len(supers) > 1:
                warnings.append(
                    f"{local}: multiple superclasses — keeping {super_local}"
                )

        schema["classes"][local] = cls_def

    # ------------------------------------------------------------------ #
    # Resolve superclass links discovered after their child in the first pass
    # ------------------------------------------------------------------ #
    for local, super_local in pending_is_a.items():
        if super_local in class_names:
            schema["classes"][local]["is_a"] = super_local
        else:
            warnings.append(
                f"{local}: superclass {super_local} not found — dropping is_a"
            )

    # ------------------------------------------------------------------ #
    # Slots (properties)
    # ------------------------------------------------------------------ #
    functional_props = set(graph.subjects(RDF.type, OWL.FunctionalProperty))
    for prop in _gather_owl_properties(graph):
        if not _is_gmeow_iri(prop):
            continue
        local = _local_name(prop)
        if not local:
            continue

        slot: dict[str, Any] = {"slot_uri": str(prop)}
        labels = list(graph.objects(prop, RDFS.label))
        if labels:
            slot["title"] = str(labels[0])
        comments = list(graph.objects(prop, RDFS.comment))
        if comments:
            slot["description"] = str(comments[0])

        # Range
        ranges = sorted(
            (
                r
                for r in graph.objects(prop, RDFS.range)
                if isinstance(r, URIRef) and not _is_bnode(r)
            ),
            key=str,
        )
        if ranges:
            slot["range"] = _iri_to_linkml_range(
                ranges[0], class_names, warnings, local
            )
            if len(ranges) > 1:
                warnings.append(f"{local}: multiple ranges — keeping {slot['range']}")
        else:
            slot["range"] = "string"

        # Domain
        domains = sorted(
            (
                d
                for d in graph.objects(prop, RDFS.domain)
                if isinstance(d, URIRef) and not _is_bnode(d)
            ),
            key=str,
        )
        if domains:
            domain_local = _local_name(domains[0])
            if _is_gmeow_iri(domains[0]) and domain_local in class_names:
                slot["domain"] = domain_local
            if len(domains) > 1:
                warnings.append(f"{local}: multiple domains — keeping {domain_local}")

        # Multivalued / required
        is_functional = prop in functional_props
        is_object = (prop, RDF.type, OWL.ObjectProperty) in graph
        if is_functional:
            slot["multivalued"] = False
        elif is_object:
            slot["multivalued"] = True
        # datatype/annotation properties default to single-valued

        schema["slots"][local] = slot

    # ------------------------------------------------------------------ #
    # Enums from value vocabularies (individuals of GMEOW classes)
    # ------------------------------------------------------------------ #
    individuals_by_class: dict[str, list[URIRef]] = {}
    for ind in graph.subjects(RDF.type):
        if not isinstance(ind, URIRef) or not _is_gmeow_iri(ind):
            continue
        for cls in graph.objects(ind, RDF.type):
            if not isinstance(cls, URIRef) or not _is_gmeow_iri(cls):
                continue
            cls_local = _local_name(cls)
            if cls_local not in class_names:
                continue
            individuals_by_class.setdefault(cls_local, []).append(ind)

    for cls_local, inds in sorted(individuals_by_class.items()):
        if not inds:
            continue
        enum_name = f"{cls_local}Enum"
        enum_def: dict[str, Any] = {
            "enum_uri": str(class_iris[cls_local]),
            "permissible_values": {},
        }
        for ind in sorted(inds, key=str):
            ind_local = _local_name(ind)
            pv: dict[str, Any] = {"meaning": str(ind)}
            labels = list(graph.objects(ind, RDFS.label))
            if labels:
                pv["title"] = str(labels[0])
            comments = list(graph.objects(ind, RDFS.comment))
            if comments:
                pv["description"] = str(comments[0])
            enum_def["permissible_values"][ind_local] = pv
        schema["enums"][enum_name] = enum_def

    # ------------------------------------------------------------------ #
    # Attach slots to their domain classes
    # ------------------------------------------------------------------ #
    for slot_name, slot_def in schema["slots"].items():
        domain = slot_def.get("domain")
        if domain and domain in schema["classes"]:
            schema["classes"][domain].setdefault("slots", []).append(slot_name)

    return schema, warnings


def _write_yaml(data: dict[str, Any], path: Path) -> None:
    """Dump a dict as YAML with a generated banner."""
    path.parent.mkdir(parents=True, exist_ok=True)
    dumped = yaml.safe_dump(data, sort_keys=False, allow_unicode=True)
    text = f"# {_GENERATED_BANNER}\n{dumped}"
    path.write_text(text, encoding="utf-8")


def gen_json_schema(linkml_path: Path) -> str:
    """Run the LinkML JSON Schema generator."""
    from linkml.generators.jsonschemagen import JsonSchemaGenerator

    gen = JsonSchemaGenerator(str(linkml_path), mergeimports=True)
    return gen.serialize()  # type: ignore[no-any-return]


def gen_pydantic(linkml_path: Path) -> str:
    """Run the LinkML Pydantic generator."""
    from linkml.generators.pydanticgen import PydanticGenerator

    gen = PydanticGenerator(str(linkml_path), mergeimports=True)
    return gen.serialize()  # type: ignore[no-any-return]


def gen_typescript(linkml_path: Path) -> str:
    """Run the LinkML TypeScript generator."""
    from linkml.generators.typescriptgen import TypescriptGenerator

    gen = TypescriptGenerator(str(linkml_path), mergeimports=True)
    return gen.serialize()  # type: ignore[no-any-return]


def gen_graphql(linkml_path: Path) -> str:
    """Run the LinkML GraphQL generator."""
    from linkml.generators.graphqlgen import GraphqlGenerator

    gen = GraphqlGenerator(str(linkml_path), mergeimports=True)
    return gen.serialize()  # type: ignore[no-any-return]


def gen_openapi(json_schema_text: str) -> str:
    """Derive an OpenAPI 3.1 spec from the JSON Schema text.

    The returned string is a minimal OpenAPI document whose
    ``components/schemas`` block is the parsed JSON Schema.
    A thin path set (``GET /entities/{id}``) is added so the
    spec validates as a complete OpenAPI document.
    """
    schema_obj = json.loads(json_schema_text)
    # Wrap the JSON Schema under a single named component so top-level keys
    # like "$schema" and "title" do not leak as component names.
    component_name = schema_obj.get("title", "GMEOWSchema")
    openapi: dict[str, Any] = {
        "openapi": "3.1.0",
        "info": {
            "title": "GMEOW API",
            "description": (
                "OpenAPI 3.1 derived from the GMEOW LinkML developer schema. "
                "Lossy by design — see gmeow.linkml.yaml for caveats."
            ),
            "version": load_self_description().version,
        },
        "paths": {
            "/entities/{id}": {
                "get": {
                    "summary": "Retrieve a GMEOW entity",
                    "parameters": [
                        {
                            "name": "id",
                            "in": "path",
                            "required": True,
                            "schema": {"type": "string"},
                        }
                    ],
                    "responses": {
                        "200": {
                            "description": "A GMEOW entity",
                            "content": {
                                "application/json": {
                                    "schema": {
                                        "$ref": f"#/components/schemas/{component_name}"
                                    }
                                }
                            },
                        }
                    },
                }
            }
        },
        "components": {"schemas": {component_name: schema_obj}},
    }
    return json.dumps(openapi, indent=2) + "\n"


def _drift(tmp_dir: Path, committed_dir: Path) -> list[str]:
    """Compare freshly-rendered artifacts against the committed ones (bytes)."""
    drifted: list[str] = []
    artifacts = {
        _LINKML_FILE,
        _JSON_SCHEMA_FILE,
        _PYDANTIC_FILE,
        _TYPESCRIPT_FILE,
        _GRAPHQL_FILE,
        _OPENAPI_FILE,
    }
    for name in sorted(artifacts):
        fresh = tmp_dir / name
        committed = committed_dir / name
        if not committed.exists():
            drifted.append(f"{name} (missing committed file)")
            continue
        if fresh.read_bytes() != committed.read_bytes():
            drifted.append(name)
    return drifted


def _normalize_text(text: str) -> str:
    """Strip trailing whitespace per line and ensure exactly one trailing newline."""
    lines = text.split("\n")
    cleaned = "\n".join(line.rstrip() for line in lines)
    return cleaned.rstrip("\n") + "\n"


def _write_artifacts(
    linkml_text: str,
    json_schema_text: str,
    pydantic_text: str,
    typescript_text: str,
    graphql_text: str,
    openapi_text: str,
    out_dir: Path,
) -> list[Path]:
    """Write all six schema artifacts to ``out_dir``."""
    out_dir.mkdir(parents=True, exist_ok=True)
    paths: list[Path] = []
    mapping = {
        _LINKML_FILE: linkml_text,
        _JSON_SCHEMA_FILE: json_schema_text,
        _PYDANTIC_FILE: pydantic_text,
        _TYPESCRIPT_FILE: typescript_text,
        _GRAPHQL_FILE: graphql_text,
        _OPENAPI_FILE: openapi_text,
    }
    for name, text in mapping.items():
        path = out_dir / name
        path.write_text(_normalize_text(text), encoding="utf-8")
        paths.append(path)
    return paths


def _reconcile_canonical(tmp_dir: Path, warnings: list[str]) -> None:
    """Read-only cross-check of JSON-LD context, SHACL, and OWL against schemas.

    Loads the generated JSON Schema and verifies that every GMEOW class and
    property IRI present in the canonical JSON-LD context also appears as a
    ``class_uri`` or ``slot_uri`` in the LinkML schema.  Mismatches are
    appended to *warnings* (non-fatal).
    """
    from gmeow_tools.jsonld_context import build_context

    linkml_path = tmp_dir / _LINKML_FILE
    schema = yaml.safe_load(linkml_path.read_text(encoding="utf-8"))
    linkml_class_uris = {
        c.get("class_uri")
        for c in schema.get("classes", {}).values()
        if c.get("class_uri")
    }
    linkml_slot_uris = {
        s.get("slot_uri") for s in schema.get("slots", {}).values() if s.get("slot_uri")
    }

    try:
        ctx_doc = build_context()
        ctx = ctx_doc.get("@context", {})
    except Exception as exc:
        warnings.append(f"reconciliation: could not load JSON-LD context: {exc}")
        return

    # Flatten @context mappings
    context_iris: set[str] = set()
    for _prefix, value in ctx.items():
        if isinstance(value, str) and value.startswith("https://"):
            context_iris.add(value)
        elif isinstance(value, dict):
            vid = value.get("@id")
            if isinstance(vid, str):
                context_iris.add(vid)

    gmeow_ns = str(_GMEOW)
    for iri in sorted(context_iris):
        if not iri.startswith(gmeow_ns):
            continue
        # Skip the namespace base IRI itself (used as @vocab / prefix),
        # which is not a class or property.
        if iri == gmeow_ns:
            continue
        if iri not in linkml_class_uris and iri not in linkml_slot_uris:
            warnings.append(
                f"reconciliation: {iri} in JSON-LD context but missing from schema"
            )


def compile_schemas(
    check: bool = False,
    reconcile: bool = False,
) -> SchemaCompileReport:
    """Compile canonical OWL → LinkML + downstream artifacts.

    Args:
        check: Render to a temp tree and report drift against committed files;
            write nothing.
        reconcile: After compiling, run a read-only cross-check against the
            JSON-LD context and append any mismatches to warnings.

    Returns:
        A :class:`SchemaCompileReport` describing what was written or what
        drifted, plus any warnings.
    """
    graph = load_merged_graph(include_imports=False)
    schema_dict, warnings = emit_linkml(graph)

    with tempfile.TemporaryDirectory() as tmp:
        tmp_dir = Path(tmp)
        linkml_path = tmp_dir / _LINKML_FILE
        _write_yaml(schema_dict, linkml_path)

        json_schema_text = gen_json_schema(linkml_path)
        pydantic_text = gen_pydantic(linkml_path)
        # The Pydantic generator embeds the absolute source path, which breaks
        # determinism because the LinkML file lives in a temp directory.
        # Normalize it to a stable relative string.
        pydantic_text = pydantic_text.replace(str(linkml_path), _LINKML_FILE)
        typescript_text = gen_typescript(linkml_path)
        graphql_text = gen_graphql(linkml_path)
        openapi_text = gen_openapi(json_schema_text)

        # Write all artifacts to the temp tree so drift/check/reconcile operate
        # on a complete, consistent set.
        _write_artifacts(
            linkml_path.read_text(encoding="utf-8"),
            json_schema_text,
            pydantic_text,
            typescript_text,
            graphql_text,
            openapi_text,
            tmp_dir,
        )

        if check:
            if reconcile:
                _reconcile_canonical(tmp_dir, warnings)
            drifted = _drift(tmp_dir, SCHEMAS_DIR)
            return SchemaCompileReport(drifted=drifted, warnings=warnings)

        written = _write_artifacts(
            linkml_path.read_text(encoding="utf-8"),
            json_schema_text,
            pydantic_text,
            typescript_text,
            graphql_text,
            openapi_text,
            SCHEMAS_DIR,
        )

        if reconcile:
            _reconcile_canonical(tmp_dir, warnings)

    return SchemaCompileReport(written=written, warnings=warnings)
