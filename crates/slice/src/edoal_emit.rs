/// Emit every EDOAL alignment file from the repo at `root`, returning
/// `{ "<profile>.edoal.ttl" → turtle_text }` for all 45 profiles.
///
/// All inputs are sourced natively from `root` (the DSL tree + slice mapping
/// artifacts for the cells; `ontology/gmeow.ttl` + slice module artifacts for the
/// language-tag retag). The text is byte-identical to the historical Python emitter.
///
/// # Errors
///
/// Returns [`SliceError`] on any missing/unparsable required source or a malformed
/// projection cell — no degraded fallback (CONSTITUTION / no-compromises).
pub fn emit_edoal_sets(root: &Path) -> Result<BTreeMap<String, String>, SliceError> {
    let dsl_store = collect_dsl_store(root)?;
    let dsl = Dsl {
        projections: projections(&dsl_store)?,
    };
    let onto_store = collect_ontology_store(root)?;
    let tag_map = build_tag_map(&onto_store)?;
    let prefixes: Vec<(String, String)> = PREFIX_REGISTRY
        .iter()
        .map(|(p, ns)| ((*p).to_owned(), (*ns).to_owned()))
        .collect();

    let mut out: BTreeMap<String, String> = BTreeMap::new();
    for profile in PROFILES {
        let nt = emit_edoal_nt(&dsl, profile, &tag_map)?;
        // Mirror Python's `graph.serialize(format="turtle")`: the EDOAL triples are
        // added to an oxigraph store (insertion order = the algorithmic build order),
        // then dumped to N-Triples — that store-dump order is what fixes the
        // blank-node interning order canonical_turtle reads to order inline `[ … ]`
        // objects (`graph.add` → `store.dump(NT)` → `canonicalize_turtle`).
        let dumped = oxigraph_redump(&nt)?;
        let body = gmeow_rdf::turtle_normalize::canonical_turtle(dumped.as_bytes(), &prefixes)
            .map_err(SliceError::Parse)?;
        // Python: graph.serialize(...).rstrip("\n") + "\n" — exactly one trailing \n.
        let text = format!("{}\n", body.trim_end_matches('\n'));
        out.insert(format!("{profile}.edoal.ttl"), text);
    }
    Ok(out)
}

/// Load the N-Triples into a fresh oxigraph store and dump it back out as
/// N-Triples — reproducing Python's `Graph.add(...)` → `store.dump(NT)` step so the
/// blank-node ordering canonical_turtle reads matches the historical emitter exactly.
fn oxigraph_redump(nt: &str) -> Result<String, SliceError> {
    use oxigraph::io::{RdfFormat, RdfParser, RdfSerializer};
    let store = Store::new().map_err(|e| SliceError::Parse(format!("store: {e}")))?;
    for quad in RdfParser::from_format(RdfFormat::NTriples)
        .lenient()
        .for_reader(nt.as_bytes())
    {
        let quad = quad.map_err(|e| SliceError::Parse(format!("edoal NT parse: {e}")))?;
        store
            .insert(&quad)
            .map_err(|e| SliceError::Parse(format!("edoal store insert: {e}")))?;
    }
    let mut buf: Vec<u8> = Vec::new();
    let mut writer = RdfSerializer::from_format(RdfFormat::NTriples).for_writer(&mut buf);
    for quad in store.iter() {
        let quad = quad.map_err(|e| SliceError::Parse(format!("edoal store iter: {e}")))?;
        writer
            .serialize_quad(&quad)
            .map_err(|e| SliceError::Parse(format!("edoal NT serialize: {e}")))?;
    }
    writer
        .finish()
        .map_err(|e| SliceError::Parse(format!("edoal NT finish: {e}")))?;
    String::from_utf8(buf).map_err(|e| SliceError::Parse(format!("edoal NT utf8: {e}")))
}

// ── Language-tag retag map ───────────────────────────────────────────────────────

/// Build the internal→BCP-47 tag map (`gmeow:languageTag` → `gmeow:bcp47Tag`),
/// mirroring `research_objects.rs::load_tag_map`. The only tag EDOAL uses is
/// `x-gmeow-english` → `en`.
fn build_tag_map(store: &Store) -> Result<BTreeMap<String, String>, SliceError> {
    use crate::sparql_emit::{first_lexical_of_iri, quads_with_predicate, term_iri, term_lexical};
    const GM_LANGUAGE_TAG: &str = "https://blackcatinformatics.ca/gmeow/languageTag";
    const GM_BCP47_TAG: &str = "https://blackcatinformatics.ca/gmeow/bcp47Tag";

    let mut map: BTreeMap<String, String> = BTreeMap::new();
    for (subject, object) in quads_with_predicate(store, GM_LANGUAGE_TAG)? {
        let Some(internal) = term_lexical(&object) else {
            continue;
        };
        let Some(subj_iri) = term_iri(&subject) else {
            continue;
        };
        let ext = first_lexical_of_iri(store, &subj_iri, GM_BCP47_TAG)?;
        if let Some(ext) = ext {
            map.insert(internal, ext);
        }
    }
    Ok(map)
}

/// Retag an internal `x-gmeow-*` language tag to its public BCP-47 form; a public
/// tag (no `x-gmeow-` prefix) passes through unchanged.
fn retag(tag: &str, tag_map: &BTreeMap<String, String>) -> String {
    if let Some(ext) = tag_map.get(tag) {
        return ext.clone();
    }
    tag.to_owned()
}

// ── N-Triples builder ────────────────────────────────────────────────────────────

/// An N-Triples accumulator with a per-emit monotonic blank-node counter. Blank
/// nodes are emitted in first-seen order, which the canonical serializer uses to
/// order inline `[ … ]` objects — matching the Python append order.
struct Nt {
    lines: String,
    counter: usize,
}

impl Nt {
    fn new() -> Self {
        Self {
            lines: String::new(),
            counter: 0,
        }
    }

    /// A fresh bare blank node (`_:bN`), mirroring rdflib's anonymous `BNode()`.
    fn fresh_bnode(&mut self) -> String {
        let label = format!("_:b{}", self.counter);
        self.counter += 1;
        label
    }

    /// A deterministic `_stable_bnode(label)` — `_:n_<sanitized>` where every
    /// non-alphanumeric char is replaced by `_`. Used for align:Cell nodes.
    fn stable_bnode(label: &str) -> String {
        let safe: String = label
            .chars()
            .map(|c| if c.is_alphanumeric() { c } else { '_' })
            .collect();
        format!("_:n_{safe}")
    }

    fn add_iri(&mut self, s: &str, p: &str, o: &str) {
        self.add_raw(s, p, &format!("<{o}>"));
    }

    fn add_node(&mut self, s: &str, p: &str, o: &str) {
        // `o` is either a bnode label (`_:…`) or a full `<iri>`/literal object.
        if o.starts_with("_:") {
            self.add_raw(s, p, o);
        } else {
            self.add_iri(s, p, o);
        }
    }

    fn add_bnode_obj(&mut self, s: &str, p: &str, o: &str) {
        self.add_raw(s, p, o);
    }

    /// `subject` is a bnode label or IRI; `pred` is an IRI; object verbatim.
    fn add_raw(&mut self, subject: &str, pred: &str, object: &str) {
        let subj = if subject.starts_with("_:") {
            subject.to_owned()
        } else {
            format!("<{subject}>")
        };
        self.lines
            .push_str(&format!("{subj} <{pred}> {object} .\n"));
    }

    /// Add a language-tagged literal triple.
    fn add_lang_literal(&mut self, s: &str, p: &str, text: &str, lang: &str) {
        let obj = format!("{}@{lang}", nt_quote(text));
        self.add_raw(s, p, &obj);
    }

    /// Add a plain (untyped → xsd:string) string literal triple.
    fn add_string_literal(&mut self, s: &str, p: &str, text: &str) {
        self.add_raw(s, p, &nt_quote(text));
    }

    /// Add a typed literal triple.
    fn add_typed_literal(&mut self, s: &str, p: &str, text: &str, datatype: &str) {
        let obj = format!("{}^^<{datatype}>", nt_quote(text));
        self.add_raw(s, p, &obj);
    }

    /// Attach an rdf:List of bnode/iri items to `subject` via `predicate`.
    fn attach_list(&mut self, subject: &str, predicate: &str, items: &[String]) {
        let head = self.fresh_bnode();
        self.add_bnode_obj(subject, predicate, &head);
        let mut cur = head;
        for (i, item) in items.iter().enumerate() {
            self.add_node(&cur, RDF_FIRST, item);
            if i + 1 < items.len() {
                let next = self.fresh_bnode();
                self.add_bnode_obj(&cur, RDF_REST, &next);
                cur = next;
            } else {
                self.add_iri(&cur, RDF_REST, RDF_NIL);
            }
        }
    }
}

/// Quote a string as an N-Triples literal (escape `\`, `"`, control chars).
fn nt_quote(text: &str) -> String {
    let mut out = String::with_capacity(text.len() + 2);
    out.push('"');
    for c in text.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

// ── EDOAL emission (mirrors mapping_compile.emit_edoal) ──────────────────────────

const EN_TAG: &str = "x-gmeow-english";

fn emit_edoal_nt(
    dsl: &Dsl,
    profile: &str,
    tag_map: &BTreeMap<String, String>,
) -> Result<String, SliceError> {
    let mut nt = Nt::new();
    let align = format!("{ONTOLOGY_IRI}/projections/{profile}");
    let en = retag(EN_TAG, tag_map);

    nt.add_iri(&align, RDF_TYPE, &format!("{ALIGN}Alignment"));
    nt.add_lang_literal(
        &align,
        RDFS_LABEL,
        &format!("GMEOW → {profile} (EDOAL)"),
        &en,
    );
    nt.add_iri(&align, DCTERMS_IS_PART_OF, ONTOLOGY_IRI);
    nt.add_lang_literal(&align, RDFS_COMMENT, GENERATED_BANNER, &en);
    nt.add_string_literal(&align, &format!("{ALIGN}level"), "2EDOAL");
    for (n, name) in [
        (format!("{ALIGN}onto1"), "GMEOW"),
        (format!("{ALIGN}onto2"), profile),
    ] {
        let onto = nt.fresh_bnode();
        nt.add_iri(&onto, RDF_TYPE, &format!("{ALIGN}Ontology"));
        let formalism = nt.fresh_bnode();
        nt.add_string_literal(&formalism, &format!("{ALIGN}name"), name);
        nt.add_bnode_obj(&onto, &format!("{ALIGN}formalism"), &formalism);
        nt.add_bnode_obj(&align, &n, &onto);
    }

    for cell in &dsl.projections {
        for b in &cell.bindings {
            if b.profile != profile {
                continue;
            }
            let map_cells = edoal_cells(&mut nt, cell, b, &en)?;
            for map_cell in map_cells {
                nt.add_bnode_obj(&align, &format!("{ALIGN}map"), &map_cell);
            }
        }
    }
    Ok(nt.lines)
}

/// The EDOAL kind class IRI for a kind string.
fn edoal_kind(kind: &str) -> &'static str {
    match kind {
        "class" => "Class",
        "relation" => "Relation",
        "property" => "Property",
        _ => "Property",
    }
}

/// A `_edoal_entity` bnode.
fn edoal_entity(nt: &mut Nt, term: &str, kind: &str) -> String {
    let node = nt.fresh_bnode();
    nt.add_iri(&node, RDF_TYPE, &format!("{EDOAL}{}", edoal_kind(kind)));
    nt.add_iri(&node, &format!("{EDOAL}uri"), term);
    node
}

/// A `_edoal_restriction` bnode (the `edoal:and ( base restriction )` class).
fn edoal_restriction(nt: &mut Nt, source: &str, attr: &str, value: &str) -> String {
    let cls = nt.fresh_bnode();
    nt.add_iri(&cls, RDF_TYPE, &format!("{EDOAL}Class"));
    let restriction = nt.fresh_bnode();
    nt.add_iri(
        &restriction,
        RDF_TYPE,
        &format!("{EDOAL}AttributeValueRestriction"),
    );
    let on_attr = nt.fresh_bnode();
    nt.add_iri(&on_attr, RDF_TYPE, &format!("{EDOAL}Relation"));
    nt.add_iri(&on_attr, &format!("{EDOAL}uri"), attr);
    nt.add_bnode_obj(&restriction, &format!("{EDOAL}onAttribute"), &on_attr);
    nt.add_iri(
        &restriction,
        &format!("{EDOAL}comparator"),
        &format!("{EDOAL}equals"),
    );
    let val = nt.fresh_bnode();
    nt.add_iri(&val, &format!("{EDOAL}uri"), value);
    nt.add_bnode_obj(&restriction, &format!("{EDOAL}value"), &val);
    let base = edoal_entity(nt, source, "class");
    nt.attach_list(&cls, &format!("{EDOAL}and"), &[base, restriction]);
    cls
}

/// Build the EDOAL align:Cell node(s) for one binding (0, 1, or N), mirroring
/// `_edoal_cells`.
fn edoal_cells(
    nt: &mut Nt,
    cell: &ProjectionCell,
    b: &ProfileBinding,
    en: &str,
) -> Result<Vec<String>, SliceError> {
    let pattern = &cell.pattern;
    let mut cells: Vec<String> = Vec::new();

    if !b.value_class_map.is_empty() {
        let Some(edoal_source) = &pattern.edoal_source else {
            return Err(SliceError::Parse(format!(
                "{}: value-class map needs edoalSource",
                cell.iri
            )));
        };
        let attr = attr_of(pattern)?;
        for (i, vc) in b.value_class_map.iter().enumerate() {
            let entity1 = edoal_restriction(nt, edoal_source, &attr, &vc.when_value);
            let entity2 = edoal_entity(nt, &vc.to_class, "class");
            let label = format!(
                "{} [{}] → {}",
                curie(edoal_source),
                curie(&vc.when_value),
                curie(&vc.to_class)
            );
            let key = format!("{i}-{}", local(&vc.to_class));
            cells.push(make_cell(nt, cell, b, entity1, entity2, &label, &key, en));
        }
        return Ok(cells);
    }

    let (target, target_kind) = edoal_target(b);
    let Some(target) = target else {
        return Ok(cells);
    };

    let source: String = if pattern.edoal_path {
        match edoal_path(nt, pattern)? {
            Some(s) => s,
            None => {
                return Err(SliceError::Parse(format!(
                    "{}: edoalPath set but no anchor→value path",
                    cell.iri
                )))
            }
        }
    } else if let Some(es) = &pattern.edoal_source {
        edoal_entity(nt, es, &pattern.edoal_source_kind)
    } else {
        return Ok(cells);
    };

    let target_entity = edoal_entity(nt, &target, target_kind);
    let label = if cell.label.is_empty() {
        format!("→ {}", curie(&target))
    } else {
        cell.label.clone()
    };
    cells.push(make_cell(
        nt,
        cell,
        b,
        source,
        target_entity,
        &label,
        "0",
        en,
    ));
    Ok(cells)
}

/// The `_cell` closure: a `_stable_bnode("cell-<profile>-<local>-<key>")` Cell node.
#[allow(clippy::too_many_arguments)]
fn make_cell(
    nt: &mut Nt,
    cell: &ProjectionCell,
    b: &ProfileBinding,
    entity1: String,
    entity2: String,
    label: &str,
    key: &str,
    en: &str,
) -> String {
    let node = Nt::stable_bnode(&format!("cell-{}-{}-{}", b.profile, local(&cell.iri), key));
    nt.add_iri(&node, RDF_TYPE, &format!("{ALIGN}Cell"));
    nt.add_lang_literal(&node, RDFS_LABEL, label, en);
    nt.add_bnode_obj(&node, &format!("{ALIGN}entity1"), &entity1);
    nt.add_bnode_obj(&node, &format!("{ALIGN}entity2"), &entity2);
    nt.add_string_literal(&node, &format!("{ALIGN}relation"), &b.relation);
    if let Some(transform) = &b.transform {
        let trans = nt.fresh_bnode();
        nt.add_iri(&trans, RDFS_SEE_ALSO, transform);
        nt.add_bnode_obj(&node, &format!("{EDOAL}transformation"), &trans);
    }
    if let Some(conf) = b.confidence {
        nt.add_typed_literal(
            &node,
            &format!("{EDOAL}measure"),
            &format_double(conf),
            XSD_DOUBLE,
        );
    }
    node
}

/// `_attr_of`: the predicate of the flattened atom whose object_var == value.
fn attr_of(pattern: &MappingPattern) -> Result<String, SliceError> {
    for atom in pattern.flat_atoms() {
        if atom.object_var.as_deref() == pattern.value.as_deref()
            && pattern.value.is_some()
            && atom.predicate.is_some()
        {
            return Ok(atom.predicate.clone().unwrap());
        }
    }
    Err(SliceError::Parse(
        "value-class pattern has no value-binding predicate".to_owned(),
    ))
}

/// `_edoal_target`.
fn edoal_target(b: &ProfileBinding) -> (Option<String>, &str) {
    if let Some(t) = &b.edoal_target {
        return (
            Some(t.clone()),
            b.edoal_target_kind.as_deref().unwrap_or("class"),
        );
    }
    if let Some(t) = &b.to_class {
        return (
            Some(t.clone()),
            b.edoal_target_kind.as_deref().unwrap_or("class"),
        );
    }
    if let Some(t) = &b.to_predicate {
        return (
            Some(t.clone()),
            b.edoal_target_kind.as_deref().unwrap_or("property"),
        );
    }
    (None, "property")
}

/// `_edoal_path`: the anchor→value relation path (compose/inverse), or None.
fn edoal_path(nt: &mut Nt, pattern: &MappingPattern) -> Result<Option<String>, SliceError> {
    let Some(value) = &pattern.value else {
        return Ok(None);
    };
    let edges = nav_edges(pattern);
    let Some(steps) = find_var_path(&edges, &pattern.anchor, value) else {
        return Ok(None);
    };
    if steps.is_empty() {
        return Ok(None);
    }
    let mut relations: Vec<String> = Vec::new();
    for (atom_idx, forward) in &steps {
        relations.push(edoal_relation_step(nt, &edges[*atom_idx].2, *forward));
    }
    if relations.len() == 1 {
        return Ok(Some(relations.into_iter().next().unwrap()));
    }
    let compose = nt.fresh_bnode();
    nt.add_iri(&compose, RDF_TYPE, &format!("{EDOAL}Relation"));
    nt.attach_list(&compose, &format!("{EDOAL}compose"), &relations);
    Ok(Some(compose))
}

/// A navigation edge: (subjVar, objVar, atom).
type NavEdge = (String, String, Atom);

/// `_nav_edges`: flattened atoms relating two variables.
fn nav_edges(pattern: &MappingPattern) -> Vec<NavEdge> {
    let mut edges: Vec<NavEdge> = Vec::new();
    for atom in pattern.flat_atoms() {
        let has_pred = atom.predicate.is_some()
            || atom.predicate_var.is_some()
            || atom.path.is_some()
            || !atom.path_alts.is_empty();
        if let Some(obj) = &atom.object_var {
            if has_pred {
                edges.push((atom.subject_var.clone(), obj.clone(), atom.clone()));
            }
        }
    }
    edges
}

/// `_find_var_path`: BFS a simple var path anchor→value; steps carry an edge index
/// + a forward/inverse flag.
fn find_var_path(edges: &[NavEdge], anchor: &str, value: &str) -> Option<Vec<(usize, bool)>> {
    use std::collections::{HashMap, VecDeque};
    // adjacency: node → list of (neighbour, edge_idx, forward)
    let mut adj: HashMap<String, Vec<(String, usize, bool)>> = HashMap::new();
    for (idx, (subj, obj, _)) in edges.iter().enumerate() {
        adj.entry(subj.clone())
            .or_default()
            .push((obj.clone(), idx, true));
        adj.entry(obj.clone())
            .or_default()
            .push((subj.clone(), idx, false));
    }
    let mut queue: VecDeque<(String, Vec<(usize, bool)>)> = VecDeque::new();
    queue.push_back((anchor.to_owned(), Vec::new()));
    let mut seen: std::collections::HashSet<String> = std::collections::HashSet::new();
    seen.insert(anchor.to_owned());
    while let Some((node, steps)) = queue.pop_front() {
        if node == value {
            return Some(steps);
        }
        if let Some(neighbours) = adj.get(&node) {
            for (nbr, idx, forward) in neighbours {
                if !seen.contains(nbr) {
                    seen.insert(nbr.clone());
                    let mut next = steps.clone();
                    next.push((*idx, *forward));
                    queue.push_back((nbr.clone(), next));
                }
            }
        }
    }
    None
}

/// `_edoal_relation_step`.
fn edoal_relation_step(nt: &mut Nt, atom: &Atom, forward: bool) -> String {
    let base = if !atom.path_alts.is_empty() {
        if atom.path_alts.len() == 1 {
            edoal_entity(nt, &atom.path_alts[0], "relation")
        } else {
            let base = nt.fresh_bnode();
            nt.add_iri(&base, RDF_TYPE, &format!("{EDOAL}Relation"));
            let members: Vec<String> = atom
                .path_alts
                .iter()
                .map(|a| edoal_entity(nt, a, "relation"))
                .collect();
            nt.attach_list(&base, &format!("{EDOAL}or"), &members);
            base
        }
    } else if let Some(pred) = &atom.predicate {
        edoal_entity(nt, pred, "relation")
    } else {
        let base = nt.fresh_bnode();
        nt.add_iri(&base, RDF_TYPE, &format!("{EDOAL}Relation"));
        let comment = atom
            .path
            .clone()
            .or_else(|| atom.predicate_var.clone())
            .unwrap_or_else(|| "path".to_owned());
        nt.add_string_literal(&base, RDFS_COMMENT, &comment);
        base
    };
    if forward {
        return base;
    }
    let inverse = nt.fresh_bnode();
    nt.add_iri(&inverse, RDF_TYPE, &format!("{EDOAL}Relation"));
    nt.add_bnode_obj(&inverse, &format!("{EDOAL}inverse"), &base);
    inverse
}

/// Format an f64 the way `Literal(float)` lexicalizes for the committed corpus
/// (simple short decimals like `0.8`, `0.95`). Mirrors the SSSOM `format_g`-style
/// shortest round-trip; the committed measures are all short decimals.
fn format_double(v: f64) -> String {
    // The committed values are exact short decimals; Rust's default f64 Display
    // produces the shortest round-tripping form (e.g. 0.8 → "0.8", 0.95 → "0.95").
    let s = format!("{v}");
    if s.contains('.') || s.contains('e') || s.contains('E') {
        s
    } else {
        // An integer-valued double (none in the corpus) keeps a ".0" tail to match
        // Python's float repr (e.g. 1.0).
        format!("{s}.0")
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn repo_root() -> PathBuf {
        // crates/slice/ → repo root is two levels up.
        PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .unwrap()
            .parent()
            .unwrap()
            .to_path_buf()
    }

    #[test]
    fn stable_bnode_sanitizes() {
        assert_eq!(Nt::stable_bnode("cell-foaf-x-0"), "_:n_cell_foaf_x_0");
    }

    #[test]
    fn format_double_matches_corpus() {
        assert_eq!(format_double(0.8), "0.8");
        assert_eq!(format_double(0.95), "0.95");
        assert_eq!(format_double(0.6), "0.6");
        assert_eq!(format_double(0.85), "0.85");
        assert_eq!(format_double(0.7), "0.7");
        assert_eq!(format_double(0.9), "0.9");
    }

    #[test]
    fn every_edoal_file_matches_committed() {
        let root = repo_root();
        let sets = emit_edoal_sets(&root).expect("emit edoal");
        let dir = root.join("generated").join("projections");
        let mut mismatches: Vec<String> = Vec::new();
        for (filename, text) in &sets {
            let committed_path = dir.join(filename);
            let committed = std::fs::read_to_string(&committed_path)
                .unwrap_or_else(|e| panic!("read {}: {e}", committed_path.display()));
            if *text != committed {
                let first = first_diff(text, &committed);
                mismatches.push(format!("{filename}: {first}"));
            }
        }
        assert!(
            mismatches.is_empty(),
            "{} EDOAL file(s) differ:\n{}",
            mismatches.len(),
            mismatches.join("\n")
        );
        assert_eq!(sets.len(), 45, "expected 45 EDOAL files");
    }

    /// First differing line, got vs want.
    fn first_diff(got: &str, want: &str) -> String {
        for (i, (g, w)) in got.lines().zip(want.lines()).enumerate() {
            if g != w {
                return format!("line {}:\n  got:  {g}\n  want: {w}", i + 1);
            }
        }
        format!(
            "length differs (got {} lines, want {} lines)",
            got.lines().count(),
            want.lines().count()
        )
    }
}
