"""Structural guards for email behavioral metadata: MessageKind, header facets,
and disposition-notification request. Issue #137.
"""

from __future__ import annotations

from pathlib import Path

from purrdf.compat.rdflib import Graph, Literal, URIRef
from purrdf.compat.rdflib.query import ResultRow

from gmeow_tools.graph import load_merged_graph

GMEOW = "https://blackcatinformatics.ca/gmeow/"


def _graph() -> Graph:
    """Load the merged ontology graph without imports."""
    return load_merged_graph(include_imports=False)


def _fixture_path() -> str:
    """Return the path to the email coverage fixture."""
    return str(Path(__file__).parent / "fixtures" / "coverage" / "email.ttl")


def test_fixture_dsn_has_overlapping_kinds() -> None:
    """msgDsn is a bounce, a DSN, and auto-generated — demonstrating overlap."""
    graph = load_merged_graph(include_imports=False)
    graph.parse(_fixture_path(), format="turtle")
    msg_dsn = URIRef("https://example.org/mail/msgDsn")
    kind_dsn = URIRef(GMEOW + "messageKindDeliveryStatusNotification")
    kind_bounce = URIRef(GMEOW + "messageKindBounce")
    kind_auto = URIRef(GMEOW + "messageKindAutoGenerated")
    q = """
    SELECT ?kind WHERE {
        ?msg <https://blackcatinformatics.ca/gmeow/hasMessageKind> ?kind .
    }
    """
    results = list(graph.query(q, initBindings={"msg": msg_dsn}))
    kinds = set()
    for r in results:
        assert isinstance(r, ResultRow)
        kinds.add(str(r[0]))
    assert len(kinds) == 3, f"Expected exactly 3 kinds, found {len(kinds)}"
    assert str(kind_dsn) in kinds
    assert str(kind_bounce) in kinds
    assert str(kind_auto) in kinds


def test_fixture_auto_generated_message() -> None:
    """msgAuto is auto-generated and linked to a SoftwareAgent."""
    graph = load_merged_graph(include_imports=False)
    graph.parse(_fixture_path(), format="turtle")
    msg_auto = URIRef("https://example.org/mail/msgAuto")
    kind_auto = URIRef(GMEOW + "messageKindAutoGenerated")
    assert (msg_auto, URIRef(GMEOW + "hasMessageKind"), kind_auto) in graph
    assert (msg_auto, URIRef(GMEOW + "autoSubmitted"), Literal("auto-replied")) in graph
    assert (msg_auto, URIRef(GMEOW + "precedence"), Literal("bulk")) in graph
    assert (
        msg_auto,
        URIRef(GMEOW + "userAgent"),
        Literal("Microsoft Exchange"),
    ) in graph
    exchange_agent = URIRef("https://example.org/mail/exchangeAgent")
    assert (msg_auto, URIRef(GMEOW + "sentBySoftware"), exchange_agent) in graph


def test_fixture_read_receipt_request() -> None:
    """msg3 requests a read receipt via dispositionNotificationTo."""
    graph = load_merged_graph(include_imports=False)
    graph.parse(_fixture_path(), format="turtle")
    msg3 = URIRef("https://example.org/mail/msg3")
    addr_alice = URIRef("https://example.org/mail/addrAlice")
    assert (msg3, URIRef(GMEOW + "readReceiptRequested"), Literal(True)) in graph
    assert (msg3, URIRef(GMEOW + "dispositionNotificationTo"), addr_alice) in graph
    assert (msg3, URIRef(GMEOW + "priority"), Literal("1")) in graph
    assert (msg3, URIRef(GMEOW + "importance"), Literal("high")) in graph
    assert (
        msg3,
        URIRef(GMEOW + "userAgent"),
        Literal("Mozilla/5.0 (X11; Linux x86_64; rv:128.0) Thunderbird/128.0"),
    ) in graph
