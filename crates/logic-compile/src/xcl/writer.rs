//! The XCL **writer**: [`LogicProgram`] → XCL XML (`generated/cl/gmeow.xcl`).
//!
//! See [`crate::xcl`] for the two-channel architecture. This module emits the idiomatic
//! sentence channel (`rules` + `formulas`) as readable XCL2 elements and the RDF/predication
//! channel (everything else) as canonical N-Triples inside the single
//! `RDF_META_ELEMENT` element.

use gmeow_errors::Diag;

use crate::ir::{Formula, LogicAxiom, LogicProgram, Term};
use crate::nt::nt_escape_literal;
use crate::projections::{ProjectionResult, rdf, target_meta};

use super::{RDF_META_ELEMENT, ROOT_ELEMENT, xml_escape_attr, xml_escape_text};

use purrdf::{SerializeGraph, parse_dataset, serialize_dataset};

/// `xsd:integer` — the datatype emitted for a path shape's integer min/max depths.
const XSD_INTEGER: &str = "http://www.w3.org/2001/XMLSchema#integer";

/// Project a [`LogicProgram`] to XCL XML.
///
/// Returns `Err` if the lossless RDF/predication carrier cannot be built (the
/// canonical-RDF-1.2 projection or its re-serialization failing is an invariant break, not a
/// recoverable condition) — surfacing a structured error to `compile_program` exactly like the
/// sibling projectors, rather than panicking.
pub fn project_xcl(program: &LogicProgram) -> gmeow_errors::Result<ProjectionResult> {
    // Registry is the single source of truth for (preservation, complexity, drops).
    let (kind, cx, _) = target_meta("xcl");

    let mut lines: Vec<String> = vec![
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>".to_owned(),
        "<!-- GENERATED by `gmeow logic compile` - DO NOT EDIT. -->".to_owned(),
        "<!-- XCL (eXtended Common Logic Markup Language) projection of the canonical logic program. -->"
            .to_owned(),
        format!("<{ROOT_ELEMENT}>"),
    ];

    // ── Idiomatic sentence channel (human-readable rendering) ───────────────────
    // Rules and formulas are rendered as readable XCL2 elements. This channel is WRITE-ONLY:
    // the canonical IR carries an `obj_is_literal` bit on a rule term (and a rule's minted
    // reifier-node identity) that idiomatic sentence syntax cannot express, so reconstructing
    // the byte-exact IR from the sentences would be lossy. The lossless carrier is the
    // RDF/predication channel below (the Exact `canonical-rdf12` leg), from which the reader
    // reconstructs the WHOLE program — rules and formulas included. The sentence elements are
    // therefore an idiomatic view over the same content, never the round-trip authority.
    lines.push("  <!-- Rules (idiomatic XCL2 sentences; human-readable view) -->".to_owned());
    lines.push("  <sentences>".to_owned());
    for rule in &program.rules {
        lines.push(format!("    {}", rule_to_xml(rule)));
    }
    for formula in &program.formulas {
        lines.push(format!("    {}", formula_to_xml(formula)));
    }
    lines.push("  </sentences>".to_owned());

    // ── RDF / predication channel (the lossless round-trip carrier): the WHOLE program
    //    — axioms (+ scope), rules, formulas, contracts, correspondences — serialized as
    //    canonical N-Triples inside a single `<gmeow-rdf-meta>` element. ────────────────────
    let meta_nt = meta_ntriples(program)?;
    lines.push(
        "  <!-- RDF/predication channel: canonical N-Triples (round-trip authority). -->"
            .to_owned(),
    );
    if meta_nt.is_empty() {
        lines.push(format!("  <{RDF_META_ELEMENT}></{RDF_META_ELEMENT}>"));
    } else {
        // A leading newline keeps the payload visually distinct; roxmltree preserves it and the
        // reader parses N-Triples line-by-line, so it is round-trip-neutral.
        let body = meta_nt.join("\n");
        lines.push(format!(
            "  <{RDF_META_ELEMENT}>\n{}\n  </{RDF_META_ELEMENT}>",
            xml_escape_text(&body)
        ));
    }

    lines.push(format!("</{ROOT_ELEMENT}>"));

    let content = format!("{}\n", lines.join("\n"));
    Ok(ProjectionResult {
        target: "xcl".to_owned(),
        content,
        is_rdf: false,
        preservation: kind,
        complexity: cx.to_owned(),
        // Exact target: every construct is carried (sentence channel verbatim, RDF channel via
        // the lossless canonical-RDF-1.2 leg). Nothing is dropped, so the writer never touches
        // the loss store — the drop-less row keeps its pure signature.
    })
}

// --------------------------------------------------------------------------- //
// Idiomatic sentence channel — rules
// --------------------------------------------------------------------------- //

/// Encode a [`LogicAxiom`] (a Horn triple) as an XCL2 `<atom>` predication.
fn axiom_atom(axiom: &LogicAxiom) -> String {
    let rel = format!("<name>{}</name>", xml_escape_text(&axiom.predicate));
    let subj = horn_term(&axiom.subject, false);
    let obj = horn_term(&axiom.obj, axiom.obj_is_literal);
    format!("<atom><rel>{rel}</rel><arg>{subj}</arg><arg>{obj}</arg></atom>")
}

/// A Horn subject/object argument: a `?var`, a literal, or a `<name>` IRI.
fn horn_term(value: &str, is_literal: bool) -> String {
    if let Some(var) = value.strip_prefix('?') {
        format!("<var>{}</var>", xml_escape_text(var))
    } else if is_literal {
        // A plain literal in the Horn fragment (the canonical IR carries no datatype on
        // `LogicAxiom.obj`; that detail lives in the RDF channel).
        format!("<literal>{}</literal>", xml_escape_text(value))
    } else {
        format!("<name>{}</name>", xml_escape_text(value))
    }
}

/// Encode a [`crate::ir::LogicRule`] as `<rule><body>…</body><head>…</head></rule>`, or — for
/// the degenerate empty-body rule — the bare head atom (a fact).
fn rule_to_xml(rule: &crate::ir::LogicRule) -> String {
    let head = axiom_atom(&rule.head);

    let mut body_parts: Vec<String> = Vec::new();
    for ba in &rule.body {
        let atom = axiom_atom(ba);
        if ba.negated {
            body_parts.push(format!("<not>{atom}</not>"));
        } else {
            body_parts.push(atom);
        }
    }
    // `distinct_pairs` (a, b) → a negated equality `<not><atom>(= ?a ?b)</atom></not>`.
    for (a, b) in &rule.distinct_pairs {
        body_parts.push(format!(
            "<not><atom><rel><name>=</name></rel><arg>{}</arg><arg>{}</arg></atom></not>",
            var_term(a),
            var_term(b)
        ));
    }

    if body_parts.is_empty() {
        // A fact: emit the head atom alone.
        return head;
    }

    format!(
        "<rule><body>{}</body><head>{head}</head></rule>",
        body_parts.join("")
    )
}

/// Normalize a possibly-`?`-prefixed variable string to an XCL2 `<var>` element.
fn var_term(s: &str) -> String {
    let name = s.strip_prefix('?').unwrap_or(s);
    format!("<var>{}</var>", xml_escape_text(name))
}

// --------------------------------------------------------------------------- //
// Idiomatic sentence channel — formulas
// --------------------------------------------------------------------------- //

/// Encode a [`Formula`] recursively as an XCL2 sentence element.
fn formula_to_xml(formula: &Formula) -> String {
    match formula {
        Formula::Atom { relation, args } => {
            let rel = term_to_xml(relation);
            let mut parts = format!("<rel>{rel}</rel>");
            for a in args {
                parts.push_str(&format!("<arg>{}</arg>", term_to_xml(a)));
            }
            format!("<atom>{parts}</atom>")
        }
        Formula::Not(inner) => format!("<not>{}</not>", formula_to_xml(inner)),
        Formula::And(fs) => {
            let parts: String = fs.iter().map(formula_to_xml).collect();
            format!("<and>{parts}</and>")
        }
        Formula::Or(fs) => {
            let parts: String = fs.iter().map(formula_to_xml).collect();
            format!("<or>{parts}</or>")
        }
        Formula::Implies(a, b) => {
            format!(
                "<implies>{}{}</implies>",
                formula_to_xml(a),
                formula_to_xml(b)
            )
        }
        Formula::Iff(a, b) => {
            format!("<iff>{}{}</iff>", formula_to_xml(a), formula_to_xml(b))
        }
        Formula::Forall { vars, body } => {
            let vs: String = vars
                .iter()
                .map(|v| format!("<var>{}</var>", xml_escape_text(v)))
                .collect();
            format!("<forall><vars>{vs}</vars>{}</forall>", formula_to_xml(body))
        }
        Formula::Exists { vars, body } => {
            let vs: String = vars
                .iter()
                .map(|v| format!("<var>{}</var>", xml_escape_text(v)))
                .collect();
            format!("<exists><vars>{vs}</vars>{}</exists>", formula_to_xml(body))
        }
    }
}

/// Encode a [`Term`] as an XCL2 term element.
fn term_to_xml(term: &Term) -> String {
    match term {
        Term::Var(n) => format!("<var>{}</var>", xml_escape_text(n)),
        Term::Iri(i) => format!("<name>{}</name>", xml_escape_text(i)),
        Term::Literal { lexical, datatype } => match datatype {
            None => format!("<literal>{}</literal>", xml_escape_text(lexical)),
            Some(dt) => format!(
                "<literal datatype=\"{}\">{}</literal>",
                xml_escape_attr(dt),
                xml_escape_text(lexical)
            ),
        },
        Term::SequenceMarker(n) => format!("<seq>{}</seq>", xml_escape_text(n)),
        // A function-term application → an `<app>` element whose head names the function symbol
        // and whose body is the ordered argument terms (each recursively rendered, so a nested
        // application nests its `<app>` elements).
        Term::App { symbol, args } => {
            let inner: String = args.iter().map(term_to_xml).collect();
            format!("<app><name>{}</name>{inner}</app>", xml_escape_text(symbol))
        }
    }
}

